/** Generate the permission table: the infra-level actions each entity permits, with display text and tenancy. See docs/permissions.md. */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { SDK_PACKAGE_ROOT } from "../paths.ts";
import { loadSpec, lowerFirst, type SpecInterface, type SpecModel } from "../spec/spec-model.ts";

/** The channels a run reports on: the console, or a caller's own sink. */
type Output = Pick<Console, "log" | "error">;

/** Where the generated module is written when no `--out` is given. */
const DEFAULT_OUT_FILE = join(SDK_PACKAGE_ROOT, "src/permissions.ts");

const HEADER = "// Generated by scripts/sdk/generate-permissions.ts. Do not edit.";

/** One key of the `PERMISSIONS` value: the entity's camel-cased name and what it permits. */
export interface PermissionEntry {
    key: string;
    /** The entity name split into words, for display. */
    name: string;
    /** The plural noun the action names use. */
    plural: string;
    /** Whether the entity declares `@tenantOwned`. See docs/tenancy.md. */
    tenantOwned: boolean;
    actions: string[];
}

/** The infra actions an entity permits: its repository writes, then its query, then its watch. */
export function entityActions(entity: SpecInterface): string[] {
    const actions: string[] = [...entity.repositoryOperations, ...entity.queries];
    if (entity.watch.length > 0) {
        actions.push("watch");
    }
    return actions;
}

/** One entry for an entity: its key, display names, tenancy, and the actions it permits. */
function permissionEntry(entity: SpecInterface): PermissionEntry {
    return {
        key: lowerFirst(entity.name),
        name: entity.displayName,
        plural: entity.plural,
        tenantOwned: entity.tags.tenantOwned !== undefined,
        actions: entityActions(entity),
    };
}

/** One entry per entity, in the model's name order; the REST declarations expose these actions and add none. */
export function buildPermissionsModel(spec: SpecModel): PermissionEntry[] {
    return [...spec.interfaces.values()].map(permissionEntry);
}

/** The label an action reads, over the plural noun the entity declares. */
export function actionName(action: string, plural: string): string {
    return `${action.charAt(0).toUpperCase()}${action.slice(1)} ${plural}`;
}

/** Render one action's display name. */
function renderAction(lines: string[], action: string, plural: string): void {
    const name = actionName(action, plural);
    lines.push(`            ${JSON.stringify(action)}: { name: ${JSON.stringify(name)} },`);
}

/** Render one entity's entry, with its actions nested so the `tenantOwned` flag is stated once. */
function renderEntry(lines: string[], entry: PermissionEntry): void {
    lines.push(`    ${JSON.stringify(entry.key)}: {`);
    lines.push(`        name: ${JSON.stringify(entry.name)},`);
    lines.push(`        tenantOwned: ${entry.tenantOwned},`);
    if (entry.actions.length === 0) {
        lines.push("        actions: {},");
    } else {
        lines.push("        actions: {");
        for (const action of entry.actions) {
            renderAction(lines, action, entry.plural);
        }
        lines.push("        },");
    }
    lines.push("    },");
}

/** Render the module: one `as const` table keyed by entity, then the types that name it. */
export function renderPermissionsModule(entries: PermissionEntry[]): string {
    const lines: string[] = [HEADER];
    lines.push("/** The infra-level actions each entity permits, keyed by its camel-cased name. */");
    if (entries.length === 0) {
        lines.push("export const PERMISSIONS = {} as const;");
    } else {
        lines.push("export const PERMISSIONS = {");
        for (const entry of entries) {
            renderEntry(lines, entry);
        }
        lines.push("} as const;");
    }
    lines.push("");
    lines.push("/** The type of PERMISSIONS, for naming an entity or an action without a value. */");
    lines.push("export type Permissions = typeof PERMISSIONS;");
    lines.push("");
    lines.push("/** The camel-cased name of an entity in PERMISSIONS. */");
    lines.push("export type PermissionEntity = keyof Permissions;");
    lines.push("");
    lines.push("/** The action an entity permits. */");
    lines.push("export type PermissionAction<E extends PermissionEntity> = keyof Permissions[E][\"actions\"];");
    lines.push("");
    lines.push("/** The entities a tenant scopes, from their `tenantOwned` flag. */");
    lines.push("export type TenantPermissionEntity = {");
    lines.push("    [E in PermissionEntity]: Permissions[E][\"tenantOwned\"] extends true ? E : never;");
    lines.push("}[PermissionEntity];");
    lines.push("");
    lines.push("/** The action a tenant-scoped entity permits. */");
    lines.push(
        "export type TenantPermissionAction<E extends TenantPermissionEntity> = keyof Permissions[E][\"actions\"];",
    );
    lines.push("");
    return lines.join("\n");
}

/** Write the module for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv, output: Output = console): number {
    const outIndex = argv.indexOf("--out");
    const outFile = outIndex === -1 ? DEFAULT_OUT_FILE : argv[outIndex + 1];
    if (!outFile) {
        output.error("--out needs a file");
        return 1;
    }

    const entries = buildPermissionsModel(spec);
    const tenantOwned = entries.filter((entry) => entry.tenantOwned).length;
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, renderPermissionsModule(entries));
    output.log(`wrote ${entries.length} entity permission(s), ${tenantOwned} tenant-owned, to ${outFile}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec(), process.argv);
}
