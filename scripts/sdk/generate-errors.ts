/** Generate one shared error class per `@throws` the spec declares. See docs/errors.md. */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { BUILTIN_ERROR_CLASSES } from "sdk/builtinErrors.ts";
import {
    loadSpec,
    type Diagnostic,
    type SpecLocation,
    type SpecModel,
} from "spec/scripts/spec-model.ts";

export type { Diagnostic };

/** This package's root, so paths do not depend on the current working directory. */
const SDK_PACKAGE_ROOT = dirname(import.meta.dirname);

/** Where the generated module is written when no `--out` is given. */
const DEFAULT_OUT_FILE = join(SDK_PACKAGE_ROOT, "src/specErrors.ts");

/** The hand-written module the generated classes extend; it must stay outside the generated file, so neither imports the other. */
const BASE_MODULE = "./errorBase.ts";

const HEADER = "// Generated by scripts/generate-errors.ts. Do not edit.";

/** The registry type the generated module exports, written out so it imports no generated module back. */
const REGISTRY_TYPE = "Record<string, new (message: string, options?: AppErrorOptions) => AppError>";

/** The status a `@throws` without a `status=` parameter answers with. */
export const DEFAULT_ERROR_STATUS = 400;

/** One error class the generator writes: the tag's name, the wire kind it answers to, and its status. */
export interface GeneratedError {
    /** The class name, as the `@throws` tag wrote it, e.g. `InvoiceDetailsError`. */
    name: string;
    /** The wire kind a client rebuilds from, derived from the class name. */
    kind: string;
    status: number;
    /** The reason the first `@throws` tag gave, which the class doc comment carries. */
    reason: string;
    location: SpecLocation;
}

/** InvoiceDetailsError -> invoice-details: the class name without its suffix, kebab-cased. */
export function errorKind(name: string): string {
    return name
        .replace(/Error$/u, "")
        .replace(/([a-z0-9])([A-Z])/gu, "$1-$2")
        .replace(/([A-Z]+)([A-Z][a-z])/gu, "$1-$2")
        .toLowerCase();
}

/** The class names a `@throws` may not declare, since the hand-written module already answers for them. */
const RESERVED_NAMES: ReadonlySet<string> = new Set(
    Object.values(BUILTIN_ERROR_CLASSES).map((ErrorClass) => ErrorClass.name),
);

/** The kinds the hand-written module already answers for. */
const RESERVED_KINDS: ReadonlySet<string> = new Set(Object.keys(BUILTIN_ERROR_CLASSES));

/** Read the `@throws` declarations of every operation into the classes the module declares. */
export function buildErrorModel(spec: SpecModel): { errors: GeneratedError[]; diagnostics: Diagnostic[] } {
    const diagnostics: Diagnostic[] = [];
    const byName = new Map<string, GeneratedError>();
    const kindOwners = new Map<string, string>();

    for (const error of spec.operations.flatMap((operation) => operation.throws)) {
        const report = (message: string) => {
            diagnostics.push({ filePath: error.location.filePath, line: error.location.line, message });
        };
        if (error.name === "") {
            report("@throws names the error class, as `@throws {InvoiceDetailsError} why`");
            continue;
        }
        if (!/^[A-Z][A-Za-z0-9]*$/u.test(error.name)) {
            report(`@throws \`${error.name}\` is not a class name the generator can declare`);
            continue;
        }
        if (RESERVED_NAMES.has(error.name)) {
            report(`@throws \`${error.name}\` is a built-in error; name the failure's own class`);
            continue;
        }
        const written = error.parameters.get("status");
        if (written !== undefined && !/^\d+$/u.test(written)) {
            report(`@throws \`${error.name}\` names status \`${written}\`; a status is a number, 400 to 599`);
            continue;
        }
        const status = error.status ?? DEFAULT_ERROR_STATUS;
        if (status < 400 || status > 599) {
            report(`@throws \`${error.name}\` names status ${status}; an error status is 400 to 599`);
            continue;
        }
        for (const parameter of error.parameters.keys()) {
            if (parameter !== "status") {
                report(`@throws \`${error.name}\` does not take \`${parameter}=\`; it takes \`status=\``);
            }
        }

        const existing = byName.get(error.name);
        if (existing) {
            if (existing.status !== status) {
                report(`@throws \`${error.name}\` is declared with status ${existing.status} and ${status}`);
            }
            continue;
        }
        const kind = errorKind(error.name);
        if (RESERVED_KINDS.has(kind)) {
            report(`@throws \`${error.name}\` maps to kind \`${kind}\`, which a built-in error already answers for`);
            continue;
        }
        const owner = kindOwners.get(kind);
        if (owner !== undefined) {
            report(`@throws \`${error.name}\` maps to kind \`${kind}\`, which \`${owner}\` already answers for`);
            continue;
        }
        kindOwners.set(kind, error.name);
        byName.set(error.name, { name: error.name, kind, status, reason: error.reason, location: error.location });
    }

    const errors = [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
    return { errors, diagnostics };
}

/** Keep a reason from closing the doc comment it is written into, and read as a sentence. */
function commentText(reason: string): string {
    const text = reason.replace(/\*\//gu, "*\\/").trim();
    const sentence = text.charAt(0).toUpperCase() + text.slice(1);
    return /[.!?]$/u.test(sentence) ? sentence : `${sentence}.`;
}

/** Render the module: one class per error, then the registry the hand-written `errors.ts` merges. */
export function renderErrorModule(errors: GeneratedError[]): string {
    const lines: string[] = [HEADER];
    lines.push(`import { AppError, type AppErrorOptions } from "${BASE_MODULE}";`);
    lines.push("");

    for (const error of errors) {
        lines.push(`/** ${commentText(error.reason === "" ? error.name : error.reason)} */`);
        lines.push(`export class ${error.name} extends AppError {`);
        lines.push("    constructor(message: string, options: AppErrorOptions = {}) {");
        lines.push(`        super(message, { kind: "${error.kind}", status: ${error.status} }, options);`);
        lines.push("    }");
        lines.push("}");
        lines.push("");
    }

    lines.push("/** Every error the spec's `@throws` declares, keyed by the wire kind that rebuilds it. */");
    if (errors.length === 0) {
        lines.push(`export const SPEC_ERROR_CLASSES: ${REGISTRY_TYPE} = {};`);
    } else {
        lines.push(`export const SPEC_ERROR_CLASSES: ${REGISTRY_TYPE} = {`);
        for (const error of errors) {
            lines.push(`    "${error.kind}": ${error.name},`);
        }
        lines.push("};");
    }
    lines.push("");
    return lines.join("\n");
}

/** Write the module for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv): number {
    const { errors, diagnostics } = buildErrorModel(spec);

    if (diagnostics.length > 0) {
        diagnostics.sort((a, b) => a.filePath.localeCompare(b.filePath) || a.line - b.line);
        for (const diagnostic of diagnostics) {
            console.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
        }
        console.error(`\n${diagnostics.length} problem(s) in the spec's @throws tags`);
        return 1;
    }

    const outIndex = argv.indexOf("--out");
    const outFile = outIndex === -1 ? DEFAULT_OUT_FILE : argv[outIndex + 1];
    if (!outFile) {
        console.error("--out needs a file");
        return 1;
    }

    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, renderErrorModule(errors));
    console.log(`wrote ${errors.length} error class(es) to ${outFile}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec());
}
