/** Generate the operation routes the operations package exposes, one route per `@restOperation`. See docs/rest-api.md. */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { OPERATIONS_PACKAGE_ROOT } from "../paths.ts";
import { loadSpec, type SpecModel } from "../spec/spec-model.ts";
import {
    buildRestModel,
    type RestModel,
    type RestOperationCall,
} from "../sdk/rest-model.ts";
import { ROUTES_FILE, filesBelow, groupedName, removeEmptyDirectories } from "./generated-paths.ts";

/** The channels a run reports on: the console, or a caller's own sink. */
type Output = Pick<Console, "log" | "error">;

export type { Diagnostic } from "../sdk/rest-model.ts";

/** Where the route modules are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(OPERATIONS_PACKAGE_ROOT, "src");

const HEADER = "// Generated by scripts/operations/generate-operation-routes.ts. Do not edit.";

/** The export every group's `routes.ts` names its calls by, so the barrel composes them the same way. */
export const OPERATION_ROUTES_EXPORT = "operationRoutes";

/** The package that declares the `Route` type the routes are typed against. */
const ROUTE_TYPE_IMPORT = "infra";

/** The module specifiers of the generated pieces an operation route calls into. */
const SCHEMAS_IMPORT = "sdk/schemas.ts";

/** The distinct guard names a group's routes use, sorted so the imports are stable. */
function guardNames(operations: readonly RestOperationCall[]): string[] {
    return [...new Set(operations.flatMap((operation) => (operation.guardName === undefined ? [] : [operation.guardName])))].sort(
        (a, b) => a.localeCompare(b),
    );
}

/** The service directories with a route, so the barrel imports one `routes.ts` per group; absent is the root group. */
export function routeGroups(model: RestModel): (string | undefined)[] {
    const groups = new Set<string | undefined>(model.operations.map((operation) => operation.topLevelDirectory));
    return [...groups].sort((a, b) => (a ?? "").localeCompare(b ?? ""));
}

/** Render the calls the spec's `@restOperation` tags declare, one route each. */
export function renderOperationRoutes(operations: RestOperationCall[]): string {
    const lines: string[] = [HEADER];
    lines.push(`import { defineRoute, type Route } from "${ROUTE_TYPE_IMPORT}";`);
    if (operations.length > 0) {
        // The module sits beside the operations of its own group, so both imports stay inside the directory.
        for (const operation of operations) {
            lines.push(`import { ${operation.id} } from "./${operation.id}.ts";`);
        }
        for (const name of guardNames(operations)) {
            lines.push(`import { ${name} } from "./guards/${name}.ts";`);
        }
        const schemas = operations
            .flatMap((operation) => (operation.inputSchemaName === undefined ? [] : [operation.inputSchemaName]))
            .sort((a, b) => a.localeCompare(b));
        if (schemas.length > 0) {
            lines.push(`import { ${schemas.join(", ")} } from "${SCHEMAS_IMPORT}";`);
        }
        // A call with no input still validates the decoded argument, which is `undefined` for an empty body.
        if (operations.some((operation) => operation.inputSchemaName === undefined)) {
            lines.push('import { z } from "zod";');
        }
    }

    lines.push("");
    lines.push("/** The calls the spec's `@restOperation` tags expose: each under its id, its verb, and its path. */");
    if (operations.length === 0) {
        lines.push(`export const ${OPERATION_ROUTES_EXPORT}: Route[] = [];`);
        return lines.join("\n") + "\n";
    }
    lines.push(`export const ${OPERATION_ROUTES_EXPORT}: Route[] = [`);
    for (const operation of operations) {
        lines.push("    defineRoute({");
        lines.push(`        id: "${operation.id}",`);
        lines.push(`        method: "${operation.method}",`);
        lines.push(`        path: "${operation.path}",`);
        lines.push(`        source: "${operation.source}",`);
        lines.push(`        input: ${operation.inputSchemaName ?? "z.undefined()"},`);
        if (operation.guardName !== undefined) {
            lines.push(`        guard: ${operation.guardName},`);
        }
        // The context is the one every route receives; an operation that wanted another fails to compile here.
        lines.push(
            operation.inputTypeName === undefined
                ? `        handler: (ctx) => ${operation.id}(ctx),`
                : `        handler: (ctx, body) => ${operation.id}(ctx, body),`,
        );
        lines.push("    }),");
    }
    lines.push("];");

    return lines.join("\n") + "\n";
}

/** Render one `routes.ts` per group, keyed by its path relative to the output root. */
export function renderRouteFiles(model: RestModel): Map<string, string> {
    const files = new Map<string, string>();
    for (const group of routeGroups(model)) {
        const operations = model.operations.filter((operation) => operation.topLevelDirectory === group);
        files.set(groupedName(group, ROUTES_FILE), renderOperationRoutes(operations));
    }
    return files;
}

/** Remove the generated route modules the spec no longer declares, so a dropped group leaves nothing behind. */
function pruneStale(outDir: string, keep: Set<string>): void {
    for (const shown of filesBelow(outDir, ".ts")) {
        if (basename(shown) !== ROUTES_FILE || keep.has(shown)) {
            continue;
        }
        const file = join(outDir, shown);
        if (readFileSync(file, "utf8").split("\n", 1)[0] === HEADER) {
            rmSync(file);
        }
    }
    removeEmptyDirectories(outDir);
}

/** Write the operation route modules for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv, output: Output = console): number {
    const model = buildRestModel(spec);

    for (const diagnostic of model.diagnostics) {
        output.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }
    if (model.diagnostics.length > 0) {
        return 1;
    }

    const outIndex = argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : argv[outIndex + 1];
    if (!outDir) {
        output.error("--out needs a directory");
        return 1;
    }

    const files = renderRouteFiles(model);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        const file = join(outDir, name);
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, content);
    }
    pruneStale(outDir, new Set(files.keys()));
    output.log(`wrote ${files.size} files to ${outDir}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec());
}
