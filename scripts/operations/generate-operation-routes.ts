/** Generate the operation routes and the route table `packages/backend/src/http/routes` serves over infra's entity routes. See docs/rest-api.md. */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BACKEND_PACKAGE_ROOT } from "../paths.ts";
import { loadSpec, type SpecModel } from "../spec/spec-model.ts";
import {
    buildRestModel,
    type RestModel,
    type RestOperationCall,
} from "../sdk/rest-model.ts";

/** The channels a run reports on: the console, or a caller's own sink. */
type Output = Pick<Console, "log" | "error">;

export type { Diagnostic } from "../sdk/rest-model.ts";

/** Where the route modules are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(BACKEND_PACKAGE_ROOT, "src/http/routes");

const HEADER = "// Generated by scripts/backend/generate-operation-routes.ts. Do not edit.";

/** The barrel re-exporting the complete route table. */
const INDEX_FILE = "index.ts";

/** The module holding the operation routes `@restOperation` declares. */
const OPERATION_ROUTES_FILE = "operationRoutes.ts";

/** The export the barrel spreads for the operation routes. */
const OPERATION_ROUTES_EXPORT = "operationRoutes";

/** The export infra's entity route barrel provides. */
const ENTITY_ROUTES_IMPORT = "infra";
const ENTITY_ROUTES_EXPORT = "entityRoutes";

/** The operations directory, relative to the route modules. */
const OPERATION_MODULES_DIR = "../../operations";

/** The module specifiers of the generated pieces an operation route calls into. */
const SCHEMAS_IMPORT = "sdk/schemas.ts";

/** A scaffolded operation module, relative to the route modules: one file per operation. */
function operationImport(id: string): string {
    return `${OPERATION_MODULES_DIR}/${id}.ts`;
}

/** Render the calls the spec's `@restOperation` tags declare, one route each. */
export function renderOperationRoutes(operations: RestOperationCall[]): string {
    const lines: string[] = [HEADER];
    lines.push(`import type { Route } from "${ENTITY_ROUTES_IMPORT}";`);
    if (operations.length > 0) {
        for (const operation of operations) {
            lines.push(`import { ${operation.id} } from "${operationImport(operation.id)}";`);
        }
        const schemas = operations
            .flatMap((operation) => (operation.inputSchemaName === undefined ? [] : [operation.inputSchemaName]))
            .sort((a, b) => a.localeCompare(b));
        const types = [
            ...new Set(
                operations.flatMap((operation) =>
                    operation.inputTypeName === undefined ? [] : [operation.inputTypeName],
                ),
            ),
        ].sort((a, b) => a.localeCompare(b));
        // One import per module: the schemas are values, the type names ride along as type-only specifiers.
        const named = [...schemas, ...types.map((type) => `type ${type}`)];
        if (named.length > 0) {
            lines.push(`import { ${named.join(", ")} } from "${SCHEMAS_IMPORT}";`);
        }
        // A call with no input still validates the decoded argument, which is `undefined` for an empty body.
        if (operations.some((operation) => operation.inputSchemaName === undefined)) {
            lines.push('import { z } from "zod";');
        }
    }

    lines.push("");
    lines.push("/** The calls the spec's `@restOperation` tags expose: each under its id, its verb, and its path. */");
    if (operations.length === 0) {
        lines.push(`export const ${OPERATION_ROUTES_EXPORT}: Route[] = [];`);
        return lines.join("\n") + "\n";
    }
    lines.push(`export const ${OPERATION_ROUTES_EXPORT}: Route[] = [`);
    for (const operation of operations) {
        lines.push("    {");
        lines.push(`        id: "${operation.id}",`);
        lines.push(`        method: "${operation.method}",`);
        lines.push(`        path: "${operation.path}",`);
        lines.push(`        source: "${operation.source}",`);
        lines.push(`        input: ${operation.inputSchemaName ?? "z.undefined()"},`);
        // The context is the one every route receives; an operation that wanted another fails to compile here.
        lines.push(
            operation.inputTypeName === undefined
                ? `        handler: (ctx) => ${operation.id}(ctx),`
                : `        handler: (ctx, body) => ${operation.id}(ctx, body as ${operation.inputTypeName}),`,
        );
        lines.push("    },");
    }
    lines.push("];");

    return lines.join("\n") + "\n";
}

/** Render the barrel that joins infra's entity routes with this package's operation routes. */
export function renderRoutesIndex(model: RestModel): string {
    const lines: string[] = [HEADER];
    lines.push(`import { ${ENTITY_ROUTES_EXPORT}, type Route } from "${ENTITY_ROUTES_IMPORT}";`);
    if (model.operations.length > 0) {
        lines.push(`import { ${OPERATION_ROUTES_EXPORT} } from "./${OPERATION_ROUTES_FILE}";`);
    }

    lines.push("");
    lines.push("/** Every exposed call: id, verb, and path, as the router and the group resolve them. */");
    lines.push("export const routes: Route[] = [");
    lines.push(`    ...${ENTITY_ROUTES_EXPORT},`);
    if (model.operations.length > 0) {
        lines.push(`    ...${OPERATION_ROUTES_EXPORT},`);
    }
    lines.push("];");

    return lines.join("\n") + "\n";
}

/** Render every generated backend route file, keyed by file name (the barrel included). */
export function renderRouteFiles(model: RestModel): Map<string, string> {
    const files = new Map<string, string>();
    // The operation module is written even when it is empty, so a dropped @restOperation leaves no stale route.
    files.set(OPERATION_ROUTES_FILE, renderOperationRoutes(model.operations));
    files.set(INDEX_FILE, renderRoutesIndex(model));
    return files;
}

/** Remove the generated modules the spec no longer declares, so a dropped route leaves nothing behind. */
function pruneStale(outDir: string, keep: Set<string>): void {
    for (const entry of readdirSync(outDir, { withFileTypes: true })) {
        if (!entry.isFile() || !entry.name.endsWith(".ts") || keep.has(entry.name)) {
            continue;
        }
        const file = join(outDir, entry.name);
        if (readFileSync(file, "utf8").split("\n", 1)[0] === HEADER) {
            rmSync(file);
        }
    }
}

/** Write the operation route modules for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv, output: Output = console): number {
    const model = buildRestModel(spec);

    for (const diagnostic of model.diagnostics) {
        output.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }
    if (model.diagnostics.length > 0) {
        return 1;
    }

    const outIndex = argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : argv[outIndex + 1];
    if (!outDir) {
        output.error("--out needs a directory");
        return 1;
    }

    const files = renderRouteFiles(model);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    pruneStale(outDir, new Set(files.keys()));
    output.log(`wrote ${files.size} files to ${outDir}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec());
}
