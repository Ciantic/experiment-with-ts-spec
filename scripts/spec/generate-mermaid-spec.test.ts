import { describe, expect, it } from "vitest";
import { buildRelationships, mermaidName, renderMarkdown, renderMermaid } from "./generate-mermaid-spec.ts";
import { parseInMemorySpec } from "./spec-model.ts";

/** Parse sources into a spec without touching the workspace. */
function parse(files: Record<string, string>) {
    return parseInMemorySpec(
        Object.entries(files).map(([filePath, sourceFileText]) => ({ filePath, sourceFileText })),
    );
}

/** An entity declaration with the fields under test. */
function entity(name: string, fields: string[]): string {
    return `/** @entity */\nexport interface ${name} {\n${fields.join("\n")}\n}`;
}

/** A field with its JSDoc tags, indented the way a spec writes it. */
function field(declaration: string, tags: string[] = []): string {
    if (tags.length === 0) {
        return `    ${declaration};`;
    }
    return `    /**\n${tags.map((tag) => `     * ${tag}`).join("\n")}\n     */\n    ${declaration};`;
}

describe("renderMermaid", () => {
    it("draws an entity with its fields and key markers", () => {
        const spec = parse({
            "/src/Widget.ts": entity("Widget", [
                field("id: string", ["@primaryKey"]),
                field("accountId: string", ["@foreignKey Account"]),
                field("code: string", ["@unique"]),
            ]),
            "/src/Account.ts": entity("Account", [field("id: string", ["@primaryKey"])]),
        });

        const diagram = renderMermaid(spec);

        expect(diagram).toContain("erDiagram");
        expect(diagram).toContain("    Widget {\n        string id PK\n        string accountId FK\n        string code UK\n    }");
    });

    it("renders arrays, unions, and object types as attribute tokens", () => {
        const spec = parse({
            "/src/Widget.ts": entity("Widget", [
                field("rows: WidgetRow[]", ["@children"]),
                field("label?: string | null"),
                field("meta: { count: number }"),
            ]),
            "/src/WidgetRow.ts": entity("WidgetRow", [field("id: string", ["@primaryKey"])]),
        });

        const diagram = renderMermaid(spec);

        expect(diagram).toContain("WidgetRow[] rows");
        expect(diagram).toContain("string_null label");
        expect(diagram).toContain("object meta");
    });
});

describe("buildRelationships", () => {
    it("prefers @relation and @children over the foreign-key column naming the same pair", () => {
        const spec = parse({
            "/src/Widget.ts": entity("Widget", [
                field("accountId?: string", ["@foreignKey Account"]),
                field("account?: Account", ["@relation"]),
                field("rows?: WidgetRow[]", ["@children"]),
            ]),
            "/src/WidgetRow.ts": entity("WidgetRow", [field("widgetId: string", ["@foreignKey Widget"])]),
            "/src/Account.ts": entity("Account", [field("id: string", ["@primaryKey"])]),
        });

        const relationships = buildRelationships(spec);

        expect(relationships).toEqual([
            { from: "Widget", to: "Account", label: "account", fromCardinality: "|o" },
            { from: "Widget", to: "WidgetRow", label: "rows", fromCardinality: "||" },
        ]);
    });

    it("draws a foreign-key column as an edge when the entity declares no relation for it", () => {
        const spec = parse({
            "/src/Widget.ts": entity("Widget", [field("accountId: string", ["@foreignKey Account"])]),
            "/src/Account.ts": entity("Account", [field("id: string", ["@primaryKey"])]),
        });

        expect(buildRelationships(spec)).toEqual([
            { from: "Widget", to: "Account", label: "accountId", fromCardinality: "||" },
        ]);
    });

    it("sorts relationships so the file does not depend on declaration order", () => {
        const spec = parse({
            "/src/Widget.ts": entity("Widget", [
                field("supplierId: string", ["@foreignKey Supplier"]),
                field("accountId: string", ["@foreignKey Account"]),
            ]),
            "/src/Account.ts": entity("Account", [field("id: string", ["@primaryKey"])]),
            "/src/Supplier.ts": entity("Supplier", [field("id: string", ["@primaryKey"])]),
        });

        expect(buildRelationships(spec).map((relationship) => relationship.to)).toEqual(["Account", "Supplier"]);
    });
});

describe("renderMarkdown", () => {
    it("wraps the diagram in a mermaid fenced code block", () => {
        const spec = parse({ "/src/Widget.ts": entity("Widget", [field("id: string", ["@primaryKey"])]) });

        const markdown = renderMarkdown(spec);

        expect(markdown).toContain("```mermaid\n%% Generated by scripts/spec/generate-mermaid-spec.ts");
        expect(markdown).toContain("erDiagram");
        expect(markdown.trimEnd().endsWith("```")).toBe(true);
    });
});

describe("mermaidName", () => {
    it("replaces characters Mermaid does not accept", () => {
        expect(mermaidName("Widget$Row")).toBe("Widget_Row");
    });
});
