/** Draw the spec as a Mermaid ER diagram at the repository root. See docs/spec-annotations.md. */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { REPO_ROOT } from "../paths.ts";
import { loadSpec, type SpecInterface, type SpecModel, type SpecProperty, type SpecType } from "./spec-model.ts";

/** The channels a run reports on: the console, or a caller's own sink. */
type Output = Pick<Console, "log" | "error">;

/** Where the diagram is written when no `--out` is given. */
const DEFAULT_OUT_FILE = join(REPO_ROOT, "spec.md");

const HEADER = "%% Generated by scripts/spec/generate-mermaid-spec.ts. Do not edit.";

/** One relationship drawn between two entities. */
export interface MermaidRelationship {
    /** The entity that declares the field. */
    from: string;
    /** The entity the field points at. */
    to: string;
    /** The field name, which labels the edge. */
    label: string;
    /** The cardinality on the `from` side: zero-or-one for an optional field, exactly-one otherwise. */
    fromCardinality: "|o" | "||";
}

/** Keep an identifier to the characters Mermaid accepts. */
export function mermaidName(name: string): string {
    return name.replace(/[^A-Za-z0-9_]/gu, "_");
}

/** Render a field type as a single Mermaid attribute token, keeping array suffixes. */
function mermaidType(type: SpecType): string {
    switch (type.kind) {
        case "keyword":
        case "reference":
            return mermaidName(type.name);
        case "array":
            return `${mermaidType(type.element)}[]`;
        case "union":
        case "intersection":
            return type.members.map(mermaidType).join("_");
        case "object":
            return "object";
        case "stringLiteral":
            return "string";
        case "numberLiteral":
            return "number";
        case "missing":
        case "unknown":
            return mermaidName(type.kind === "unknown" ? type.text : "") || "unknown";
    }
}

/** The Mermaid key markers a field carries: a primary key, a foreign-key column, or a unique column. */
function mermaidKeys(property: SpecProperty): string {
    const keys: string[] = [];
    if (property.tags.primaryKey) {
        keys.push("PK");
    }
    if (property.tags.foreignKey !== undefined) {
        keys.push("FK");
    }
    if (property.tags.unique) {
        keys.push("UK");
    }
    return keys.length === 0 ? "" : ` ${keys.join(", ")}`;
}

/** Render one entity block with its fields in declaration order. */
function renderEntity(entity: SpecInterface): string[] {
    const lines = [`    ${mermaidName(entity.name)} {`];
    for (const property of entity.properties) {
        lines.push(`        ${mermaidType(property.type)} ${mermaidName(property.name)}${mermaidKeys(property)}`);
    }
    lines.push("    }");
    return lines;
}

/** The entity a field points at, looking through arrays and unions, when the spec declares one. */
function referencedEntity(type: SpecType, entities: ReadonlySet<string>): string | undefined {
    switch (type.kind) {
        case "reference":
            return entities.has(type.name) ? type.name : undefined;
        case "array":
            return referencedEntity(type.element, entities);
        case "union": {
            for (const member of type.members) {
                const found = referencedEntity(member, entities);
                if (found !== undefined) {
                    return found;
                }
            }
            return undefined;
        }
        default:
            return undefined;
    }
}

/** Collect one edge per entity pair, preferring `@relation`, `@children`, and `@inlined` over a plain `@foreignKey`. */
export function buildRelationships(spec: SpecModel): MermaidRelationship[] {
    const entities = new Set(spec.interfaces.keys());
    const seen = new Set<string>();
    const relationships: MermaidRelationship[] = [];
    const pairKey = (a: string, b: string) => [a, b].sort().join("\u0000");

    for (const entity of spec.interfaces.values()) {
        for (const property of entity.properties) {
            const tags = property.tags;
            if (!tags.relation && !tags.children && !tags.inlined) {
                continue;
            }
            const target = referencedEntity(property.type, entities);
            if (target === undefined || target === entity.name) {
                continue;
            }
            const key = pairKey(entity.name, target);
            if (seen.has(key)) {
                continue;
            }
            seen.add(key);
            const optional = (tags.relation || tags.inlined) && property.optional;
            relationships.push({
                from: entity.name,
                to: target,
                label: property.name,
                fromCardinality: optional ? "|o" : "||",
            });
        }
    }

    for (const entity of spec.interfaces.values()) {
        for (const property of entity.properties) {
            const foreignKey = property.tags.foreignKey;
            if (foreignKey === undefined || !entities.has(foreignKey.entity)) {
                continue;
            }
            const key = pairKey(entity.name, foreignKey.entity);
            if (seen.has(key)) {
                continue;
            }
            seen.add(key);
            relationships.push({
                from: entity.name,
                to: foreignKey.entity,
                label: property.name,
                fromCardinality: property.optional ? "|o" : "||",
            });
        }
    }

    return relationships.sort(
        (a, b) => a.from.localeCompare(b.from) || a.to.localeCompare(b.to) || a.label.localeCompare(b.label),
    );
}

/** Render the whole spec as an ER diagram; entities and edges are sorted so the file is deterministic. */
export function renderMermaid(spec: SpecModel): string {
    const lines = [HEADER, "erDiagram"];
    const entities = [...spec.interfaces.values()].sort((a, b) => a.name.localeCompare(b.name));
    for (const entity of entities) {
        lines.push(...renderEntity(entity));
        lines.push("");
    }
    for (const relationship of buildRelationships(spec)) {
        const from = mermaidName(relationship.from);
        const to = mermaidName(relationship.to);
        lines.push(`    ${from} ${relationship.fromCardinality}--o{ ${to} : "${relationship.label}"`);
    }
    return `${lines.join("\n").trimEnd()}\n`;
}

/** Wrap the diagram in a Markdown document so GitHub renders the ER diagram. */
export function renderMarkdown(spec: SpecModel): string {
    return ["# Spec", "", "```mermaid", renderMermaid(spec).trimEnd(), "```", ""].join("\n");
}

/** Write the diagram for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv, output: Output = console): number {
    const outIndex = argv.indexOf("--out");
    const outFile = outIndex === -1 ? DEFAULT_OUT_FILE : argv[outIndex + 1];
    if (!outFile) {
        output.error("--out needs a file");
        return 1;
    }

    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, renderMarkdown(spec));
    output.log(`wrote ${spec.interfaces.size} entity/entities to ${outFile}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec());
}
