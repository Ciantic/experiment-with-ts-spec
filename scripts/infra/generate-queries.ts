/** Generate the per-entity `query` functions and the query metadata module from the spec entities. See docs/queries.md. */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { INFRA_PACKAGE_ROOT } from "../paths.ts";
import { TRIGGER_EVENTS, loadSpec, lowerFirst, type DeclaredType, type FilterDefault, type SpecModel, type TriggerEvent } from "../spec/spec-model.ts";
import {
    buildSpecTables,
    primaryKeyColumns,
    type Table,
} from "./postgres-model.ts";

/** The channels a run reports on: the console, or a caller's own sink. */
type Output = Pick<Console, "log" | "error">;

/** Where the generated modules are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(INFRA_PACKAGE_ROOT, "src/db/queries");

const HEADER = "// Generated by scripts/infra/generate-queries.ts. Do not edit.";

/** The model file name, next to the per-entity query modules. */
const MODEL_FILE = "model.ts";

/** The barrel re-exporting the model and every query module. */
const INDEX_FILE = "index.ts";

/** QueryTable as plain data, matching the resolver's `QueryTable`. */
interface QueryTableData {
    name: string;
    key: string;
    fields: Record<string, string>;
    relations: Record<string, Record<string, unknown>>;
    requiredFilters?: string[];
    order?: string[];
    defaultOrder?: { field: string; direction: string };
    where?: Record<string, string[]>;
    filterDefaults?: Record<string, FilterDefault>;
}

/** QueryModel as plain data, matching the resolver's `QueryModel`. */
interface QueryModelData {
    tables: Record<string, QueryTableData>;
}

/** The module file for an entity's read, e.g. `Invoice` -> `queryInvoice.ts`. */
function queryFileName(entity: string): string {
    return `query${entity}.ts`;
}

/** The module file for an entity's row-scoped change stream, e.g. `Invoice` -> `watchInvoice.ts`. */
function watchFileName(entity: string): string {
    return `watch${entity}.ts`;
}

/** The module file for an entity's tenant lookup, e.g. `Invoice` -> `getInvoiceTenants.ts`. */
function tenantsFileName(entity: string): string {
    return `${tenantsFunctionName(entity)}.ts`;
}

/** The tenant lookup's function name, e.g. `getInvoiceTenants`. See docs/permissions.md. */
export function tenantsFunctionName(entity: string): string {
    return `get${entity}Tenants`;
}

/** Map the table model to the resolver's metadata: scalar fields plus branch descriptors. */
export function buildQueryModel(tables: Map<string, Table>): QueryModelData {
    const out: Record<string, QueryTableData> = {};
    for (const table of tables.values()) {
        // Inlined columns are reached through their branch; a relation's foreign key stays selectable.
        const branchColumns = new Set<string>();
        for (const relation of table.relations.values()) {
            if (relation.kind === "inlined") {
                for (const column of Object.values(relation.columns ?? {})) {
                    branchColumns.add(column);
                }
            }
        }

        const fields: Record<string, string> = {};
        for (const column of table.columns) {
            if (!branchColumns.has(column.name)) {
                fields[column.name] = column.name;
            }
        }

        const relations: Record<string, Record<string, unknown>> = {};
        for (const [field, relation] of table.relations) {
            relations[field] =
                relation.kind === "inlined"
                    ? { kind: relation.kind, columns: relation.columns }
                    : { kind: relation.kind, table: relation.table, column: relation.column };
        }

        // A composite key is root-only, so the first key column only aliases the row. See docs/queries.md.
        const key = primaryKeyColumns(table)[0]?.name as string;
        const data: QueryTableData = { name: table.name, key, fields, relations };

        // A required filter is an invariant rather than a typing nicety, so the resolver reads it too.
        const requiredFilters = requiredFilterFields(table);
        if (requiredFilters.length > 0) {
            data.requiredFilters = requiredFilters;
        }

        // Orderable fields come from `@queryOrderBy`; one may declare the entity default ordering.
        const orderColumns = table.columns.filter((column) => column.queryOrder !== undefined);
        if (orderColumns.length > 0) {
            data.order = orderColumns.map((column) => column.name);
            const defaultColumn = orderColumns.find((column) => column.queryOrder?.default !== undefined);
            const direction = defaultColumn?.queryOrder?.default;
            if (defaultColumn && direction) {
                data.defaultOrder = { field: defaultColumn.name, direction };
            }
        }

        // Comparable fields come from `@queryWhere`, each with the operators it whitelists.
        const whereColumns = table.columns.filter((column) => column.where !== undefined);
        if (whereColumns.length > 0) {
            data.where = Object.fromEntries(whereColumns.map((column) => [column.name, column.where ?? []]));
        }

        // A defaulted filter is applied when a read leaves it out, so the resolver reads the value too.
        const filterDefaults: Record<string, FilterDefault> = {};
        for (const column of table.columns) {
            const fallback = column.queryFilter?.default;
            if (fallback !== undefined) {
                filterDefaults[column.name] = fallback;
            }
        }
        if (Object.keys(filterDefaults).length > 0) {
            data.filterDefaults = filterDefaults;
        }

        out[table.name] = data;
    }
    return { tables: out };
}

/** Render the metadata module the resolver is constructed with. */
export function renderQueryModelModule(model: QueryModelData): string {
    const lines: string[] = [HEADER];
    lines.push('import type { QueryModel } from "../resolvers.ts";');
    lines.push("");
    lines.push(`export const queryModel: QueryModel = ${JSON.stringify(model, null, 4)};`);
    return lines.join("\n") + "\n";
}

/** The field names an entity exposes as filters: its `@queryFilter` scalar columns. */
function filterFields(table: Table): string[] {
    return table.columns.filter((column) => column.queryFilter !== undefined).map((column) => column.name);
}

/** The filter fields every read must name: its `@queryFilter required` columns. */
function requiredFilterFields(table: Table): string[] {
    return table.columns.filter((column) => column.queryFilter?.required).map((column) => column.name);
}

/** The field names an entity exposes as ordering keys: its `@queryOrderBy` scalar columns. */
function orderFields(table: Table): string[] {
    return table.columns.filter((column) => column.queryOrder !== undefined).map((column) => column.name);
}

/** The comparable fields with their allowed operators: its `@queryWhere` scalar columns. */
function whereFields(table: Table): { name: string; operators: string[] }[] {
    return table.columns
        .filter((column) => column.where !== undefined)
        .map((column) => ({ name: column.name, operators: column.where ?? [] }));
}

/** Invoice -> `"id" | "number"`. */
function filterKeys(filters: string[]): string {
    return filters.map((name) => JSON.stringify(name)).join(" | ");
}

/** `Where<Invoice, { issueDate: "gte" | "lte" }>`. */
function whereType(entity: string, fields: { name: string; operators: string[] }[]): string {
    const entries = fields.map((field) => `${field.name}: ${filterKeys(field.operators)}`);
    return `Where<${entity}, { ${entries.join("; ")} }>`;
}

/** Render one entity's query function. */
export function renderQueryModule(entity: string, table: Table): string {
    const filters = filterFields(table);
    const required = requiredFilterFields(table);
    const order = orderFields(table);
    const where = whereFields(table);
    const lines: string[] = [HEADER];
    lines.push(`import type { ${entity} } from "${table.importSpecifier}";`);
    const selectionTypes = ["Selection", "Selected"];
    if (filters.length > 0) {
        selectionTypes.push("Filters");
    }
    if (order.length > 0) {
        selectionTypes.push("Order");
    }
    if (where.length > 0) {
        selectionTypes.push("Where");
    }
    selectionTypes.sort((a, b) => a.localeCompare(b));
    lines.push(`import type { ${selectionTypes.join(", ")} } from "sdk/selection.ts";`);
    lines.push('import type { SqlExecutor } from "../sql-executor.ts";');
    lines.push('import { createResolver } from "../resolvers.ts";');
    lines.push('import { queryModel } from "./model.ts";');
    lines.push("");
    lines.push("const resolver = createResolver(queryModel);");
    lines.push("");
    lines.push(`/** Query \`${entity}\` rows, filtered by the \`@queryFilter\` fields, combined with and. */`);
    lines.push(
        `export function query${entity}<S extends Selection<${entity}>>(db: SqlExecutor, opts: ${queryOptsType(entity, filters, required, order, where)}): Promise<Selected<${entity}, S>[]> {`,
    );
    const resolverOpts =
        (order.length > 0 ? "order: opts.order, " : "") +
        (where.length > 0 ? "where: opts.where, " : "") +
        "limit: opts.limit, offset: opts.offset";
    lines.push(
        `    return resolver.resolveMany<${entity}, S>(db, ${JSON.stringify(table.name)}, ${queryArgs(filters)}, { select: opts.select, ${resolverOpts} });`,
    );
    lines.push("}");
    return lines.join("\n") + "\n";
}

/** The `query` options: a filter, ordering, comparisons, and paging, plus the selection. */
function queryOptsType(
    entity: string,
    filters: string[],
    required: string[],
    order: string[],
    where: { name: string; operators: string[] }[],
): string {
    const parts: string[] = [];
    if (filters.length > 0) {
        // A required filter makes the whole object mandatory: `filter` may not be left out when it holds one.
        const keys = required.length > 0 ? `${filterKeys(filters)}, ${filterKeys(required)}` : filterKeys(filters);
        parts.push(`${required.length > 0 ? "filter" : "filter?"}: Filters<${entity}, ${keys}>`);
    }
    if (order.length > 0) {
        parts.push(`order?: Order<${filterKeys(order)}>[]`);
    }
    if (where.length > 0) {
        parts.push(`where?: ${whereType(entity, where)}`);
    }
    // Every read pages: `limit` defaults to the resolver's cap, `offset` to 0.
    parts.push("limit?: number", "offset?: number", "select: S");
    return `{ ${parts.join("; ")} }`;
}

/** The filter object handed to the resolver: the caller's, or an empty one when the entity has none. */
function queryArgs(filters: string[]): string {
    return filters.length > 0 ? "opts.filter ?? {}" : "{}";
}

/** The filter object a generated watch takes: the fields its scope tag declares. */
function watchFilterType(entity: string, filters: string[]): string | undefined {
    return filters.length === 0
        ? undefined
        : `WatchFilter<${entity}, ${filters.map((field) => JSON.stringify(field)).join(" | ")}>`;
}

/** The uppercase union of the operations a scope publishes; undefined when it publishes all three. */
function operationUnion(ops: readonly TriggerEvent[]): string | undefined {
    return ops.length === 0 || ops.length === TRIGGER_EVENTS.length
        ? undefined
        : ops.map((op) => JSON.stringify(op.toUpperCase())).join(" | ");
}

/** A readonly array of one union, parenthesized only when it has more than one member. */
function readonlyOperations(union: string): string {
    return union.includes(" | ") ? `readonly (${union})[]` : `readonly ${union}[]`;
}

/** The options a generated watch takes: `pks` only on the rows helper, `filter` only when its scope declares one. */
function watchOptsType(keyType: string, pks: boolean, entity: string, filters: string[], union: string | undefined): string {
    const parts: string[] = [];
    if (pks) {
        parts.push(`pks: ${keyType}[]`);
    }
    const filter = watchFilterType(entity, filters);
    if (filter !== undefined) {
        parts.push(`filter?: ${filter} | undefined`);
    }
    parts.push(union === undefined ? "ops?: readonly WatchOperation[] | undefined" : `ops?: ${readonlyOperations(union)} | undefined`, "signal?: AbortSignal");
    return `{ ${parts.join("; ")} }`;
}

/** Render one entity's change streams: `watch<Entity>` for the table and `watch<Entity>Rows` for keys. */
export function renderWatchModule(entity: string, table: Table): string {
    const keyType = `${entity}PrimaryKey`;
    const allWatch = table.watchAll;
    const rowsWatch = table.watchRows;
    const all = allWatch !== undefined;
    const rows = rowsWatch !== undefined;
    const allUnion = allWatch === undefined ? undefined : operationUnion(allWatch.ops);
    const rowsUnion = rowsWatch === undefined ? undefined : operationUnion(rowsWatch.ops);
    const allEvent = allUnion === undefined ? "WatchAllEvent" : `WatchAllEvent<${allUnion}>`;
    const rowsEvent = rowsUnion === undefined ? `WatchRowsEvent<${keyType}>` : `WatchRowsEvent<${keyType}, ${rowsUnion}>`;
    const fields = rows ? primaryKeyColumns(table).map((column) => column.name) : [];
    const lines: string[] = [HEADER];
    if (rows) {
        lines.push(`import type { ${keyType} } from "sdk/schemas.ts";`);
    }
    if ((allWatch?.filters.length ?? 0) > 0 || (rowsWatch?.filters.length ?? 0) > 0) {
        lines.push(`import type { ${entity} } from "${table.importSpecifier}";`);
    }
    const watchTypes = all ? ["WatchAllEvent"] : [];
    if (rows) {
        watchTypes.push("WatchRowsEvent");
    }
    if (allUnion === undefined || rowsUnion === undefined) {
        if ((all && allUnion === undefined) || (rows && rowsUnion === undefined)) {
            watchTypes.push("WatchOperation");
        }
    }
    if ((allWatch?.filters.length ?? 0) > 0 || (rowsWatch?.filters.length ?? 0) > 0) {
        watchTypes.push("WatchFilter");
    }
    watchTypes.sort((a, b) => a.localeCompare(b));
    lines.push(`import type { ${watchTypes.join(", ")} } from "sdk/watch.ts";`);
    lines.push('import type { SqlExecutor } from "../sql-executor.ts";');
    const functions = [rows ? "watchRows" : "", all ? "watchAll" : ""].filter(Boolean).sort();
    lines.push(`import { ${functions.join(", ")} } from "../notifications.ts";`);
    lines.push("");

    if (allWatch !== undefined) {
        const allFilters = allWatch.filters;
        const optionalFilterArg = allFilters.length > 0 ? ", opts?.filter" : "";
        lines.push(`/** Subscribe to changes of \`${entity}\`, optionally scoped to operations${allFilters.length > 0 ? " and filter values" : ""}. See docs/notifications.md. */`);
        lines.push(`export function watch${entity}(`);
        lines.push("    db: SqlExecutor,");
        lines.push(`    opts?: ${watchOptsType(keyType, false, entity, allFilters, allUnion)},`);
        lines.push(`): AsyncIterable<${allEvent}> {`);
        lines.push(`    return watchAll(db, ${JSON.stringify(allWatch.channel)}, opts?.ops, opts?.signal${optionalFilterArg})${allUnion === undefined ? "" : ` as AsyncIterable<${allEvent}>`};`);
        lines.push("}");
    }

    if (rowsWatch !== undefined) {
        const rowFilters = rowsWatch.filters;
        const filterArg = rowFilters.length > 0 ? ", opts.filter" : "";
        if (all) {
            lines.push("");
        }
        lines.push(`/** Subscribe to changes of the selected \`${entity}\` rows, optionally scoped to operations${rowFilters.length > 0 ? " and filter values" : ""}. See docs/notifications.md. */`);
        lines.push(`export function watch${entity}Rows(`);
        lines.push("    db: SqlExecutor,");
        lines.push(`    opts: ${watchOptsType(keyType, true, entity, rowFilters, rowsUnion)},`);
        lines.push(`): AsyncIterable<${rowsEvent}> {`);
        lines.push(
            `    return watchRows(db, ${JSON.stringify(rowsWatch.channel)}, opts.pks, ${JSON.stringify(fields)}, opts.ops, opts.signal${filterArg})${rowsUnion === undefined ? "" : ` as AsyncIterable<${rowsEvent}>`};`,
        );
        lines.push("}");
    }
    return lines.join("\n") + "\n";
}

/** Render one entity's tenant lookup: the distinct tenants the named rows belong to. See docs/permissions.md. */
export function renderTenantsModule(table: Table, declared?: DeclaredType): string {
    const module = lowerFirst(table.interfaceName);
    const owned = table.tenantOwned;
    const tenant = owned?.field as string;
    const nullable = owned?.optional === true;
    const keys = primaryKeyColumns(table);
    // The spec's tenant key type names the column, so the lookup does not index the entity.
    const tenantType = declared?.name ?? `${table.interfaceName}[${JSON.stringify(tenant)}]`;
    const returnedElement = nullable ? `${tenantType} | null` : tenantType;
    const returnedType = nullable ? `(${tenantType} | null)[]` : `${tenantType}[]`;
    const keyType = `${table.interfaceName}PrimaryKey`;
    const lines: string[] = [HEADER];
    if (declared?.importSpecifier !== undefined) {
        lines.push(`import type { ${declared.name} } from "${declared.importSpecifier}";`);
    } else if (declared === undefined) {
        lines.push(`import type { ${table.interfaceName} } from "${table.importSpecifier}";`);
    }
    lines.push(`import type { ${keyType} } from "sdk/repositories/${module}PrimaryKeySchema.ts";`);
    lines.push('import type { SqlExecutor } from "../sql-executor.ts";');
    lines.push("");
    lines.push(
        nullable
            ? `/** The distinct tenants the named \`${table.name}\` rows belong to, with \`null\` for a row that has none. */`
            : `/** The distinct tenants the named \`${table.name}\` rows belong to, read on the caller's executor. */`,
    );
    lines.push(
        `export async function ${tenantsFunctionName(table.interfaceName)}(db: SqlExecutor, pks: readonly ${keyType}[]): Promise<${returnedType}> {`,
    );
    lines.push("    if (pks.length === 0) {");
    lines.push("        return [];");
    lines.push("    }");
    // One array parameter per key column keeps the statement fixed however many keys the call names.
    const parameters = keys.length === 1
        ? `[pks.map((key) => key.${keys[0]?.name as string})]`
        : `[${keys.map((key) => `pks.map((row) => row.${key.name})`).join(", ")}]`;
    const where = keys.length === 1
        ? `"${keys[0]?.name as string}" = any($1)`
        : `(${keys.map((key) => `"${key.name}"`).join(", ")}) in (select * from unnest(${keys.map((key, index) => `$${index + 1}::${key.sqlType}[]`).join(", ")}))`;
    const sql = `'select distinct "${tenant}" as "tenant" from "${table.name}" where ${where}'`;
    lines.push(`    const result = await db.query<{ tenant: ${returnedElement} }>(`);
    lines.push(`        ${sql},`);
    lines.push(`        ${parameters},`);
    lines.push("    );");
    lines.push("    return result.rows.map((row) => row.tenant);");
    lines.push("}");
    return lines.join("\n") + "\n";
}

/** Render every generated file, keyed by file name (including the barrel). */
export function generateQueries(tables: Map<string, Table>, declared?: DeclaredType): Map<string, string> {
    const entities = [...tables.values()].sort((a, b) => a.interfaceName.localeCompare(b.interfaceName));

    const files = new Map<string, string>();
    // The model names every table, since a read may navigate into one that has no read of its own.
    files.set(MODEL_FILE, renderQueryModelModule(buildQueryModel(tables)));
    for (const table of entities) {
        if (table.queries.includes("query")) {
            files.set(queryFileName(table.interfaceName), renderQueryModule(table.interfaceName, table));
        }
        if (table.watchAll !== undefined || table.watchRows !== undefined) {
            files.set(watchFileName(table.interfaceName), renderWatchModule(table.interfaceName, table));
        }
        if (table.tenantOwned !== undefined) {
            files.set(tenantsFileName(table.interfaceName), renderTenantsModule(table, declared));
        }
    }

    const lines = [HEADER, `export * from "./${MODEL_FILE}";`];
    for (const table of entities) {
        if (table.queries.includes("query")) {
            lines.push(`export * from "./${queryFileName(table.interfaceName)}";`);
        }
        if (table.watchAll !== undefined || table.watchRows !== undefined) {
            lines.push(`export * from "./${watchFileName(table.interfaceName)}";`);
        }
        if (table.tenantOwned !== undefined) {
            lines.push(`export * from "./${tenantsFileName(table.interfaceName)}";`);
        }
    }
    files.set(INDEX_FILE, lines.join("\n") + "\n");
    return files;
}

/** Remove the generated modules the spec no longer declares, so an entity that drops a read leaves no file. */
function pruneStale(outDir: string, keep: Set<string>): void {
    for (const entry of readdirSync(outDir, { withFileTypes: true })) {
        if (!entry.isFile() || !entry.name.endsWith(".ts") || keep.has(entry.name)) {
            continue;
        }
        const file = join(outDir, entry.name);
        if (readFileSync(file, "utf8").split("\n", 1)[0] === HEADER) {
            rmSync(file);
        }
    }
}

/** Write the query modules for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv, output: Output = console): number {
    const { tables, diagnostics } = buildSpecTables(spec);

    for (const diagnostic of diagnostics) {
        output.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }
    if (diagnostics.length > 0) {
        return 1;
    }

    const outIndex = argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : argv[outIndex + 1];
    if (!outDir) {
        output.error("--out needs a directory");
        return 1;
    }

    const files = generateQueries(tables, spec.tenantIdType);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    pruneStale(outDir, new Set(files.keys()));
    output.log(`wrote ${files.size} files to ${outDir}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec());
}
