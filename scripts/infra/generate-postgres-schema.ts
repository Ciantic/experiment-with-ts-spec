/** Generate Postgres DDL from the spec entities. See docs/schema-generation.md. */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { INFRA_PACKAGE_ROOT } from "../paths.ts";
import { SPEC_GLOB, loadSpec, type ReferentialAction, type SpecModel } from "../spec/spec-model.ts";
import {
    buildSpecTables,
    quote,
    type Column,
    type Diagnostic,
    type Table,
    type Trigger,
} from "./postgres-model.ts";

/** The channels a run reports on: the console, or a caller's own sink. */
type Output = Pick<Console, "log" | "error">;

/** The SQL clause each `@foreignKey` action maps to. */
const REFERENTIAL_ACTION_SQL: Record<ReferentialAction, string> = {
    cascade: "cascade",
    restrict: "restrict",
    noAction: "no action",
    setNull: "set null",
    setDefault: "set default",
};

export type { Diagnostic } from "./postgres-model.ts";

/** Where the DDL is written when no `--out` is given. */
const DEFAULT_OUT = join(INFRA_PACKAGE_ROOT, "src/postgres/schema.sql");

/** Emit tables so that referenced tables come first. */
function orderTables(tables: Map<string, Table>, diagnostics: Diagnostic[], sourceGlob: string): Table[] {
    const remaining = [...tables.values()];
    const emitted = new Map<string, Table>();
    const ordered: Table[] = [];

    while (remaining.length > 0) {
        const ready = remaining.filter((table) =>
            table.columns.every(
                (column) => !column.references || emitted.has(column.references.table),
            ),
        );
        if (ready.length === 0) {
            diagnostics.push({
                filePath: sourceGlob,
                line: 1,
                message: `circular foreign keys among: ${remaining.map((table) => table.name).join(", ")}`,
            });
            ordered.push(...remaining);
            break;
        }
        for (const table of ready) {
            ordered.push(table);
            emitted.set(table.name, table);
            remaining.splice(remaining.indexOf(table), 1);
        }
    }

    return ordered;
}

/** Render a table's `create table` and its constraints; a test fixture is built from it, so it cannot drift from `schema.sql`. */
export function renderCreateTable(table: Table): string[] {
    const lines: string[] = [`create table ${quote(table.name)} (`];
    const parts: string[] = [];

    for (const column of table.columns) {
        let part = `    ${quote(column.name)} ${column.sqlType}`;
        if (column.generatedExpression !== undefined) {
            part += ` generated always as (${column.generatedExpression}) virtual`;
        }
        // An identity column owns its sequence. `by default` leaves an explicit value in the upsert's insert legal.
        if (column.identity) {
            part += " generated by default as identity";
        }
        if (column.notNull) {
            part += " not null";
        }
        if (column.default) {
            part += ` default ${column.default}`;
        }
        // A scoped reference is composite, so it is a table constraint rather than an inline one.
        if (column.references && column.references.scope === undefined) {
            part += ` references ${quote(column.references.table)}(${quote(column.references.column)})`;
            if (column.references.onDelete !== undefined) {
                part += ` on delete ${REFERENTIAL_ACTION_SQL[column.references.onDelete]}`;
            }
            if (column.references.onUpdate !== undefined) {
                part += ` on update ${REFERENTIAL_ACTION_SQL[column.references.onUpdate]}`;
            }
        }
        if (column.unique) {
            part += " unique";
        }
        parts.push(part);
    }

    // A table with no key column is already a diagnostic; emitting `primary key ()` would be invalid DDL.
    const primaryKeys = table.columns.filter((column) => column.primaryKey).map((column) => quote(column.name));
    if (primaryKeys.length > 0) {
        parts.push(`    constraint ${quote(`${table.name}_pkey`)} primary key (${primaryKeys.join(", ")})`);
    }

    // A scoped reference constrains the pair `(scope, key)`, so it names both columns on both sides.
    for (const column of table.columns) {
        const reference = column.references;
        if (reference?.scope === undefined) {
            continue;
        }
        const columns = [reference.scope, column.name].map(quote).join(", ");
        const target = [reference.scope, reference.column].map(quote).join(", ");
        let clause = `    constraint ${quote(`${table.name}_${reference.scope}_${column.name}_fkey`)} foreign key (${columns}) references ${quote(reference.table)} (${target})`;
        if (reference.onDelete !== undefined) {
            clause += ` on delete ${REFERENTIAL_ACTION_SQL[reference.onDelete]}`;
        }
        if (reference.onUpdate !== undefined) {
            clause += ` on update ${REFERENTIAL_ACTION_SQL[reference.onUpdate]}`;
        }
        parts.push(clause);
    }

    // The pair a scoped reference matches has to be unique on the target, or the constraint cannot exist.
    for (const unique of table.uniqueConstraints ?? []) {
        parts.push(
            `    constraint ${quote(`${table.name}_${unique.join("_")}_key`)} unique (${unique.map(quote).join(", ")})`,
        );
    }

    for (const column of table.columns) {
        if (!column.checkValues || column.checkValues.length === 0) {
            continue;
        }
        const values = column.checkValues.map((value) => `'${value.replace(/'/g, "''")}'`).join(", ");
        parts.push(
            `    constraint ${quote(`${table.name}_${column.name}_check`)} check (${quote(column.name)} in (${values}))`,
        );
    }

    lines.push(parts.join(",\n"));
    lines.push(");");
    return lines;
}

/** The name of a trigger and its function; the shared row-level before insert or update shape keeps `_compute`. */
function triggerName(table: Table, trigger: Trigger): string {
    if (
        trigger.level === "row" &&
        trigger.timing === "before" &&
        trigger.events.length === 2 &&
        trigger.events[0] === "insert" &&
        trigger.events[1] === "update"
    ) {
        return `${table.name}_compute`;
    }
    const level = trigger.level === "statement" ? "_statement" : "";
    return `${table.name}_${trigger.timing}_${trigger.events.join("_")}${level}`;
}

/** The return each shape needs: a before row trigger must return the row, since null cancels its event. */
function triggerReturn(trigger: Trigger): string {
    // A statement-level return value is ignored, and a before row trigger on delete has no NEW to return.
    if (trigger.level === "statement" || trigger.timing === "after") {
        return "return null;";
    }
    return trigger.events.includes("delete") ? "return coalesce(NEW, OLD);" : "return NEW;";
}

function renderTriggers(table: Table): string[] {
    const lines: string[] = [];
    for (const trigger of table.triggers) {
        if (trigger.statements.length === 0) {
            continue;
        }
        const name = quote(triggerName(table, trigger));
        lines.push(
            `create function ${name}() returns trigger as $$`,
            "begin",
            ...trigger.statements.map((statement) => `    ${statement}`),
            `    ${triggerReturn(trigger)}`,
            "end;",
            "$$ language plpgsql;",
            "",
            `create trigger ${name} ${trigger.timing} ${trigger.events.join(" or ")} on ${quote(table.name)}`,
            `    for each ${trigger.level} execute function ${name}();`,
            "",
        );
    }
    return lines;
}

/** A Postgres string literal, quoted for the channel `pg_notify` publishes on. */
function quoteLiteral(value: string): string {
    return `'${value.replace(/'/g, "''")}'`;
}

/** The text the trigger publishes for one key column, matching `canonical` in `db/notifications.ts`. */
function keyText(column: Column, value: string): string {
    switch (column.sqlType) {
        case "timestamptz":
            return `to_char(${value} at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`;
        case "bytea":
            return `encode(${value}, 'hex')`;
        default:
            return `${value}::text`;
    }
}

/** Notify the entity's channel once per statement that changes its table, publishing `TG_OP`. See docs/notifications.md. */
function renderNotifyTrigger(table: Table): string[] {
    const name = quote(`${table.name}_notify`);
    return [
        `create function ${name}() returns trigger as $$`,
        "begin",
        `    perform pg_notify(${quoteLiteral(table.name)}, TG_OP);`,
        "    return null;",
        "end;",
        "$$ language plpgsql;",
        "",
        `create trigger ${name} after insert or update or delete on ${quote(table.name)}`,
        `    for each statement execute function ${name}();`,
        "",
    ];
}

/** Notify the entity's channel per changed row, publishing the primary key and `TG_OP`. See docs/notifications.md. */
function renderWatchTrigger(table: Table): string[] {
    const keys = table.columns.filter((column) => column.primaryKey);
    // A keyless table is already a diagnostic; there is no row identity to publish.
    if (keys.length === 0) {
        return [];
    }
    const name = quote(`${table.name}_notify`);
    const payload = (row: "new" | "old" | "either"): string => {
        const entries = keys.map((column) => {
            const value =
                row === "either"
                    ? `coalesce(NEW.${quote(column.name)}, OLD.${quote(column.name)})`
                    : `${row === "new" ? "NEW" : "OLD"}.${quote(column.name)}`;
            return `${quoteLiteral(column.name)}, ${keyText(column, value)}`;
        });
        return `json_build_object('op', TG_OP, 'key', json_build_object(${entries.join(", ")}))::text`;
    };
    const oldKey = keys.map((column) => `OLD.${quote(column.name)}`).join(", ");
    const newKey = keys.map((column) => `NEW.${quote(column.name)}`).join(", ");

    return [
        `create function ${name}() returns trigger as $$`,
        "begin",
        // A changed key notifies both the row's old identity and its new one.
        `    if TG_OP = 'UPDATE' and (${oldKey}) is distinct from (${newKey}) then`,
        `        perform pg_notify(${quoteLiteral(table.name)}, ${payload("old")});`,
        "    end if;",
        `    perform pg_notify(${quoteLiteral(table.name)}, ${payload("either")});`,
        "    return null;",
        "end;",
        "$$ language plpgsql;",
        "",
        `create trigger ${name} after insert or update or delete on ${quote(table.name)}`,
        `    for each row execute function ${name}();`,
        "",
    ];
}

/** Render Postgres DDL from the spec. */
export function generateSchema(spec: SpecModel): { sql: string; diagnostics: Diagnostic[] } {
    const { tables, diagnostics } = buildSpecTables(spec);
    const ordered = orderTables(tables, diagnostics, SPEC_GLOB);

    const lines: string[] = [];
    lines.push("-- Generated by scripts/infra/generate-postgres-schema.ts. Do not edit.");
    lines.push("");

    for (const table of ordered) {
        lines.push(...renderCreateTable(table));
        lines.push("");
    }

    for (const table of ordered) {
        lines.push(...renderTriggers(table));
    }

    for (const table of ordered) {
        if (table.queries.includes("watch")) {
            lines.push(...renderWatchTrigger(table));
        } else if (table.queries.includes("notify")) {
            lines.push(...renderNotifyTrigger(table));
        }
    }

    return { sql: lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n", diagnostics };
}

/** Write the schema for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv, output: Output = console): number {
    const { sql, diagnostics } = generateSchema(spec);

    for (const diagnostic of diagnostics) {
        output.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }

    if (diagnostics.length > 0) {
        return 1;
    }

    if (argv.includes("--stdout")) {
        process.stdout.write(sql);
        return 0;
    }

    const outIndex = argv.indexOf("--out");
    const outPath = outIndex === -1 ? DEFAULT_OUT : argv[outIndex + 1];
    if (!outPath) {
        output.error("--out needs a path");
        return 1;
    }

    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, sql);
    output.log(`wrote ${outPath}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec());
}
