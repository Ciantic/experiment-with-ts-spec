/** Generate `packages/infra/src/http/guards` from the REST model: one self-contained `can<Call>` guard per exposed route. See docs/permissions.md. */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { INFRA_PACKAGE_ROOT } from "../paths.ts";
import { loadSpec, type DeclaredType, type SpecModel } from "../spec/spec-model.ts";
import {
    buildRestModel,
    type RestEntity,
    type RestKind,
    type RestModel,
    type RestOperation,
} from "../sdk/rest-model.ts";

/** The channels a run reports on: the console, or a caller's own sink. */
type Output = Pick<Console, "log" | "error">;

export type { Diagnostic } from "../sdk/rest-model.ts";

/** Where the guard modules are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(INFRA_PACKAGE_ROOT, "src/http/guards");

const HEADER = "// Generated by scripts/infra/generate-guards.ts. Do not edit.";

/** The barrel re-exporting every generated guard. */
const INDEX_FILE = "index.ts";

const FORBIDDEN_IMPORT = "sdk/errors.ts";
const ROUTER_IMPORT = "../router.ts";
const SCHEMAS_IMPORT = "sdk/schemas.ts";
const LOOKUPS_IMPORT = "../../db/queries/index.ts";

/** `queryInvoice` -> `canQueryInvoice`. */
export function guardName(operation: RestOperation): string {
    return `can${operation.id.charAt(0).toUpperCase()}${operation.id.slice(1)}`;
}

/** The check each kind makes, for the doc comment the module carries. */
const CHECKS: Record<RestKind, string> = {
    query: "the session may read the tenants the filter names",
    watch: "the session may watch the filter's tenant, or the tenants of the keys it names",
    create: "the session may write into the tenants the rows name",
    upsert: "the session may replace rows, in the tenants they leave and enter",
    update: "the session may patch rows, in the tenants they are stored in and move to",
    delete: "the session may delete the keys' rows, in the tenants they belong to",
};

/** The kinds whose body resolves a stored row's tenant through the entity's generated lookup. */
const LOOKUP_KINDS: ReadonlySet<RestKind> = new Set<RestKind>(["watch", "upsert", "update", "delete"]);

/** The argument type a guard receives, the imports it needs, and whether it names the entity itself. */
export function argumentType(
    entity: RestEntity,
    kind: RestKind,
    field: string,
    tenantType?: DeclaredType,
    optional = false,
): { type: string; payload?: string; importSpecifier?: string } {
    const name = entity.entity;
    // A field typed by an alias is named as such; an unresolved shape still reads through the entity.
    const tenant = tenantType?.name ?? `${name}[${JSON.stringify(field)}]`;
    const importSpecifier = tenantType?.importSpecifier ?? (tenantType === undefined ? entity.importSpecifier : undefined);
    // A nullable tenant filter also accepts the generated null tests, which name no tenant.
    const filter = optional
        ? `readonly ${tenant}[] | { readonly isNull: true } | { readonly isNotNull: true }`
        : `readonly ${tenant}[]`;
    switch (kind) {
        case "query":
            return {
                type: `{ filter?: { ${field}?: ${filter} | undefined } | undefined }`,
                ...(importSpecifier === undefined ? {} : { importSpecifier }),
            };
        case "watch":
            return {
                type: `{ filter?: { ${field}?: ${tenant} | undefined } | undefined; pks?: readonly ${name}PrimaryKey[] | undefined } | undefined`,
                payload: `${name}PrimaryKey`,
                ...(importSpecifier === undefined ? {} : { importSpecifier }),
            };
        case "create":
            return { type: `readonly ${name}Insert[]`, payload: `${name}Insert` };
        case "upsert":
            return { type: `readonly ${name}Upsert[]`, payload: `${name}Upsert` };
        case "update":
            return { type: `readonly ${name}Patch[]`, payload: `${name}Patch` };
        case "delete":
            return { type: `readonly ${name}PrimaryKey[]`, payload: `${name}PrimaryKey` };
    }
}

/** The lines that refuse a call whose tenants the session does not hold the permission in. */
function checkLines(scope: string, action: string, optional: boolean, emptyMessage?: string): string[] {
    const permission = `${scope}:${action}`;
    const lines: string[] = [
        "    if (tenants.size === 0) {",
        `        throw new ForbiddenError(${JSON.stringify(emptyMessage ?? `${permission} names no tenant the session can be checked against`)});`,
        "    }",
        "    for (const tenant of tenants) {",
    ];
    // A null tenant is a global row: it is only reachable through the permission checked before this helper.
    if (optional) {
        lines.push(
            "        if (tenant === null) {",
            `            throw new ForbiddenError("${permission} addresses a row with no tenant, which needs the global permission");`,
            "        }",
        );
    }
    lines.push(
        `        if (!(await ctx.hasTenantPermission(${JSON.stringify(scope)}, ${JSON.stringify(action)}, tenant))) {`,
        `            throw new ForbiddenError(\`missing permission ${permission} in tenant \${tenant}\`);`,
        "        }",
        "    }",
    );
    return lines;
}

/** The lines that gather the tenants a call addresses, before {@link checkLines} refuses it. */
function tenantLines(
    entity: RestEntity,
    kind: RestKind,
    lookup: string | undefined,
    field: string,
    optional: boolean,
): string[] {
    switch (kind) {
        case "query":
            // A null test names no tenant, so it reaches the global permission the guard asks for first.
            return optional
                ? [
                      `    const filtered = argument.filter?.${field};`,
                      "    const tenants = new Set(Array.isArray(filtered) ? filtered : []);",
                  ]
                : [`    const tenants = new Set(argument.filter?.${field});`];
        case "watch":
            return [
                `    const filtered = argument?.filter?.${field};`,
                `    const tenants = new Set(filtered !== undefined ? [filtered] : await ${lookup as string}(ctx.db, argument?.pks ?? []));`,
            ];
        case "create":
            // A create writes an absent tenant as null, so an unowned row must reach the null check.
            return [
                `    const tenants = new Set(argument.flatMap((row) => row.${field} ?? ${optional ? "[null]" : "[]"}));`,
            ];
        case "upsert":
            // An upsert writes the row whole, so an omitted tenant is the null it stores; a patch leaves it alone.
            return [
                "    const tenants = new Set([",
                `        ...(await ${lookup as string}(ctx.db, argument)),`,
                `        ...argument.flatMap((row) => row.${field} ?? ${optional ? "[null]" : "[]"}),`,
                "    ]);",
            ];
        case "update":
            // A patch that leaves the field out keeps the stored tenant; an explicit null moves an optional owner to no tenant.
            return [
                "    const tenants = new Set([",
                `        ...(await ${lookup as string}(ctx.db, argument)),`,
                optional
                    ? `        ...argument.flatMap((row) => (row.${field} === undefined ? [] : [row.${field}])),`
                    : `        ...argument.flatMap((row) => row.${field} ?? []),`,
                "    ]);",
            ];
        case "delete":
            return [`    const tenants = new Set(await ${lookup as string}(ctx.db, argument));`];
    }
}

/** Render one guard module: the check itself, calling the entity's lookup where a stored row names the tenant. */
export function renderGuardModule(
    entity: RestEntity,
    operation: RestOperation,
    tenantType?: DeclaredType,
): string {
    const name = guardName(operation);
    const scope = JSON.stringify(entity.module);
    const action = JSON.stringify(operation.kind);
    const lines: string[] = [HEADER];

    lines.push(`import { ForbiddenError } from "${FORBIDDEN_IMPORT}";`);
    lines.push(`import type { RouteGuard } from "${ROUTER_IMPORT}";`);

    if (entity.tenantOwned === undefined) {
        lines.push("");
        lines.push("/**");
        lines.push(` * Guard \`${operation.id}\`: the session holds \`${entity.module}:${operation.kind}\`.`);
        lines.push(" * @throws {ForbiddenError} when the session lacks it");
        lines.push(" */");
        lines.push(`export const ${name}: RouteGuard = async (ctx) => {`);
        lines.push(`    if (!(await ctx.hasGlobalPermission(${scope}, ${action}))) {`);
        lines.push(`        throw new ForbiddenError("missing permission ${entity.module}:${operation.kind}");`);
        lines.push("    }");
        lines.push("};");
        return lines.join("\n") + "\n";
    }

    // A delete names the tenant only through its lookup, so it reads no field from the argument.
    const owned = entity.tenantOwned;
    const field = operation.kind !== "delete" ? owned.field : undefined;
    const argument = argumentType(entity, operation.kind, field ?? owned.field, tenantType, owned.optional);
    const lookup = LOOKUP_KINDS.has(operation.kind) ? `get${entity.entity}Tenants` : undefined;
    if (argument.importSpecifier !== undefined) {
        lines.push(`import type { ${tenantType?.name ?? entity.entity} } from "${argument.importSpecifier}";`);
    }
    if (argument.payload !== undefined) {
        lines.push(`import type { ${argument.payload} } from "${SCHEMAS_IMPORT}";`);
    }
    if (lookup !== undefined) {
        lines.push(`import { ${lookup} } from "${LOOKUPS_IMPORT}";`);
    }
    lines.push("");

    lines.push("/**");
    lines.push(` * Guard \`${operation.id}\`: ${CHECKS[operation.kind]}.`);
    lines.push(
        ` * @throws {ForbiddenError} when a tenant the call names is not permitted, or it names none${owned.optional ? ", or when a row has no tenant and the session lacks the global permission" : ""}`,
    );
    lines.push(" */");
    lines.push(`export const ${name}: RouteGuard<${argument.type}> = async (ctx, argument) => {`);
    const returnsEarly = operation.kind === "query" || operation.kind === "watch";
    const early = returnsEarly ? `await ctx.hasGlobalPermission(${scope}, ${action})` : `argument.length === 0 || (await ctx.hasGlobalPermission(${scope}, ${action}))`;
    lines.push(`    if (${early}) {`);
    lines.push("        return;");
    lines.push("    }");
    lines.push(...tenantLines(entity, operation.kind, lookup, field as string, owned.optional));
    const emptyMessage =
        owned.optional && operation.kind === "query"
            ? `${entity.module}:${operation.kind} names no tenant, which needs the global permission`
            : undefined;
    lines.push(...checkLines(entity.module, operation.kind, owned.optional, emptyMessage));
    lines.push("};");
    return lines.join("\n") + "\n";
}

/** Render every generated guard module, keyed by file name (the barrel included). */
export function generateGuards(model: RestModel, spec: SpecModel): Map<string, string> {
    const files = new Map<string, string>();
    const names: string[] = [];
    for (const entity of model.entities) {
        for (const operation of entity.operations) {
            const name = guardName(operation);
            files.set(`${name}.ts`, renderGuardModule(entity, operation, spec.tenantIdType));
            names.push(name);
        }
    }

    names.sort((a, b) => a.localeCompare(b));
    const lines = [HEADER];
    for (const name of names) {
        lines.push(`export * from "./${name}.ts";`);
    }
    files.set(INDEX_FILE, lines.join("\n") + "\n");
    return files;
}

/** Remove the generated modules the spec no longer declares, so a dropped route leaves no guard behind. */
function pruneStale(outDir: string, keep: Set<string>): void {
    for (const entry of readdirSync(outDir, { withFileTypes: true })) {
        if (!entry.isFile() || !entry.name.endsWith(".ts") || keep.has(entry.name)) {
            continue;
        }
        const file = join(outDir, entry.name);
        if (readFileSync(file, "utf8").split("\n", 1)[0] === HEADER) {
            rmSync(file);
        }
    }
}

/** Write the guard modules for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv, output: Output = console): number {
    const model = buildRestModel(spec);

    for (const diagnostic of model.diagnostics) {
        output.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }
    if (model.diagnostics.length > 0) {
        return 1;
    }

    const outIndex = argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : argv[outIndex + 1];
    if (!outDir) {
        output.error("--out needs a directory");
        return 1;
    }

    const files = generateGuards(model, spec);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    pruneStale(outDir, new Set(files.keys()));
    output.log(`wrote ${files.size} files to ${outDir}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec());
}
