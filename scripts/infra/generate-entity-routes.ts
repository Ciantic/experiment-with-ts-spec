/** Generate `packages/infra/src/http/routes` from the REST model: one `Route[]` module per entity plus a barrel. See docs/rest-api.md. */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { INFRA_PACKAGE_ROOT } from "../paths.ts";
import { loadSpec, type SpecModel } from "../spec/spec-model.ts";
// The REST model is shared with the client generator, so both read it from the SDK model.
import {
    buildRestModel,
    type RestEntity,
    type RestKind,
    type RestModel,
} from "../sdk/rest-model.ts";

/** The channels a run reports on: the console, or a caller's own sink. */
type Output = Pick<Console, "log" | "error">;

export type { Diagnostic } from "../sdk/rest-model.ts";

/** Where the route modules are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(INFRA_PACKAGE_ROOT, "src/http/routes");

const HEADER = "// Generated by scripts/infra/generate-entity-routes.ts. Do not edit.";

/** The barrel re-exporting the concatenated entity route table. */
const INDEX_FILE = "index.ts";

/** The hand-written router module the generated table is typed against. */
const ROUTER_IMPORT = "../router.ts";

/** The export the barrel names, which the backend spreads with its operation routes. */
const ENTITY_ROUTES_EXPORT = "entityRoutes";

/** The module specifiers of the generated pieces the routes call into. */
const QUERIES_IMPORT = "../../db/queries/index.ts";
const REPOSITORIES_IMPORT = "../../db/repositories/index.ts";
const SCHEMAS_IMPORT = "sdk/schemas.ts";

/** Invoice -> invoiceRoutes.ts, the module holding that entity's exposed calls. */
export function routesModuleName(entity: RestEntity): string {
    return `${entity.module}Routes.ts`;
}

/** Invoice -> invoiceRoutes. */
export function routesExportName(entity: RestEntity): string {
    return `${entity.module}Routes`;
}

/** The generated schema that validates the request body, before the `delete` projection. */
function schemaName(entity: RestEntity, kind: RestKind): string {
    switch (kind) {
        case "query":
            return `query${entity.entity}Schema`;
        case "create":
            return `${entity.module}InsertSchema`;
        case "upsert":
            return `${entity.module}UpsertSchema`;
        // A delete carries only the key, so it validates against the key schema, not the whole entity.
        case "delete":
            return `${entity.module}PrimaryKeySchema`;
        case "update":
            return `${entity.module}PatchSchema`;
    }
}

/** The expression the router validates the argument with. A read takes options; every write takes rows. */
function inputExpression(entity: RestEntity, kind: RestKind): string {
    return kind === "query" ? schemaName(entity, kind) : `z.array(${schemaName(entity, kind)})`;
}

/** Every repository function one entity needs. */
function repositoryFunctions(entity: RestEntity): string[] {
    // Every write kind names a repository function of its own; a read is served by the query module.
    return entity.operations
        .filter((operation) => operation.kind !== "query")
        .map((operation) => operation.id)
        .sort((a, b) => a.localeCompare(b));
}

/** Every query function one entity needs. */
function queryFunctions(entity: RestEntity): string[] {
    return entity.operations
        .filter((operation) => operation.kind === "query")
        .map((operation) => operation.id)
        .sort((a, b) => a.localeCompare(b));
}

/** Every validation schema one entity needs, de-duplicated. */
function inputSchemas(entity: RestEntity): string[] {
    const names = new Set(entity.operations.map((operation) => schemaName(entity, operation.kind)));
    return [...names].sort((a, b) => a.localeCompare(b));
}

/** Render one entity's route module: the calls its collection exposes. */
export function renderEntityRoutes(entity: RestEntity): string {
    const repositories = repositoryFunctions(entity);
    const queries = queryFunctions(entity);
    const schemas = inputSchemas(entity);

    const lines: string[] = [HEADER];
    lines.push(`import type { Route } from "${ROUTER_IMPORT}";`);
    // Only a write wraps its argument in an array, so the batch shape is the only use of `z`.
    if (entity.operations.some((operation) => operation.kind !== "query")) {
        lines.push('import { z } from "zod";');
    }
    if (repositories.length > 0) {
        lines.push(`import { ${repositories.join(", ")} } from "${REPOSITORIES_IMPORT}";`);
    }
    if (queries.length > 0) {
        lines.push(`import { ${queries.join(", ")} } from "${QUERIES_IMPORT}";`);
    }
    if (schemas.length > 0) {
        lines.push(`import { ${schemas.join(", ")} } from "${SCHEMAS_IMPORT}";`);
    }

    lines.push("");
    lines.push(`/** The calls \`${entity.path}\` exposes: each under its id, its verb, and its path. */`);
    lines.push(`export const ${routesExportName(entity)}: Route[] = [`);
    for (const operation of entity.operations) {
        lines.push("    {");
        lines.push(`        id: "${operation.id}",`);
        lines.push(`        method: "${operation.method}",`);
        lines.push(`        path: "${operation.path}",`);
        lines.push(`        source: "${operation.source}",`);
        lines.push(`        input: ${inputExpression(entity, operation.kind)},`);
        // The body is validated against the schema above, so the handler may trust its shape.
        lines.push(`        handler: (ctx, body) => ${operation.id}(ctx.db, body as never),`);
        lines.push("    },");
    }
    lines.push("];");

    return lines.join("\n") + "\n";
}

/** Render the barrel that concatenates every entity's routes into the table the backend serves. */
export function renderEntityRoutesIndex(model: RestModel): string {
    const lines: string[] = [HEADER];
    lines.push(`import type { Route } from "${ROUTER_IMPORT}";`);
    for (const entity of model.entities) {
        lines.push(
            `import { ${routesExportName(entity)} } from "./${routesModuleName(entity)}";`,
        );
    }

    lines.push("");
    lines.push("/** The calls the spec's repositories and queries expose, one module per entity. */");
    lines.push(`export const ${ENTITY_ROUTES_EXPORT}: Route[] = [`);
    for (const entity of model.entities) {
        lines.push(`    ...${routesExportName(entity)},`);
    }
    lines.push("];");

    return lines.join("\n") + "\n";
}

/** Render every generated entity route file, keyed by file name (the barrel included). */
export function renderEntityRoutesFiles(model: RestModel): Map<string, string> {
    const files = new Map<string, string>();
    for (const entity of model.entities) {
        files.set(routesModuleName(entity), renderEntityRoutes(entity));
    }
    files.set(INDEX_FILE, renderEntityRoutesIndex(model));
    return files;
}

/** Remove the generated modules the spec no longer declares, so a dropped entity leaves no routes behind. */
function pruneStale(outDir: string, keep: Set<string>): void {
    for (const entry of readdirSync(outDir, { withFileTypes: true })) {
        if (!entry.isFile() || !entry.name.endsWith(".ts") || keep.has(entry.name)) {
            continue;
        }
        const file = join(outDir, entry.name);
        if (readFileSync(file, "utf8").split("\n", 1)[0] === HEADER) {
            rmSync(file);
        }
    }
}

/** Write the entity route modules for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv, output: Output = console): number {
    const model = buildRestModel(spec);

    for (const diagnostic of model.diagnostics) {
        output.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }
    if (model.diagnostics.length > 0) {
        return 1;
    }

    const outIndex = argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : argv[outIndex + 1];
    if (!outDir) {
        output.error("--out needs a directory");
        return 1;
    }

    const files = renderEntityRoutesFiles(model);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    pruneStale(outDir, new Set(files.keys()));
    output.log(`wrote ${files.size} files to ${outDir}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec());
}
