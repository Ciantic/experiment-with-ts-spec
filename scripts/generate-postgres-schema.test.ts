/** Unit tests for generateSchema, driven by self-contained fixtures. */
import { describe, expect, it } from "vitest";
import { Project } from "ts-morph";
import { generateSchema, type Diagnostic } from "./generate-postgres-schema.js";

const SPEC_GLOB = "fixtures/domain/**/*.ts";
const FORMULAS_FILE = "fixtures/postgres/formulas.ts";
const EMPTY_FORMULAS = "export const rowFormulas = {} as const;\nexport const invoiceFormulas = {} as const;";

interface Fixture {
    domain: Record<string, string>;
    formulas?: string;
}

/** Generate from an in-memory project, so no fixture depends on the real spec. */
function generate(fixture: Fixture) {
    const project = new Project({ useInMemoryFileSystem: true });
    for (const [name, text] of Object.entries(fixture.domain)) {
        project.createSourceFile(`fixtures/domain/${name}.ts`, text);
    }
    project.createSourceFile(FORMULAS_FILE, fixture.formulas ?? EMPTY_FORMULAS);
    return generateSchema(project, { specGlob: SPEC_GLOB, formulasFile: FORMULAS_FILE });
}

function messages(diagnostics: Diagnostic[]): string[] {
    return diagnostics.map((diagnostic) => diagnostic.message);
}

describe("generateSchema output", () => {
    it("starts with the do-not-edit header", () => {
        const { sql } = generate({ domain: { Thing: "export interface Thing { id: string; }" } });

        expect(sql.startsWith("-- Generated by scripts/generate-postgres-schema.ts. Do not edit.\n")).toBe(true);
    });

    it("maps keyword types to Postgres types", () => {
        const { sql } = generate({
            domain: {
                Thing: `export interface Thing {
                    id: string;
                    name: string;
                    count: number;
                    flag: boolean;
                    big: bigint;
                }`,
            },
        });

        expect(sql).toContain('"name" text not null');
        expect(sql).toContain('"count" float8 not null');
        expect(sql).toContain('"flag" boolean not null');
        expect(sql).toContain('"big" int8 not null');
    });

    it("maps known named types to Postgres types", () => {
        const { sql } = generate({
            domain: {
                Thing: `export interface Thing {
                    id: GUID;
                    amount: Price;
                    rate: Decimal;
                    email: Email;
                    at: Date;
                }`,
            },
        });

        expect(sql).toContain('"id" uuid not null');
        expect(sql).toContain('"amount" int8 not null');
        expect(sql).toContain('"rate" decimal not null');
        expect(sql).toContain('"email" text not null');
        expect(sql).toContain('"at" timestamptz not null');
    });

    it("makes an optional field nullable", () => {
        const { sql } = generate({
            domain: { Thing: "export interface Thing { id: string; note?: string; }" },
        });

        expect(sql).toContain('"note" text');
        expect(sql).not.toContain('"note" text not null');
    });

    it("treats id as a not-null primary key even when optional", () => {
        const { sql } = generate({
            domain: { Thing: "export interface Thing { id?: GUID; }" },
        });

        expect(sql).toContain('"id" uuid not null');
        expect(sql).toContain('constraint "thing_pkey" primary key ("id")');
    });

    it("adds a unique constraint for @unique", () => {
        const { sql } = generate({
            domain: {
                Thing: `export interface Thing {
                    id: GUID;
                    /** @unique */
                    code: string;
                }`,
            },
        });

        expect(sql).toContain('"code" text not null unique');
    });

    it("derives the table name from the interface in snake_case", () => {
        const { sql } = generate({
            domain: { LineItem: "export interface LineItem { id: GUID; }" },
        });

        expect(sql).toContain('create table "line_item"');
    });

    it("lets @table override the table name", () => {
        const { sql } = generate({
            domain: { Person: "/** @table people */\nexport interface Person { id: GUID; }" },
        });

        expect(sql).toContain('create table "people"');
    });
});

describe("generateSchema types", () => {
    it("emits a CHECK for a union of string literals", () => {
        const { sql } = generate({
            domain: { Thing: `export interface Thing { id: GUID; status: "draft" | "sent"; }` },
        });

        expect(sql).toContain(`constraint "thing_status_check" check ("status" in ('draft', 'sent'))`);
    });

    it("escapes single quotes in CHECK values", () => {
        const { sql } = generate({
            domain: { Thing: `export interface Thing { id: GUID; status: "it's" | "plain"; }` },
        });

        expect(sql).toContain(`check ("status" in ('it''s', 'plain'))`);
    });

    it("treats a lone literal as a closed set of one", () => {
        const { sql, diagnostics } = generate({
            domain: { Thing: `export interface Thing { id: GUID; status: "only"; }` },
        });

        expect(diagnostics).toEqual([]);
        expect(sql).toContain(`check ("status" in ('only'))`);
    });

    it("does not constrain an open union", () => {
        const { sql } = generate({
            domain: { Thing: `export interface Thing { id: GUID; unit: "hours" | (string & {}); }` },
        });

        expect(sql).toContain('"unit" text not null');
        expect(sql).not.toContain('"unit" in (');
    });

    it("emits a nullable foreign key for an optional @relation", () => {
        const { sql } = generate({
            domain: {
                Owner: "export interface Owner { id: GUID; }",
                Thing: `export interface Thing {
                    id: GUID;
                    /** @relation Owner */
                    owner?: Owner;
                }`,
            },
        });

        expect(sql).toContain('"ownerId" uuid references "owner"("id")');
        expect(sql).not.toContain('"ownerId" uuid not null');
    });

    it("emits a mandatory foreign key for a required @relation", () => {
        const { sql } = generate({
            domain: {
                Owner: "export interface Owner { id: GUID; }",
                Thing: `export interface Thing {
                    id: GUID;
                    /** @relation Owner */
                    owner: Owner;
                }`,
            },
        });

        expect(sql).toContain('"ownerId" uuid not null references "owner"("id")');
    });

    it("skips a child collection and emits no column for it", () => {
        const { sql, diagnostics } = generate({
            domain: {
                Row: "export interface Row { id: GUID; parentId: ParentId; }",
                Parent: `export interface Parent {
                    id: GUID;
                    /** @children Row */
                    rows: Row[];
                }`,
            },
        });

        expect(sql).not.toContain('"rows"');
        expect(diagnostics).toEqual([]);
    });
});

describe("generateSchema ordering", () => {
    it("emits referenced tables before referencing ones", () => {
        const { sql } = generate({
            domain: {
                Alpha: "export interface Alpha { id: GUID; betaId: BetaId; }",
                Beta: "export interface Beta { id: GUID; }",
            },
        });

        // Alphabetical order would put alpha first; the foreign key reverses that.
        expect(sql.indexOf('create table "alpha"')).toBeGreaterThan(sql.indexOf('create table "beta"'));
    });

    it("reports circular foreign keys", () => {
        const { diagnostics } = generate({
            domain: {
                Alpha: "export interface Alpha { id: GUID; betaId: BetaId; }",
                Beta: "export interface Beta { id: GUID; alphaId: AlphaId; }",
            },
        });

        expect(messages(diagnostics).some((message) => message.startsWith("circular foreign keys"))).toBe(true);
    });
});

describe("generateSchema diagnostics", () => {
    it("reports an entity field without @relation", () => {
        const { diagnostics } = generate({
            domain: {
                Owner: "export interface Owner { id: GUID; }",
                Thing: "export interface Thing { id: GUID; owner: Owner; }",
            },
        });

        expect(messages(diagnostics)).toContain("`owner`: `Owner` is an entity; add @relation Owner");
    });

    it("reports an array field without @children", () => {
        const { diagnostics } = generate({
            domain: {
                Row: "export interface Row { id: GUID; parentId: ParentId; }",
                Parent: "export interface Parent { id: GUID; rows: Row[]; }",
            },
        });

        expect(messages(diagnostics)).toContain("`rows`: array fields need @children <Entity> and are not columns");
    });

    it("reports an interface without a primary key", () => {
        const { diagnostics } = generate({
            domain: { Thing: "export interface Thing { name: string; }" },
        });

        expect(messages(diagnostics)).toContain("`Thing`: no `id` field to use as primary key");
    });

    it("reports an unsupported type", () => {
        const { diagnostics } = generate({
            domain: { Thing: "export interface Thing { id: GUID; data: unknown; }" },
        });

        expect(messages(diagnostics)).toContain("`data`: unsupported type `unknown`");
    });

    it("reports @relation pointing at an unknown entity", () => {
        const { diagnostics } = generate({
            domain: {
                Owner: "export interface Owner { id: GUID; }",
                Thing: `export interface Thing {
                    id: GUID;
                    /** @relation Missing */
                    owner: Owner;
                }`,
            },
        });

        expect(messages(diagnostics)).toContain("`owner`: @relation Missing has no interface");
    });
});

describe("generateSchema triggers", () => {
    const rowFormulas = [
        "export const rowFormulas = {",
        "    rowNet: 'round(NEW.\"a\" * NEW.\"b\")::bigint',",
        "    rowTax: 'NEW.\"net\" * 2',",
        "    rowTotal: 'NEW.\"net\" + NEW.\"tax\"',",
        "} as const;",
        "export const invoiceFormulas = {} as const;",
    ].join("\n");

    it("emits a before trigger assigning computed fields in interface order", () => {
        const { sql } = generate({
            formulas: rowFormulas,
            domain: {
                Thing: `export interface Thing {
                    id: GUID;
                    a: number;
                    b: bigint;
                    /** @computed storage=stored formula=rowNet */
                    net: Price;
                    /** @computed storage=stored formula=rowTax */
                    tax: Price;
                    /** @computed storage=stored formula=rowTotal */
                    total: Price;
                }`,
            },
        });

        expect(sql).toContain('create function "thing_compute"() returns trigger as $$');
        expect(sql).toContain('before insert or update on "thing"');
        expect(sql).toContain("    return NEW;");

        const net = sql.indexOf(`NEW."net" := round(NEW."a" * NEW."b")::bigint;`);
        const tax = sql.indexOf(`NEW."tax" := NEW."net" * 2;`);
        const total = sql.indexOf(`NEW."total" := NEW."net" + NEW."tax";`);
        expect(net).toBeGreaterThan(-1);
        expect(net).toBeLessThan(tax);
        expect(tax).toBeLessThan(total);
    });

    it("emits no trigger for a table without computed fields", () => {
        const { sql } = generate({ domain: { Thing: "export interface Thing { id: GUID; }" } });

        expect(sql).not.toContain("create function");
    });

    it("emits after triggers that maintain a cross-table aggregate", () => {
        const formulas = [
            "export const rowFormulas = {} as const;",
            "export const invoiceFormulas = {",
            "    parentNet: {",
            "        childNew: 'update \"parent\" set \"net\" = 1 where \"id\" = NEW.\"parentId\";',",
            "        childOld: 'update \"parent\" set \"net\" = 0 where \"id\" = OLD.\"parentId\";',",
            "    },",
            "} as const;",
        ].join("\n");

        const { sql } = generate({
            formulas,
            domain: {
                Parent: `export interface Parent {
                    id: GUID;
                    /** @computed storage=stored formula=parentNet */
                    net: Price;
                }`,
                Child: "export interface Child { id: GUID; parentId: ParentId; }",
            },
        });

        expect(sql).toContain('create function "child_rollup_parent_set"() returns trigger as $$');
        expect(sql).toContain('after insert or update on "child"');
        expect(sql).toContain('create function "child_rollup_parent_unset"() returns trigger as $$');
        expect(sql).toContain('after delete on "child"');
        expect(sql).toContain("return null;");
    });

    it("groups several aggregate fields into one trigger function per child table", () => {
        const formulas = [
            "export const rowFormulas = {} as const;",
            "export const invoiceFormulas = {",
            "    net: { childNew: 'update \"parent\" set \"net\" = 1;', childOld: 'update \"parent\" set \"net\" = 0;' },",
            "    tax: { childNew: 'update \"parent\" set \"tax\" = 1;', childOld: 'update \"parent\" set \"tax\" = 0;' },",
            "} as const;",
        ].join("\n");

        const { sql } = generate({
            formulas,
            domain: {
                Parent: `export interface Parent {
                    id: GUID;
                    /** @computed storage=stored formula=net */
                    net: Price;
                    /** @computed storage=stored formula=tax */
                    tax: Price;
                }`,
                Child: "export interface Child { id: GUID; parentId: ParentId; }",
            },
        });

        const declarations = sql.split('create function "child_rollup_parent_set"()').length - 1;
        expect(declarations).toBe(1);
        expect(sql).toContain('set "net" =');
        expect(sql).toContain('set "tax" =');
    });
});
