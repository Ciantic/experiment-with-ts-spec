/**
 * Generate the server's route table from the REST model, on `effect/schema` and
 * `effect/sql`. See docs/rest-api-effect.md.
 *
 * Emits `packages/backend-effect/src/http/routes.ts`: a `Route[]` the hand-written
 * router matches on. The generator emits the contract and the wiring, never
 * request handling — the router owns parsing, validation, and status mapping.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Project } from "ts-morph";
import { DEFAULT_SPEC_GLOB, SPEC_GLOB, buildSpecTables } from "./postgres-model.ts";
import { BACKEND_PACKAGE_ROOT } from "./postgres-model.ts";
import { buildRestModel, type RestEntity, type RestKind, type RestModel } from "./rest-model.ts";

export type { Diagnostic } from "./postgres-model.ts";

/** Where the route table is written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(BACKEND_PACKAGE_ROOT, "src/http");

const HEADER = "// Generated by scripts/generate-routes.ts. Do not edit.";

/** The file name of the rendered route table. */
const ROUTES_FILE = "routes.ts";

/** The hand-written router module the generated table is typed against. */
const ROUTER_IMPORT = "./router.ts";

/** The module specifiers of the generated pieces the routes call into. */
const QUERIES_IMPORT = "../db/queries/index.ts";
const REPOSITORIES_IMPORT = "../db/repositories/index.ts";
const VALIDATION_IMPORT = "../validation/index.ts";

/** `invoice` + `list` -> `listInvoice`. The generated function that serves the call. */
function functionName(entity: RestEntity, kind: RestKind): string {
    return `${kind}${entity.entity}`;
}

/** The generated schema that validates the request, before the `delete` projection. */
function schemaName(entity: RestEntity, kind: RestKind): string {
    switch (kind) {
        case "list":
            return `list${entity.entity}Schema`;
        case "get":
            return `get${entity.entity}Schema`;
        case "create":
        case "delete":
            return `${entity.module}Schema`;
        case "update":
            return `${entity.module}PatchSchema`;
    }
}

/** The expression the router validates the body with. A delete carries only the key. */
function inputExpression(entity: RestEntity, kind: RestKind): string {
    if (kind !== "delete") {
        return schemaName(entity, kind);
    }
    // `effect/schema` has no `.pick`, so the key-only struct is rebuilt from the entity's field.
    return `Schema.Array(Schema.Struct({ ${entity.key}: ${entity.module}Schema.fields.${entity.key} }))`;
}

/** Every repository function the model needs. */
function repositoryFunctions(model: RestModel): string[] {
    return model.entities
        .flatMap((entity) =>
            entity.operations
                .filter(
                    (operation) =>
                        operation.kind === "create" || operation.kind === "update" || operation.kind === "delete",
                )
                .map((operation) => functionName(entity, operation.kind)),
        )
        .sort((a, b) => a.localeCompare(b));
}

/** Every query function the model needs. */
function queryFunctions(model: RestModel): string[] {
    return model.entities
        .flatMap((entity) =>
            entity.operations
                .filter((operation) => operation.kind === "list" || operation.kind === "get")
                .map((operation) => functionName(entity, operation.kind)),
        )
        .sort((a, b) => a.localeCompare(b));
}

/** Every validation schema the model needs, de-duplicated. */
function inputSchemas(model: RestModel): string[] {
    const names = new Set<string>();
    for (const entity of model.entities) {
        for (const operation of entity.operations) {
            names.add(schemaName(entity, operation.kind));
        }
    }
    return [...names].sort((a, b) => a.localeCompare(b));
}

/** Render the route table module. */
export function renderRoutesModule(model: RestModel): string {
    const repositories = repositoryFunctions(model);
    const queries = queryFunctions(model);
    const schemas = inputSchemas(model);

    const lines: string[] = [HEADER];
    lines.push('import { Schema } from "effect";');
    lines.push(`import type { Route } from "${ROUTER_IMPORT}";`);
    if (repositories.length > 0) {
        lines.push(`import { ${repositories.join(", ")} } from "${REPOSITORIES_IMPORT}";`);
    }
    if (queries.length > 0) {
        lines.push(`import { ${queries.join(", ")} } from "${QUERIES_IMPORT}";`);
    }
    if (schemas.length > 0) {
        lines.push(`import { ${schemas.join(", ")} } from "${VALIDATION_IMPORT}";`);
    }

    lines.push("");
    lines.push("/** Every exposed call, matched by method and path. */");
    lines.push("export const routes: Route[] = [");
    for (const entity of model.entities) {
        for (const operation of entity.operations) {
            lines.push("    {");
            lines.push(`        method: "${operation.method}",`);
            lines.push(`        path: "${operation.path}",`);
            lines.push(`        source: "${operation.source}",`);
            lines.push(`        input: ${inputExpression(entity, operation.kind)},`);
            // The body is validated against the schema above, so the handler may trust its shape.
            lines.push(`        handler: (body) => ${functionName(entity, operation.kind)}(body as never),`);
            lines.push("    },");
        }
    }
    lines.push("];");

    return lines.join("\n") + "\n";
}

function main(): void {
    const project = new Project({ tsConfigFilePath: "tsconfig.json" });
    project.addSourceFilesAtPaths(SPEC_GLOB);
    const { tables, diagnostics } = buildSpecTables(project, {
        specGlob: DEFAULT_SPEC_GLOB,
        aliasGlob: SPEC_GLOB,
    });

    for (const diagnostic of diagnostics) {
        console.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }
    if (diagnostics.length > 0) {
        process.exitCode = 1;
        return;
    }

    const outIndex = process.argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : process.argv[outIndex + 1];
    if (!outDir) {
        console.error("--out needs a directory");
        process.exitCode = 1;
        return;
    }

    const files = new Map([[ROUTES_FILE, renderRoutesModule(buildRestModel(tables))]]);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    console.log(`wrote ${files.size} files to ${outDir}`);
}

if (import.meta.main) {
    main();
}
