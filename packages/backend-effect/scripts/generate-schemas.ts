/** Generate `effect/schema` schemas from `spec/domain`. See docs/validation.md. */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { Project } from "ts-morph";
import { DEFAULT_SPEC_GLOB, SPEC_GLOB } from "spec/scripts/spec-model.ts";
import { BACKEND_PACKAGE_ROOT } from "./postgres-model.ts";
import {
    buildSchemaModel,
    lowerFirst,
    type SchemaEntity,
    type SchemaField,
    type SchemaModel,
    type SchemaPrimitive,
    type SchemaQuery,
} from "./schema-model.ts";

export type { Diagnostic } from "./schema-model.ts";

/** Where the schemas are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(BACKEND_PACKAGE_ROOT, "src/validation");

const HEADER = "// Generated by scripts/generate-schemas.ts. Do not edit.";

/** The module re-exporting the primitive schemas, and the barrel alongside the entity files. */
const PRIMITIVES_FILE = "primitives.ts";
const INDEX_FILE = "index.ts";

/** The directory holding the generated query schemas, under the output root. */
const QUERIES_DIR = "queries";

/** The barrel re-exporting every query schema, inside {@link QUERIES_DIR}. */
const QUERIES_INDEX = join(QUERIES_DIR, "index.ts");

/** The single import every generated module needs. */
const EFFECT_IMPORT = 'import { Schema } from "effect";';

/** The module specifier that imports another entity's schema, e.g. `./invoiceRow.ts`. */
function entityImport(entity: SchemaEntity): string {
    return `./${entity.fileName}`;
}

/** The file for one entity's queries, e.g. `Invoice` -> `queries/invoiceQueries.ts`. */
export function queryFileName(entity: string): string {
    return join(QUERIES_DIR, `${lowerFirst(entity)}Queries.ts`);
}

/** A field's schema, wrapped in `Schema.optionalKey` when the field may be absent. */
function fieldExpression(field: SchemaField): string {
    return field.optional ? `Schema.optionalKey(${field.expression})` : field.expression;
}

/** Render `primitives.ts`: one schema per primitive, a factory for a generic primitive. */
export function generatePrimitives(primitives: SchemaPrimitive[]): string {
    const lines: string[] = [HEADER, EFFECT_IMPORT];
    for (const primitive of primitives) {
        lines.push("");
        if (primitive.typeParameters) {
            // A generic primitive's type parameters are also value parameters: `Schema.brand`
            // takes its identifier as a value. See docs/validation-effect.md.
            const parameters = primitive.parameterNames
                .map((name) => `${lowerFirst(name)}: ${name}`)
                .join(", ");
            lines.push(`export function ${primitive.schemaName}<${primitive.typeParameters}>(${parameters}) {`);
            lines.push(`    return ${primitive.expression};`);
            lines.push("}");
        } else {
            lines.push(`export const ${primitive.schemaName} = ${primitive.expression};`);
        }
    }
    return lines.join("\n") + "\n";
}

/** Render one entity module: its schema, its patch schema, and its `select` schema. */
export function generateEntity(entity: SchemaEntity, byName: Map<string, SchemaEntity>): string {
    const lines: string[] = [HEADER, EFFECT_IMPORT];
    if (entity.usesPrimitives) {
        lines.push('import * as primitives from "./primitives.ts";');
    }
    for (const dependency of entity.dependencies) {
        const target = byName.get(dependency);
        if (target) {
            lines.push(
                `import { ${target.schemaName}, ${target.selectName} } from "${entityImport(target)}";`,
            );
        }
    }

    lines.push("");
    lines.push(`export const ${entity.schemaName} = Schema.Struct({`);
    for (const field of entity.fields) {
        lines.push(`    ${field.name}: ${fieldExpression(field)},`);
    }
    lines.push("});");

    // The patch is the schema with every field optionalKey except the key and the version.
    const required = new Set(entity.required);
    const versioned = entity.required.some((name) => name !== "id");
    lines.push("");
    lines.push(
        versioned
            ? "/** A partial update: every field is optional except the key and the version. */"
            : "/** A partial update: every field is optional except the key. */",
    );
    lines.push(`export const ${entity.patchName} = Schema.Struct({`);
    for (const field of entity.fields) {
        const expression = required.has(field.name)
            ? field.expression
            : `Schema.optionalKey(${field.expression})`;
        lines.push(`    ${field.name}: ${expression},`);
    }
    lines.push("});");

    lines.push("");
    lines.push(`/** A \`select\` over ${entity.name}: \`true\` for a scalar, a nested select for a branch. */`);
    lines.push(`export const ${entity.selectName} = Schema.suspend(() =>`);
    lines.push("    Schema.Struct({");
    for (const field of entity.selectFields) {
        if (field.target === undefined) {
            lines.push(`        ${field.name}: Schema.optionalKey(Schema.Literal(true)),`);
            continue;
        }
        const target = byName.get(field.target);
        const targetSelect = target ? target.selectName : "Schema.Never";
        lines.push(
            `        ${field.name}: Schema.optionalKey(Schema.Union([Schema.Literal(true), Schema.suspend(() => ${targetSelect})])),`,
        );
    }
    lines.push("    }),");
    lines.push(");");

    return lines.join("\n") + "\n";
}

/** Render one entity's query schema module: the `list` filters and `select`, plus the `get`. */
export function generateQueryFile(
    entity: string,
    queries: SchemaQuery[],
    entitiesByName: Map<string, SchemaEntity>,
): string {
    const lines: string[] = [HEADER, EFFECT_IMPORT];
    const entitySchema = entitiesByName.get(entity);
    if (entitySchema) {
        lines.push(`import { ${entitySchema.selectName} } from "../${entitySchema.fileName}";`);
    }
    if (queries.some((query) => query.usesPrimitives)) {
        lines.push('import * as primitives from "../primitives.ts";');
    }
    const dependencies = new Set(queries.flatMap((query) => query.dependencies));
    for (const dependency of [...dependencies].sort((a, b) => a.localeCompare(b))) {
        const target = entitiesByName.get(dependency);
        if (target) {
            lines.push(`import { ${target.schemaName} } from "../${target.fileName}";`);
        }
    }

    for (const query of queries) {
        lines.push("");
        lines.push(`export const ${query.schemaName} = Schema.Struct({`);
        for (const field of query.fields) {
            lines.push(`    ${field.name}: ${fieldExpression(field)},`);
        }
        // The read's one argument carries the filters and the selection together.
        lines.push(`    select: ${entitySchema ? entitySchema.selectName : "Schema.Never"},`);
        lines.push("});");

        // A getter needs a filter to name a row, so the schema requires at least one of them.
        if (query.fields.length > 0) {
            const named = query.fields.map((field) => `value.${field.name} !== undefined`).join(" || ");
            lines.push("");
            lines.push("/** The same filters, with at least one of them named. */");
            lines.push(`export const get${entity}Schema = ${query.schemaName}.pipe(`);
            lines.push("    Schema.check(");
            lines.push(
                `        Schema.makeFilter((value) => ${named}, { message: "get${entity} needs at least one filter" }),`,
            );
            lines.push("    ),");
            lines.push(");");
        }
    }
    return lines.join("\n") + "\n";
}

/** Render the barrel that re-exports every query schema module. */
export function generateQueriesIndex(queries: SchemaQuery[]): string {
    const lines = [HEADER];
    const entities = [...new Set(queries.map((query) => query.entity))].sort((a, b) => a.localeCompare(b));
    for (const entity of entities) {
        lines.push(`export * from "./${lowerFirst(entity)}Queries.ts";`);
    }
    return lines.join("\n") + "\n";
}

/** Render the barrel that re-exports the primitives and every entity module. */
export function generateIndex(model: SchemaModel): string {
    const lines = [HEADER, 'export * from "./primitives.ts";'];
    for (const entity of model.entities) {
        lines.push(`export * from "${entityImport(entity)}";`);
    }
    if (model.queries.length > 0) {
        lines.push('export * from "./queries/index.ts";');
    }
    return lines.join("\n") + "\n";
}

/** Render every generated file, keyed by file name (including the barrels). */
export function generateSchemas(model: SchemaModel): Map<string, string> {
    const files = new Map<string, string>();
    files.set(PRIMITIVES_FILE, generatePrimitives(model.primitives));
    const byName = new Map(model.entities.map((entity) => [entity.name, entity]));
    for (const entity of model.entities) {
        files.set(entity.fileName, generateEntity(entity, byName));
    }

    // Queries are grouped by the entity they read, so one file holds that entity's args schemas.
    const byEntity = new Map<string, SchemaQuery[]>();
    for (const query of model.queries) {
        const group = byEntity.get(query.entity) ?? [];
        group.push(query);
        byEntity.set(query.entity, group);
    }
    for (const [entity, queries] of byEntity) {
        files.set(queryFileName(entity), generateQueryFile(entity, queries, byName));
    }
    if (model.queries.length > 0) {
        files.set(QUERIES_INDEX, generateQueriesIndex(model.queries));
    }

    files.set(INDEX_FILE, generateIndex(model));
    return files;
}

function main(): void {
    const project = new Project({ tsConfigFilePath: "tsconfig.json" });
    project.addSourceFilesAtPaths(SPEC_GLOB);
    const model = buildSchemaModel(project, { specGlob: DEFAULT_SPEC_GLOB, aliasGlob: SPEC_GLOB });

    for (const diagnostic of model.diagnostics) {
        console.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }

    if (model.diagnostics.length > 0) {
        process.exitCode = 1;
        return;
    }

    const outIndex = process.argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : process.argv[outIndex + 1];
    if (!outDir) {
        console.error("--out needs a directory");
        process.exitCode = 1;
        return;
    }

    const files = generateSchemas(model);
    for (const [name, content] of files) {
        const target = join(outDir, name);
        mkdirSync(dirname(target), { recursive: true });
        writeFileSync(target, content);
    }
    console.log(`wrote ${files.size} files to ${outDir}`);
}

if (import.meta.main) {
    main();
}
