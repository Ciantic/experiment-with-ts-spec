/**
 * Generate CRUD repositories from `spec/domain`, on `effect/sql`. See docs/repositories-effect.md.
 *
 * Each function returns an `Effect` that requires the `SqlClient` service. An
 * insert uses the `sql` template and its multi-row `insert` helper; the update
 * and delete keep a hand-built parameterised statement, because their
 * `coalesce`-on-omitted-column and composite-key `using (values …)` shapes are
 * not expressible with the helpers.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Project } from "ts-morph";
import {
    BACKEND_PACKAGE_ROOT,
    DEFAULT_FORMULAS_FILE,
    DEFAULT_SPEC_GLOB,
    SPEC_GLOB,
    buildSpecTables,
    quote,
    type Column,
    type Table,
} from "./postgres-model.ts";

/** Where the repository files are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(BACKEND_PACKAGE_ROOT, "src/db/repositories");

const HEADER = "// Generated by scripts/generate-repositories.ts. Do not edit.";

/** The module re-exports every repository, alongside the per-entity files. */
const INDEX_FILE = "index.ts";

const EFFECT_IMPORT = 'import { Effect } from "effect";';
const SQL_CLIENT_IMPORT = 'import { SqlClient } from "effect/sql/SqlClient";';
const SQL_ERROR_IMPORT = 'import type { SqlError } from "effect/sql/SqlError";';

/** The `Effect` type a generated function returns. */
const EFFECT_TYPE = "Effect.Effect<void, SqlError, SqlClient>";

/** InvoiceRow -> invoiceRow.ts. */
function fileName(interfaceName: string): string {
    return interfaceName.charAt(0).toLowerCase() + interfaceName.slice(1) + ".ts";
}

/** A column's value expression and the type its placeholder is cast to. */
interface ValueEntry {
    expression: string;
    sqlType: string;
}

/** The accessor that reads a column from a row, e.g. `customer?.id` for an inlined optional field. */
function readExpression(column: Column): string {
    return `row.${column.read ?? column.name}`;
}

/** The value entry for a plain write, where every column of the row is present. */
function readEntry(column: Column): ValueEntry {
    return { expression: readExpression(column), sqlType: column.sqlType };
}

/** The value entry for a patch: a version is required, every other column is null when the caller omits it. */
function patchEntry(column: Column): ValueEntry {
    const read = readExpression(column);
    return { expression: column.version ? read : `${read} ?? null`, sqlType: column.sqlType };
}

/** The object literal an insert passes to `sql.insert`, keyed by column name. */
function insertObject(columns: Column[]): string {
    const entries = columns.map((column) => `${column.name}: ${readExpression(column)}`).join(", ");
    return `rows.map((row) => ({ ${entries} }))`;
}

/** The lines that gather the given values into `parameters` and `tuples`, one tuple per row. */
function collectValues(entries: ValueEntry[]): string[] {
    const values = entries.map((entry) => entry.expression).join(", ");
    // The `values` alias is otherwise untyped text; casting each placeholder keeps keys and
    // assignments matching the column type (a bare text value would not compare to a uuid key).
    const tuple = entries
        .map((entry, index) => `"$" + (offset + ${index + 1}) + "::${entry.sqlType}"`)
        .join(' + ", " + ');
    return [
        "        const parameters: unknown[] = [];",
        "        const tuples: string[] = [];",
        "        for (const row of rows) {",
        `            const values = [${values}];`,
        "            parameters.push(...values);",
        "            const offset = parameters.length - values.length;",
        `            tuples.push("(" + ${tuple} + ")");`,
        "        }",
    ];
}

/** Render one repository module: create, patch, and delete over `rows` of `table`. */
export function generateRepository(table: Table): string {
    const entity = table.interfaceName;
    const columns = table.columns;
    const primaryKeys = columns.filter((column) => column.primaryKey);
    const versionColumns = columns.filter((column) => column.version);
    // A column with a database default is left to the database on insert; the repository never writes it.
    const insertColumns = columns.filter((column) => column.default === undefined);
    // A patch may set every column except the key; a defaulted column is skipped unless it is the version.
    const patchColumns = columns.filter(
        (column) => !column.primaryKey && (column.default === undefined || column.version),
    );
    // The tuple carries the keys first, then the patchable columns.
    const dataEntries = [...primaryKeys.map(readEntry), ...patchColumns.map(patchEntry)];
    const requiredColumns = [...primaryKeys, ...versionColumns];
    const requiredKeys = requiredColumns.map((column) => quote(column.name)).join(" | ");
    const dataColumnNames = [...primaryKeys, ...patchColumns].map((column) => quote(column.name)).join(", ");
    const primaryKeyColumns = primaryKeys.map((column) => quote(column.name)).join(", ");
    const keyAssignment = (column: Column) => `${quote(column.name)} = data.${quote(column.name)}`;
    // An omitted column keeps its stored value, so a patch cannot set one to null; the version is required.
    const patchAssignment = (column: Column) =>
        column.version
            ? keyAssignment(column)
            : `${quote(column.name)} = coalesce(data.${quote(column.name)}, ${quote(table.name)}.${quote(column.name)})`;
    // An update must set something; a table with nothing to patch sets its key to the key it already holds.
    const setClause =
        patchColumns.length > 0
            ? patchColumns.map(patchAssignment).join(", ")
            : primaryKeys.map(keyAssignment).join(", ");
    const match = primaryKeys
        .map((column) => `${quote(table.name)}.${quote(column.name)} = data.${quote(column.name)}`)
        .join(" and ");
    const requiredComment =
        versionColumns.length > 0
            ? "/** A partial update: every column is optional except the key and the version. */"
            : "/** A partial update: every column is optional except the key. */";

    const lines: string[] = [];
    lines.push(HEADER);
    lines.push(EFFECT_IMPORT);
    lines.push(SQL_CLIENT_IMPORT);
    lines.push(SQL_ERROR_IMPORT);
    lines.push(`import type { ${entity} } from "${table.importSpecifier}";`);
    lines.push("");
    lines.push(requiredComment);
    lines.push(`export type ${entity}Patch = Partial<${entity}> & Required<Pick<${entity}, ${requiredKeys}>>;`);
    lines.push("");

    // Insert: one multi-row statement, the values keyed by column name.
    lines.push(`export function create${entity}(rows: ${entity}[]): ${EFFECT_TYPE} {`);
    lines.push("    if (rows.length === 0) {");
    lines.push("        return Effect.void;");
    lines.push("    }");
    lines.push("    return Effect.gen(function* () {");
    lines.push("        const sql = yield* SqlClient;");
    lines.push(`        const values = ${insertObject(insertColumns)};`);
    lines.push(`        yield* sql\`insert into ${quote(table.name)} \${sql.insert(values)}\`;`);
    lines.push("    });");
    lines.push("}");
    lines.push("");

    lines.push(`export function update${entity}(rows: ${entity}Patch[]): ${EFFECT_TYPE} {`);
    lines.push("    if (rows.length === 0) {");
    lines.push("        return Effect.void;");
    lines.push("    }");
    lines.push("    return Effect.gen(function* () {");
    lines.push("        const sql = yield* SqlClient;");
    lines.push(...collectValues(dataEntries));
    lines.push(
        `        yield* sql.unsafe('update ${quote(table.name)} set ${setClause} from (values ' + tuples.join(", ") + ') as data(${dataColumnNames}) where ${match}', parameters);`,
    );
    lines.push("    });");
    lines.push("}");
    lines.push("");

    lines.push(`export function delete${entity}(rows: ${entity}[]): ${EFFECT_TYPE} {`);
    lines.push("    if (rows.length === 0) {");
    lines.push("        return Effect.void;");
    lines.push("    }");
    lines.push("    return Effect.gen(function* () {");
    lines.push("        const sql = yield* SqlClient;");
    lines.push(...collectValues(primaryKeys.map(readEntry)));
    lines.push(
        `        yield* sql.unsafe('delete from ${quote(table.name)} using (values ' + tuples.join(", ") + ') as data(${primaryKeyColumns}) where ${match}', parameters);`,
    );
    lines.push("    });");
    lines.push("}");

    return lines.join("\n") + "\n";
}

/** Render the barrel that re-exports every repository module. */
export function generateIndex(tables: Table[]): string {
    const lines = [HEADER];
    for (const table of [...tables].sort((a, b) => a.interfaceName.localeCompare(b.interfaceName))) {
        lines.push(`export * from "./${fileName(table.interfaceName)}";`);
    }
    return lines.join("\n") + "\n";
}

/** Render every generated file, keyed by file name (including the barrel). */
export function generateRepositories(tables: Map<string, Table>): Map<string, string> {
    const files = new Map<string, string>();
    for (const table of tables.values()) {
        files.set(fileName(table.interfaceName), generateRepository(table));
    }
    files.set(INDEX_FILE, generateIndex([...tables.values()]));
    return files;
}

function main(): void {
    const project = new Project({ tsConfigFilePath: "tsconfig.json" });
    project.addSourceFilesAtPaths(SPEC_GLOB);
    const { tables, diagnostics } = buildSpecTables(project, {
        specGlob: DEFAULT_SPEC_GLOB,
        aliasGlob: SPEC_GLOB,
        formulasFile: DEFAULT_FORMULAS_FILE,
    });

    for (const diagnostic of diagnostics) {
        console.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }

    if (diagnostics.length > 0) {
        process.exitCode = 1;
        return;
    }

    const outIndex = process.argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : process.argv[outIndex + 1];
    if (!outDir) {
        console.error("--out needs a directory");
        process.exitCode = 1;
        return;
    }

    const files = generateRepositories(tables);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    console.log(`wrote ${files.size} files to ${outDir}`);
}

if (import.meta.main) {
    main();
}
