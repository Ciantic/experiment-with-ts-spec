/**
 * Generate Zod schemas and their write types from `spec/domain`, into this package's `src`.
 * See docs/validation.md.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { Project } from "ts-morph";
import { DEFAULT_SPEC_GLOB, SPEC_GLOB } from "spec/scripts/spec-model.ts";
import {
    buildZodModel,
    type ZodEntity,
    type ZodModel,
    type ZodPrimitive,
    type ZodQuery,
} from "./zod-model.ts";

export type { Diagnostic } from "./zod-model.ts";

/** This package's root, derived from this file's location rather than the cwd. */
const VALIDATION_PACKAGE_ROOT = dirname(import.meta.dirname);

/** Where the schemas are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(VALIDATION_PACKAGE_ROOT, "src");

const HEADER = "// Generated by scripts/generate-zod-schemas.ts. Do not edit.";

/** The module re-exporting the primitive schemas, and the barrel alongside the entity files. */
const PRIMITIVES_FILE = "primitives.ts";
const INDEX_FILE = "index.ts";

/** The module specifier that imports another entity's schema, e.g. `./invoiceRow.ts`. */
function entityImport(entity: ZodEntity): string {
    return `./${entity.fileName}`;
}

/** The directory holding the generated query schemas, under the output root. */
const QUERIES_DIR = "queries";

/** The barrel re-exporting every query schema, inside {@link QUERIES_DIR}. */
const QUERIES_INDEX = join(QUERIES_DIR, "index.ts");

/** The file for one entity's queries, e.g. `Invoice` -> `queries/queryInvoice.ts`. */
export function queryFileName(entity: string): string {
    return join(QUERIES_DIR, `query${entity}.ts`);
}

/** Render one entity's query schema module: the `query` filters and `select`. */
export function generateQueryFile(
    entity: string,
    queries: ZodQuery[],
    entitiesByName: Map<string, ZodEntity>,
): string {
    const lines: string[] = [HEADER, 'import { z } from "zod";'];
    const entitySchema = entitiesByName.get(entity);
    if (queries.some((query) => query.usesPrimitives)) {
        lines.push('import * as primitives from "../primitives.ts";');
    }
    const dependencies = new Set(queries.flatMap((query) => query.dependencies));
    for (const dependency of [...dependencies].sort((a, b) => a.localeCompare(b))) {
        const target = entitiesByName.get(dependency);
        if (target) {
            lines.push(`import { ${target.schemaName} } from "../${target.fileName}";`);
        }
    }

    if (entitySchema) {
        const selectDependencies = new Set(
            entitySchema.selectFields.flatMap((field) => field.target ? [field.target] : []),
        );
        for (const dependency of [...selectDependencies].sort((a, b) => a.localeCompare(b))) {
            const target = entitiesByName.get(dependency);
            if (target && dependency !== entity) {
                lines.push(`import { ${target.querySelectName} } from "./query${target.name}.ts";`);
            }
        }
        lines.push("");
        lines.push(`/** A \`select\` over ${entity}: \`true\` for a scalar, a nested select for a branch. */`);
        lines.push(`export const ${entitySchema.querySelectName} = z.lazy(() =>`);
        lines.push("    z.strictObject({");
        for (const field of entitySchema.selectFields) {
            if (field.target === undefined) {
                lines.push(`        ${field.name}: z.literal(true).optional(),`);
                continue;
            }
            const target = entitiesByName.get(field.target);
            const targetSelect = target ? target.querySelectName : "z.never()";
            lines.push(
                `        ${field.name}: z.union([z.literal(true), z.lazy(() => ${targetSelect})]).optional(),`,
            );
        }
        lines.push("    }),");
        lines.push(");");
    }

    for (const query of queries) {
        lines.push("");
        lines.push(`export const ${query.schemaName} = z.strictObject({`);
        // The filter is its own object so a data field can never collide with `select`.
        if (query.fields.length > 0) {
            lines.push("    filter: z.strictObject({");
            for (const field of query.fields) {
                lines.push(`        ${field.name}: ${field.expression},`);
            }
            lines.push("    }).optional(),");
        }
        // Ordering is whitelisted by `@queryorderby`, so an unknown field fails rather than reaching SQL.
        if (query.orderFields.length > 0) {
            const names = query.orderFields.map((field) => JSON.stringify(field)).join(", ");
            // A clause is a tuple: `["createdAt", "desc"]`.
            lines.push("    order: z.array(");
            lines.push(`        z.tuple([z.enum([${names}]), z.enum(["asc", "desc"])]),`);
            lines.push("    ).optional(),");
        }
        // Comparisons are whitelisted by `@where`: a field and an operator are both checked here.
        if (query.whereFields.length > 0) {
            lines.push("    where: z.strictObject({");
            for (const field of query.whereFields) {
                lines.push(`        ${field.name}: z.strictObject({`);
                for (const operator of field.operators) {
                    lines.push(`            ${operator}: ${field.expression}.optional(),`);
                }
                lines.push("        }).optional(),");
            }
            lines.push("    }).optional(),");
        }
        lines.push(...PAGING_FIELDS);
        lines.push(`    select: ${entitySchema ? entitySchema.querySelectName : "z.never()"},`);
        lines.push("});");
    }
    return lines.join("\n") + "\n";
}

/** The paging keys every read accepts, validated before they reach the SQL. See docs/queries.md. */
const PAGING_FIELDS = [
    "    limit: z.number().int().positive().optional(),",
    "    offset: z.number().int().nonnegative().optional(),",
];

/** Render the barrel that re-exports every query schema module. */
export function generateQueriesIndex(queries: ZodQuery[]): string {
    const lines = [HEADER];
    const entities = [...new Set(queries.map((query) => query.entity))].sort((a, b) => a.localeCompare(b));
    for (const entity of entities) {
        lines.push(`export * from "./query${entity}.ts";`);
    }
    return lines.join("\n") + "\n";
}

/** Render `primitives.ts`: one schema per primitive, a factory for a generic primitive. */
export function generatePrimitives(primitives: ZodPrimitive[]): string {
    const lines: string[] = [HEADER, 'import { z } from "zod";'];
    for (const primitive of primitives) {
        lines.push("");
        if (primitive.typeParameters) {
            lines.push(`export function ${primitive.schemaName}<${primitive.typeParameters}>() {`);
            lines.push(`    return ${primitive.expression};`);
            lines.push("}");
        } else {
            lines.push(`export const ${primitive.schemaName} = ${primitive.expression};`);
        }
    }
    return lines.join("\n") + "\n";
}

/** Render one entity module: its schema, its write schemas, and the matching write types. */
export function generateEntity(entity: ZodEntity, byName: Map<string, ZodEntity>): string {
    const lines: string[] = [HEADER, 'import { z } from "zod";'];
    lines.push(`import type { ${entity.name} } from "${entity.importSpecifier}";`);
    if (entity.usesPrimitives) {
        lines.push('import * as primitives from "./primitives.ts";');
    }
    for (const dependency of entity.dependencies) {
        const target = byName.get(dependency);
        if (target) {
            // An `@inlined` branch nests the target's insert schema, so its import joins the entity's.
            const inlined = entity.insertInlined.some((branch) => branch.target === dependency);
            const names = inlined ? `${target.schemaName}, ${target.insertName}` : target.schemaName;
            lines.push(`import { ${names} } from "${entityImport(target)}";`);
        }
    }

    lines.push("");
    lines.push(`export const ${entity.schemaName} = z.object({`);
    for (const field of entity.fields) {
        lines.push(`    ${field.name}: ${field.expression},`);
    }
    lines.push("});");

    lines.push("");
    const versioned = entity.required.some((name) => !entity.keys.includes(name));
    lines.push(
        versioned
            ? "/** A partial update: every field is optional except the key and the version. */"
            : "/** A partial update: every field is optional except the key. */",
    );
    lines.push(`export const ${entity.patchName} = ${entity.schemaName}`);
    if (entity.patchOmit.length > 0) {
        lines.push("    .omit({");
        for (const name of entity.patchOmit) {
            lines.push(`        ${name}: true,`);
        }
        lines.push("    })");
    }
    lines.push("    .partial()");
    lines.push("    .required({");
    for (const name of entity.required) {
        lines.push(`        ${name}: true,`);
    }
    lines.push("    })");
    lines.push("    .strict();");

    lines.push("");
    lines.push("/** The fields a create writes: a defaulted column may be omitted, and the database fills it. */");
    lines.push(`export const ${entity.insertName} = ${entity.schemaName}`);
    if (entity.insertOmit.length > 0) {
        lines.push("    .omit({");
        for (const name of entity.insertOmit) {
            lines.push(`        ${name}: true,`);
        }
        lines.push("    })");
    }
    if (entity.insertInlined.length > 0) {
        lines.push("    .extend({");
        for (const branch of entity.insertInlined) {
            const target = byName.get(branch.target);
            const insertName = target ? target.insertName : "z.never()";
            lines.push(`        ${branch.name}: ${insertName}.optional(),`);
        }
        lines.push("    })");
    }
    if (entity.insertOptional.length > 0) {
        lines.push("    .partial({");
        for (const name of entity.insertOptional) {
            lines.push(`        ${name}: true,`);
        }
        lines.push("    })");
    }
    lines.push("    .strict();");

    // The write types are the spec's, narrowed by the same omit lists the schemas use, so the type
    // a caller passes and the value the schema accepts name one field set. See docs/validation.md.
    lines.push("");
    lines.push(
        versioned
            ? "/** A partial update: every field is optional except the key and the version. */"
            : "/** A partial update: every field is optional except the key. */",
    );
    const patchBase =
        entity.patchOmit.length === 0
            ? `Partial<${entity.name}>`
            : `Omit<Partial<${entity.name}>, ${entity.patchOmit.map(quote).join(" | ")}>`;
    const required =
        entity.required.length === 0
            ? ""
            : ` & Required<Pick<${entity.name}, ${entity.required.map(quote).join(" | ")}>>`;
    lines.push(`export type ${entity.name}Patch = ${patchBase}${required};`);

    lines.push("");
    lines.push("/** The fields a create writes: a defaulted column may be omitted, and the database fills it. */");
    const insertOmitted = [...entity.insertOmit, ...entity.insertOptional];
    const insertBase =
        insertOmitted.length === 0
            ? entity.name
            : `Omit<${entity.name}, ${insertOmitted.map(quote).join(" | ")}>`;
    const insertOptionalType =
        entity.insertOptional.length === 0
            ? ""
            : ` & Partial<Pick<${entity.name}, ${entity.insertOptional.map(quote).join(" | ")}>>`;
    lines.push(`export type ${entity.name}Insert = ${insertBase}${insertOptionalType};`);

    // The key alone addresses a stored row, so a by-key write names it rather than the whole entity.
    // The schema is strict, like a patch or an insert, so a field the write ignores is a 400.
    if (entity.keys.length > 0) {
        lines.push("");
        lines.push("/** The key of one stored row: the shape a delete or other by-key write sends. */");
        const picked = entity.keys.map((name) => `${name}: true`).join(", ");
        lines.push(`export const ${entity.primaryKeyName} = ${entity.schemaName}.pick({ ${picked} }).strict();`);
        lines.push("");
        lines.push("/** The key of one stored row: what a delete or other by-key write addresses. */");
        lines.push(
            `export type ${entity.name}PrimaryKey = Pick<${entity.name}, ${entity.keys.map(quote).join(" | ")}>;`,
        );
    }

    return lines.join("\n") + "\n";
}

/** `"id"`, the quoted form a generated type alias uses. */
function quote(name: string): string {
    return JSON.stringify(name);
}

/** Render the barrel that re-exports the primitives and every entity module. */
export function generateIndex(model: ZodModel): string {
    const lines = [HEADER, 'export * from "./primitives.ts";'];
    for (const entity of model.entities) {
        lines.push(`export * from "${entityImport(entity)}";`);
    }
    if (model.queries.length > 0) {
        lines.push('export * from "./queries/index.ts";');
    }
    return lines.join("\n") + "\n";
}

/** Render every generated file, keyed by file name (including the barrels). */
export function generateZodSchemas(model: ZodModel): Map<string, string> {
    const files = new Map<string, string>();
    files.set(PRIMITIVES_FILE, generatePrimitives(model.primitives));
    const byName = new Map(model.entities.map((entity) => [entity.name, entity]));
    for (const entity of model.entities) {
        files.set(entity.fileName, generateEntity(entity, byName));
    }

    // Queries are grouped by the entity they read, so one file holds that entity's args schemas.
    const byEntity = new Map<string, ZodQuery[]>();
    for (const query of model.queries) {
        const group = byEntity.get(query.entity) ?? [];
        group.push(query);
        byEntity.set(query.entity, group);
    }
    for (const [entity, queries] of byEntity) {
        files.set(queryFileName(entity), generateQueryFile(entity, queries, byName));
    }
    if (model.queries.length > 0) {
        files.set(QUERIES_INDEX, generateQueriesIndex(model.queries));
    }

    files.set(INDEX_FILE, generateIndex(model));
    return files;
}

function main(): void {
    const project = new Project({ tsConfigFilePath: "tsconfig.json" });
    project.addSourceFilesAtPaths(SPEC_GLOB);
    const model = buildZodModel(project, { specGlob: DEFAULT_SPEC_GLOB, aliasGlob: SPEC_GLOB });

    for (const diagnostic of model.diagnostics) {
        console.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }

    if (model.diagnostics.length > 0) {
        process.exitCode = 1;
        return;
    }

    const outIndex = process.argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : process.argv[outIndex + 1];
    if (!outDir) {
        console.error("--out needs a directory");
        process.exitCode = 1;
        return;
    }

    const files = generateZodSchemas(model);
    for (const [name, content] of files) {
        const target = join(outDir, name);
        mkdirSync(dirname(target), { recursive: true });
        writeFileSync(target, content);
    }
    console.log(`wrote ${files.size} files to ${outDir}`);
}

if (import.meta.main) {
    main();
}
