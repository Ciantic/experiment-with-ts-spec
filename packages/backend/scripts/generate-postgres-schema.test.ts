describe("generateSchema @pgAutoIncrement", () => {
    const thing = `export interface Thing {
        /**
         * @primaryKey
         * @pgAutoIncrement
         */
        id: Counter;
        name: string;
    }`;

    it("makes the key an identity column the database assigns", () => {
        const { sql, diagnostics } = generate({ domain: { Thing: thing } });

        expect(diagnostics).toEqual([]);
        expect(sql).toContain('"id" integer generated by default as identity not null');
        expect(sql).toContain('constraint "thing_pkey" primary key ("id")');
    });

    it("asks Postgres for the value rather than for `always`, so a write may name the key", async () => {
        const { sql } = generate({ domain: { Thing: thing } });
        const db = new PGlite();
        await db.exec(sql);

        const assigned = await db.query<{ id: number }>(
            `insert into "thing" ("name") values ('first') returning "id";`,
        );
        expect(assigned.rows).toEqual([{ id: 1 }]);

        // `always` would reject this, and an upsert has to name the key it claims to match a conflict.
        const claimed = await db.query<{ id: number }>(
            `insert into "thing" ("id", "name") values (10, 'claimed') returning "id";`,
        );
        expect(claimed.rows).toEqual([{ id: 10 }]);

        // The claim does not move the sequence, so the next assigned key continues from where it stood.
        const next = await db.query<{ id: number }>(
            `insert into "thing" ("name") values ('second') returning "id";`,
        );
        expect(next.rows).toEqual([{ id: 2 }]);
    });

    it("reports @pgAutoIncrement on a field that is not the primary key", () => {
        const { diagnostics } = generate({
            domain: {
                Thing: `export interface Thing {
                    /** @primaryKey */
                    key: GUID;
                    /**
                     * @pgAutoIncrement
                     */
                    counter: Counter;
                }`,
            },
        });

        expect(messages(diagnostics)).toEqual(["`counter`: @pgAutoIncrement must be on a @primaryKey field"]);
    });

    it("reports a key whose storage type is not an integer", () => {
        const { diagnostics } = generate({
            domain: {
                Thing: `export interface Thing {
                    /**
                     * @primaryKey
                     * @pgAutoIncrement
                     */
                    id: GUID;
                }`,
            },
        });

        expect(messages(diagnostics)).toEqual([
            "`id`: @pgAutoIncrement needs an integer column, and `uuid` is not one of: smallint, integer, bigint, int2, int4, int8",
        ]);
    });
});

