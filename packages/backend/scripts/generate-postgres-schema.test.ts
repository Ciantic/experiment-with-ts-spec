/** Unit tests for generateSchema, driven by self-contained fixtures. */
import { describe, expect, it } from "vitest";
import { Project } from "ts-morph";
import { generateSchema, type Diagnostic } from "./generate-postgres-schema.ts";

const SPEC_GLOB = "fixtures/domain/**/*.ts";

interface Fixture {
    domain: Record<string, string>;
}

/** Primitive aliases a fixture field can reference, each declaring its own Postgres type. */
const PRIMITIVES = `
/**
 * @primitive
 * @pgtype uuid
 * @zod z.uuid()
 */
export type GUID = string;

/**
 * @primitive
 * @pgtype decimal
 * @zod z.string()
 */
export type Decimal = string;

/**
 * @primitive
 * @pgtype text
 * @zod z.email()
 */
export type Email = string;

/**
 * @primitive
 * @pgtype int8
 * @zod z.bigint()
 */
export type Version = bigint;
`.trim();

/** Generate from an in-memory project, so no fixture depends on the real spec. */
function generate(fixture: Fixture) {
    const project = new Project({ useInMemoryFileSystem: true });
    project.createSourceFile("fixtures/domain/primitives.ts", PRIMITIVES);
    for (const [name, text] of Object.entries(fixture.domain)) {
        project.createSourceFile(`fixtures/domain/${name}.ts`, text);
    }
    return generateSchema(project, { specGlob: SPEC_GLOB, aliasGlob: SPEC_GLOB });
}

function messages(diagnostics: Diagnostic[]): string[] {
    return diagnostics.map((diagnostic) => diagnostic.message);
}

describe("generateSchema output", () => {
    it("starts with the do-not-edit header", () => {
        const { sql } = generate({ domain: { Thing: "export interface Thing {\n    /** @primaryKey */\n    id: string; }" } });

        expect(sql.startsWith("-- Generated by scripts/generate-postgres-schema.ts. Do not edit.\n")).toBe(true);
    });

    it("maps keyword types to Postgres types", () => {
        const { sql } = generate({
            domain: {
                Thing: `export interface Thing {
                    /** @primaryKey */
                    id: string;
                    name: string;
                    count: number;
                    flag: boolean;
                    big: bigint;
                }`,
            },
        });

        expect(sql).toContain('"name" text not null');
        expect(sql).toContain('"count" float8 not null');
        expect(sql).toContain('"flag" boolean not null');
        expect(sql).toContain('"big" int8 not null');
    });

    it("maps named types to the Postgres type their @pgtype declares", () => {
        const { sql } = generate({
            domain: {
                Thing: `export interface Thing {
                    /** @primaryKey */
                    id: GUID;
                    amount: Decimal;
                    rate: Decimal;
                    email: Email;
                    at: Date;
                }`,
            },
        });

        expect(sql).toContain('"id" uuid not null');
        expect(sql).toContain('"amount" decimal not null');
        expect(sql).toContain('"rate" decimal not null');
        expect(sql).toContain('"email" text not null');
        expect(sql).toContain('"at" timestamptz not null');
    });

    it("derives a foreign key's column type from the target entity's key, not a fixed type", () => {
        const { sql } = generate({
            domain: {
                // Version is @pgtype int8, so a key of that type proves the type is not hardcoded.
                Owner: "export interface Owner {\n    /** @primaryKey */\n    id: Version; }",
                Thing: `export interface Thing {
                    /** @primaryKey */
                    id: GUID;
                    /** @foreignKey Owner */
                    ownerId: OwnerId;
                    /** @relation */
                    owner: Owner;
                }`,
            },
        });

        expect(sql).toContain('"ownerId" int8 not null references "owner"("id")');
    });

    it("types a @foreignKey field from the table it points at", () => {
        const { sql } = generate({
            domain: {
                Owner: "export interface Owner {\n    /** @primaryKey */\n    id: Version; }",
                Thing: "export interface Thing {\n    /** @primaryKey */\n    id: GUID; \n    /** @foreignKey Owner */\n    ownerId: OwnerId; }",
            },
        });

        expect(sql).toContain('"ownerId" int8 not null references "owner"("id")');
    });

    it("makes an optional field nullable", () => {
        const { sql } = generate({
            domain: { Thing: "export interface Thing {\n    /** @primaryKey */\n    id: string; note?: string; }" },
        });

        expect(sql).toContain('"note" text');
        expect(sql).not.toContain('"note" text not null');
    });

    it("treats id as a not-null primary key even when optional", () => {
        const { sql } = generate({
            domain: { Thing: "export interface Thing {\n    /** @primaryKey */\n    id?: GUID; }" },
        });

        expect(sql).toContain('"id" uuid not null');
        expect(sql).toContain('constraint "thing_pkey" primary key ("id")');
    });

    it("names the primary key from @primaryKey, not from the field name", () => {
        const { sql } = generate({
            domain: { Thing: "export interface Thing {\n    /** @primaryKey */\n    key: GUID; }" },
        });

        expect(sql).toContain('constraint "thing_pkey" primary key ("key")');
        expect(sql).not.toContain('"id"');
    });

    it("does not treat a field named id as the primary key", () => {
        const { sql, diagnostics } = generate({
            domain: { Thing: "export interface Thing { id: GUID; }" },
        });

        expect(messages(diagnostics)).toContain("`Thing`: no `@primaryKey` field");
        expect(sql).not.toContain("primary key");
    });

    it("adds a unique constraint for @unique", () => {
        const { sql } = generate({
            domain: {
                Thing: `export interface Thing {
                    /** @primaryKey */
                    id: GUID;
                    /** @unique */
                    code: string;
                }`,
            },
        });

        expect(sql).toContain('"code" text not null unique');
    });

    it("derives the table name from the interface in snake_case", () => {
        const { sql } = generate({
            domain: { LineItem: "export interface LineItem {\n    /** @primaryKey */\n    id: GUID; }" },
        });

        expect(sql).toContain('create table "line_item"');
    });

    it("lets @table override the table name", () => {
        const { sql } = generate({
            domain: { Person: "/** @table people */\nexport interface Person {\n    /** @primaryKey */\n    id: GUID; }" },
        });

        expect(sql).toContain('create table "people"');
    });
});

describe("generateSchema types", () => {
    it("emits a CHECK for a union of string literals", () => {
        const { sql } = generate({
            domain: { Thing: `export interface Thing {
    /** @primaryKey */
    id: GUID; status: "draft" | "sent"; }` },
        });

        expect(sql).toContain(`constraint "thing_status_check" check ("status" in ('draft', 'sent'))`);
    });

    it("escapes single quotes in CHECK values", () => {
        const { sql } = generate({
            domain: { Thing: `export interface Thing {
    /** @primaryKey */
    id: GUID; status: "it's" | "plain"; }` },
        });

        expect(sql).toContain(`check ("status" in ('it''s', 'plain'))`);
    });

    it("treats a lone literal as a closed set of one", () => {
        const { sql, diagnostics } = generate({
            domain: { Thing: `export interface Thing {
    /** @primaryKey */
    id: GUID; status: "only"; }` },
        });

        expect(diagnostics).toEqual([]);
        expect(sql).toContain(`check ("status" in ('only'))`);
    });

    it("does not constrain an open union", () => {
        const { sql } = generate({
            domain: { Thing: `export interface Thing {
    /** @primaryKey */
    id: GUID; unit: "hours" | (string & {}); }` },
        });

        expect(sql).toContain('"unit" text not null');
        expect(sql).not.toContain('"unit" in (');
    });

    it("emits a nullable foreign key for an optional @relation", () => {
        const { sql } = generate({
            domain: {
                Owner: "export interface Owner {\n    /** @primaryKey */\n    id: GUID; }",
                Thing: `export interface Thing {
                    /** @primaryKey */
                    id: GUID;
                    /** @foreignKey Owner */
                    ownerId?: OwnerId;
                    /** @relation */
                    owner?: Owner;
                }`,
            },
        });

        expect(sql).toContain('"ownerId" uuid references "owner"("id")');
        expect(sql).not.toContain('"ownerId" uuid not null');
    });

    it("emits a mandatory foreign key for a required @relation", () => {
        const { sql } = generate({
            domain: {
                Owner: "export interface Owner {\n    /** @primaryKey */\n    id: GUID; }",
                Thing: `export interface Thing {
                    /** @primaryKey */
                    id: GUID;
                    /** @foreignKey Owner */
                    ownerId: OwnerId;
                    /** @relation */
                    owner: Owner;
                }`,
            },
        });

        expect(sql).toContain('"ownerId" uuid not null references "owner"("id")');
    });

    it("emits one column for @relation and its declared id field, not two", () => {
        const { sql, diagnostics } = generate({
            domain: {
                Owner: "export interface Owner {\n    /** @primaryKey */\n    id: GUID; }",
                Thing: `export interface Thing {
                    /** @primaryKey */
                    id: GUID;
                    /** @foreignKey Owner */
                    ownerId?: OwnerId;
                    /** @relation */
                    owner?: Owner;
                }`,
            },
        });

        expect(diagnostics).toEqual([]);
        expect(sql.split('"ownerId"')).toHaveLength(2);
    });

    it("skips a child collection and emits no column for it", () => {
        const { sql, diagnostics } = generate({
            domain: {
                Row: "export interface Row {\n    /** @primaryKey */\n    id: GUID; \n    /** @foreignKey Parent */\n    parentId: ParentId; }",
                Parent: `export interface Parent {
                    /** @primaryKey */
                    id: GUID;
                    /** @children */
                    rows: Row[];
                }`,
            },
        });

        expect(sql).not.toContain('"rows"');
        expect(diagnostics).toEqual([]);
    });
});

