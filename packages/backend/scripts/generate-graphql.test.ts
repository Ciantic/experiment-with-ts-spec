/** Unit tests for the GraphQL generator, driven by self-contained table fixtures. See docs/graphql.md. */
import { describe, expect, it } from "vitest";
import { assertValidSchema } from "graphql";
import { Project } from "ts-morph";
import { schema } from "../src/graphql/schema.js";
import { generateGraphql, generateLoaders, generateScalars, generateSchema } from "./generate-graphql.js";
import { readGraphScalars, type Column, type GraphField, type GraphFieldKind, type Table } from "./spec-model.js";

function column(name: string, extras: Partial<Column> = {}): Column {
    return { name, sqlType: "text", notNull: true, primaryKey: false, unique: false, ...extras };
}

function graphField(name: string, kind: GraphFieldKind, extras: Partial<GraphField> = {}): GraphField {
    return {
        name,
        kind,
        typeName: "string",
        scalarName: undefined,
        target: undefined,
        column: undefined,
        foreignKeyColumn: undefined,
        inlinedIdColumn: undefined,
        inlinedColumns: [],
        notNull: false,
        isArray: false,
        ...extras,
    };
}

function table(name: string, interfaceName: string, columns: Column[], graphFields: GraphField[]): Table {
    return {
        name,
        interfaceName,
        importSpecifier: `spec/domain/${interfaceName}.js`,
        columns,
        graphFields,
        sameRowAssignments: [],
        rollups: new Map(),
    };
}

const owner = table("owner", "Owner", [column("id", { sqlType: "uuid", primaryKey: true }), column("name")], [
    graphField("id", "scalar", { typeName: "OwnerId", scalarName: "BrandedId", notNull: true, column: "id" }),
    graphField("name", "scalar", { typeName: "string", scalarName: "string", notNull: true, column: "name" }),
]);

const widget = table(
    "widget",
    "Widget",
    [
        column("id", { sqlType: "uuid", primaryKey: true }),
        column("name"),
        column("ownerId", { sqlType: "uuid", references: { table: "owner", column: "id" } }),
    ],
    [
        graphField("id", "scalar", { typeName: "WidgetId", scalarName: "BrandedId", notNull: true, column: "id" }),
        graphField("name", "scalar", { typeName: "string", scalarName: "string", notNull: true, column: "name" }),
        graphField("total", "scalar", { typeName: "Money", scalarName: "Money", notNull: true, column: "total" }),
        graphField("owner", "relation", { typeName: "Owner", target: "Owner", column: "ownerId" }),
        graphField("parts", "children", { typeName: "Part", target: "Part", isArray: true }),
    ],
);

const part = table(
    "part",
    "Part",
    [
        column("id", { sqlType: "uuid", primaryKey: true }),
        column("widgetId", { sqlType: "uuid", references: { table: "widget", column: "id" } }),
        column("label"),
    ],
    [
        graphField("id", "scalar", { typeName: "PartId", scalarName: "BrandedId", notNull: true, column: "id" }),
        graphField("widgetId", "scalar", { typeName: "WidgetId", scalarName: "BrandedId", notNull: true, column: "widgetId" }),
        graphField("label", "scalar", { typeName: "string", scalarName: "string", notNull: true, column: "label" }),
    ],
);

// A snapshot entity: its owner is inlined into prefixed columns rather than linked by foreign key.
const ticket = table(
    "ticket",
    "Ticket",
    [
        column("id", { sqlType: "uuid", primaryKey: true }),
        column("ownerId", { sqlType: "uuid" }),
        column("ownerName"),
    ],
    [
        graphField("id", "scalar", { typeName: "TicketId", scalarName: "BrandedId", notNull: true, column: "id" }),
        graphField("owner", "inlined", {
            typeName: "Owner",
            target: "Owner",
            inlinedIdColumn: "ownerId",
            inlinedColumns: [
                { field: "id", column: "ownerId" },
                { field: "name", column: "ownerName" },
            ],
        }),
    ],
);

/** The `@graphql` map a test provides, standing in for the spec's annotations. */
const scalars = new Map([
    ["BrandedId", "ID"],
    ["Money", "Money"],
]);

function fixture(): Map<string, Table> {
    const widgetWithChildren = widget.graphFields.map((field) =>
        field.kind === "children" ? { ...field, foreignKeyColumn: "widgetId" } : field,
    );
    return new Map([
        ["Owner", owner],
        ["Widget", { ...widget, graphFields: widgetWithChildren }],
        ["Part", part],
        ["Ticket", ticket],
    ]);
}

describe("generateScalars", () => {
    it("starts with the do-not-edit header", () => {
        expect(generateScalars(["Money"]).startsWith("// Generated by scripts/generate-graphql.ts. Do not edit.\n")).toBe(true);
    });

    it("emits a scalar only for the names it is given", () => {
        const code = generateScalars(["Money"]);

        expect(code).toContain('name: "Money"');
        expect(code).not.toContain('name: "Quantity"');
    });

    it("emits nothing but the header when no custom scalars are referenced", () => {
        const code = generateScalars([]);

        expect(code).not.toContain("GraphQLScalarType");
    });
});

describe("generateLoaders", () => {
    it("batches a by-id loader per entity", () => {
        const code = generateLoaders(fixture());

        expect(code).toContain("const ownerById = new DataLoader<string, Row | null>");
        expect(code).toContain('from "owner" where "id" = any($1::uuid[])');
        expect(code).toContain("return ids.map((id) => byId.get(id) ?? null);");
    });

    it("batches a children loader per @children field, keyed by the foreign key", () => {
        const code = generateLoaders(fixture());

        expect(code).toContain("const widgetParts = new DataLoader<string, Row[]>");
        expect(code).toContain('from "part" where "widgetId" = any($1::uuid[])');
        expect(code).toContain("return ids.map((id) => groups.get(id) ?? []);");
    });

    it("emits a paged list per entity and the per-request context", () => {
        const code = generateLoaders(fixture());

        expect(code).toContain("const listWidget = async (options: ListOptions = {}): Promise<Row[]>");
        expect(code).toContain('order by "id" limit $1::int offset $2::int');
        expect(code).toContain("export interface GraphQLContext {");
        expect(code).toContain("loaders: Loaders;");
    });
});

describe("generateSchema", () => {
    it("emits one object type per entity with a non-null key", () => {
        const code = generateSchema(fixture(), scalars);

        expect(code).toContain('const WidgetType = new GraphQLObjectType({');
        expect(code).toContain('name: "Widget",');
        expect(code).toContain("id: { type: new GraphQLNonNull(GraphQLID) },");
    });

    it("maps a scalar through its annotation, not by knowing its spec name", () => {
        const code = generateSchema(fixture(), scalars);

        // `total` is a `Money` field, resolved through the provided @graphql map to a custom scalar.
        expect(code).toContain("total: { type: new GraphQLNonNull(Money) },");
        expect(code).toContain('import { Money } from "./scalars.js";');
    });

    it("falls back to the TypeScript type when a scalar is unannotated", () => {
        const code = generateSchema(
            new Map([["Thing", table("thing", "Thing", [column("id", { sqlType: "uuid", primaryKey: true }), column("count")], [
                graphField("id", "scalar", { typeName: "ThingId", scalarName: "ThingId", notNull: true, column: "id" }),
                graphField("count", "scalar", { typeName: "number", scalarName: "number", notNull: true, column: "count" }),
            ])]]),
            scalars,
        );

        // An unannotated string-ish type is not an ID: only an annotation or a builtin decides.
        expect(code).toContain("id: { type: new GraphQLNonNull(GraphQLString) },");
        expect(code).toContain("count: { type: new GraphQLNonNull(GraphQLFloat) },");
    });

    it("resolves a @relation through its by-id loader", () => {
        const code = generateSchema(fixture(), scalars);

        expect(code).toContain("parent.ownerId == null ? null : context.loaders.ownerById.load(String(parent.ownerId))");
    });

    it("resolves @children through the foreign-key loader keyed on the parent key", () => {
        const code = generateSchema(fixture(), scalars);

        expect(code).toContain("context.loaders.widgetParts.load(String(parent.id))");
    });

    it("rebuilds an @inlined value from prefixed columns without a loader", () => {
        const code = generateSchema(fixture(), scalars);

        expect(code).toContain('(parent) => (parent["ownerId"] == null ? null : { id: parent["ownerId"], name: parent["ownerName"] })');
    });

    it("exposes a single and a paged list root per entity", () => {
        const code = generateSchema(fixture(), scalars);

        expect(code).toContain("widget: {");
        expect(code).toContain("widgets: {");
        expect(code).toContain("resolve: (_root, args, context: GraphQLContext) => context.loaders.widgetById.load(String(args.id)),");
        expect(code).toContain("resolve: (_root, args, context: GraphQLContext) => context.loaders.listWidget(args),");
    });
});

describe("generateGraphql", () => {
    it("emits scalars, loaders, schema, and an index", () => {
        const files = generateGraphql(fixture(), scalars);

        expect([...files.keys()].sort()).toEqual(["index.ts", "loaders.ts", "scalars.ts", "schema.ts"]);
        expect(files.get("index.ts")).toContain("export function createContext(db: RowExecutor): GraphQLContext {");
    });
});

describe("readGraphScalars", () => {
    it("reads @graphql annotations from type aliases, ignoring unannotated ones", () => {
        const project = new Project({ useInMemoryFileSystem: true });
        project.createSourceFile(
            "/spec/vocabulary.ts",
            [
                "/**",
                " * A monetary amount.",
                " *",
                " * @graphql Money",
                " */",
                "export type Money = string;",
                "export type Plain = string;",
            ].join("\n"),
        );

        const read = readGraphScalars(project, { aliasGlob: "/spec/**/*.ts" });

        expect(read.get("Money")).toBe("Money");
        expect(read.has("Plain")).toBe(false);
    });

    it("does not read an annotation left on an import statement", () => {
        const project = new Project({ useInMemoryFileSystem: true });
        // A JSDoc above an import attaches to the import, so it is not a type annotation.
        project.createSourceFile(
            "/spec/vocabulary.ts",
            [
                "/**",
                " * @graphql Money",
                " */",
                'import type { Decimal } from "./decimal.js";',
                "export type Money = Decimal;",
            ].join("\n"),
        );

        const read = readGraphScalars(project, { aliasGlob: "/spec/**/*.ts" });

        expect(read.has("Money")).toBe(false);
    });
});

describe("the committed GraphQL schema", () => {
    it("is a valid schema", () => {
        expect(() => assertValidSchema(schema)).not.toThrow();
    });
});