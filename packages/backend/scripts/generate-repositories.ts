/** InvoiceInsert -> repositories/invoiceInsertSchema.ts: the module holding one write type. */
export function validationFileName(writeType: string): string {
    const kind = writeType.endsWith("PrimaryKey")
        ? "PrimaryKey"
        : writeType.endsWith("Insert")
          ? "Insert"
          : writeType.endsWith("Upsert")
            ? "Upsert"
            : "Patch";
    return `repositories/${lowerFirst(writeType.slice(0, -kind.length))}${kind}Schema.ts`;
}

/** The module for one operation, named after the function it exports: ("create", "Invoice") -> createInvoice.ts. */
function operationFileName(operation: WriteOperation, entity: string): string {
    return `${operation}${entity}.ts`;
}

/** A column's value expression and the type its placeholder is cast to. */
interface ValueEntry {
    expression: string;
    sqlType: string;
}

/** The accessor that reads a column from a row, e.g. `customer?.id` for an inlined optional field. */
function readExpression(column: Column): string {
    return `row.${column.read ?? column.name}`;
}

/** The value entry for a plain write, where every column of the row is present. */
function readEntry(column: Column): ValueEntry {
    return { expression: readExpression(column), sqlType: column.sqlType };
}

/** The aliases an update carries: the row it writes, and the supplied values it reads. */
const TARGET_ALIAS = "u";

const VALUES_ALIAS = "v";

/** The suffix a presence column carries; a spec field name cannot hold `#`, so it cannot collide. */
const PRESENCE_SUFFIX = "#present";

/** One equality between the row an alias addresses and the values a patch supplies. */
function aliasMatch(column: Column, target: string, values: string): string {
    return `${target}.${quote(column.name)} = ${values}.${quote(column.name)}`;
}

/** The `set` entry that takes a supplied column from the values row and keeps the stored one otherwise. */
function keptAssignment(column: Column): string {
    return `${quote(column.name)} = ${suppliedValue(column, `${TARGET_ALIAS}.${quote(column.name)}`)}`;
}

/** The `set` entry of an entity with no writable column: its key to the key the stored row already holds. */
function identityAssignment(column: Column, target: string): string {
    return `${quote(column.name)} = ${target}.${quote(column.name)}`;
}

/** The value a bound column takes when a row supplies it, and the given one otherwise. */
function suppliedValue(column: Column, fallback: string): string {
    const name = quote(column.name);
    return `case when ${VALUES_ALIAS}.${quote(column.name + PRESENCE_SUFFIX)} then ${VALUES_ALIAS}.${name} else ${fallback} end`;
}

/** One array a chunked statement binds: what a row contributes to it, and the cast it carries. */
export interface BoundArray {
    /** The JS variable the array is built in. */
    variable: string;
    /** The alias column `unnest` exposes the array as. */
    alias: string;
    /** The cast the placeholder carries. */
    cast: string;
    /** The TS type the array is declared with. */
    type: string;
    /** What one row pushes into the array. */
    element: string;
}

/** The array carrying a column's values, with a null where the row has none to give. */
function valueArray(column: Column): BoundArray {
    return {
        variable: `${column.name}Values`,
        alias: column.name,
        cast: `${column.sqlType}[]`,
        type: "Array<unknown>",
        element: `${readExpression(column)} ?? null`,
    };
}

/** A column with the test for whether a row supplied it, which a create derives and a patch records. */
type SuppliedColumn = Column & { supplied: string };

/** The column with a test for whether a row supplied it, falling back to the field the value is read from. */
function suppliedColumn(column: Column): SuppliedColumn {
    return { ...column, supplied: column.supplied ?? `${readExpression(column)} !== undefined` };
}

/** The array carrying whether each row supplied a column, so an omitted field takes its fallback. */
function presenceArray(column: SuppliedColumn): BoundArray {
    return {
        variable: `${column.name}Present`,
        alias: `${column.name}${PRESENCE_SUFFIX}`,
        cast: "bool[]",
        type: "boolean[]",
        element: column.supplied,
    };
}

/** The arrays a statement binds for one column: its values, and whether each row supplied them. */
function columnArrays(column: Column, mayBeAbsent: boolean): BoundArray[] {
    const arrays = [valueArray(column)];
    return mayBeAbsent ? [...arrays, presenceArray(suppliedColumn(column))] : arrays;
}

/** The lines declaring every bound array and filling it from the chunk, one row at a time. */
function bindArrays(arrays: BoundArray[]): string[] {
    const indent = "            ";
    const lines = arrays.map((bound) => `${indent}const ${bound.variable}: ${bound.type} = [];`);
    lines.push(`${indent}for (const row of chunk) {`);
    for (const bound of arrays) {
        lines.push(`${indent}    ${bound.variable}.push(${bound.element});`);
    }
    lines.push(`${indent}}`);
    return lines;
}

/** The fragments that build one statement, and the arrays it binds. */
export interface ChunkStatement {
    fragments: string[];
    arrays: BoundArray[];
}

/** The SQL a statement runs: its fragments with nothing between them, the way the module concatenates them. */
export function statementSql(statement: ChunkStatement): string {
    return statement.fragments.join("");
}

/** The `await tx.query(…)` lines: the SQL built from its fragments, then the arrays it binds. */
function chunkQuery(statement: ChunkStatement): string[] {
    const lines = ["            const result = await tx.query("];
    for (const [index, fragment] of statement.fragments.entries()) {
        const indent = index === 0 ? "                " : "                    ";
        lines.push(`${indent}'${sqlLiteral(fragment)}${index === statement.fragments.length - 1 ? "'," : "' +"}`);
    }
    lines.push(`                [${statement.arrays.map((bound) => bound.variable).join(", ")}],`);
    lines.push("            );");
    return lines;
}

/** The text as the body of a single-quoted JS literal, since a column default holds quotes of its own. */
function sqlLiteral(fragment: string): string {
    return fragment.replace(/\\/g, "\\\\").replace(/'/g, "\\'");
}

/** The `from unnest(…) as v(…)` fragments: the placeholder casts, then the alias columns they expose. */
function unnestFragments(arrays: BoundArray[]): string[] {
    const casts = arrays.map((bound, index) => `$${index + 1}::${bound.cast}`).join(", ");
    return [`from unnest(${casts}) as ${VALUES_ALIAS}(`, `${arrays.map((bound) => quote(bound.alias)).join(", ")}) `];
}

/** The expression reading a written row's key, matching the way `keyOf` builds one from a patch. */
function returnedKeyExpression(primaryKeys: Column[]): string {
    return primaryKeys.map((column) => `String(row[${JSON.stringify(column.name)}])`).join(' + "/" + ');
}

/** The `const keyOf` that turns a written row, as the statement returned it, into the entity's key. */
function keyReader(entity: string, primaryKeys: Column[]): string {
    const fields = primaryKeys
        .map(
            (column) =>
                `${column.name}: row[${JSON.stringify(column.name)}] as ${entity}PrimaryKey[${JSON.stringify(column.name)}]`,
        )
        .join(", ");
    return `const keyOf = (row: Record<string, unknown>): ${entity}PrimaryKey => ({ ${fields} });`;
}

/** The indentation and row source of the loop that gathers values for the delete's `using (values …)` list. */
interface ValueLoop {
    /** The indentation every emitted line carries. */
    indent: string;
    /** The rows the loop walks: the whole array, or one chunk of it. */
    source: string;
}

/** The lines that gather the given values into `parameters` and `tuples`, one tuple per row. */
function collectValues(entries: ValueEntry[], loop: ValueLoop): string[] {
    const { indent, source } = loop;
    const values = entries.map((entry) => entry.expression).join(", ");
    // The `values` alias is otherwise untyped text; casting each placeholder keeps keys and
    // assignments matching the column type (a bare text value would not compare to a uuid key).
    const tuple = entries
        .map((entry, index) => `"$" + (offset + ${index + 1}) + "::${entry.sqlType}"`)
        .join(' + ", " + ');
    return [
        `${indent}const parameters: unknown[] = [];`,
        `${indent}const tuples: string[] = [];`,
        `${indent}for (const row of ${source}) {`,
        `${indent}    const values = [${values}];`,
        `${indent}    parameters.push(...values);`,
        `${indent}    const offset = parameters.length - values.length;`,
        `${indent}    tuples.push("(" + ${tuple} + ")");`,
        `${indent}}`,
    ];
}

/** The header and type imports every operation module carries, naming the write types it uses. */
function modulePrologue(writeTypes: string | string[], executorImport?: string): string[] {
    const types = typeof writeTypes === "string" ? [writeTypes] : writeTypes;
    return [
        HEADER,
        // The repository, the wire schema, and the client all name the one type validation declares.
        ...types.map((writeType) => `import type { ${writeType} } from "validation/${validationFileName(writeType)}";`),
        executorImport ?? 'import type { SqlExecutor } from "../sql-executor.ts";',
        "",
    ];
}

/** The `where` that matches each row of the `data` alias to the row it addresses. */
function keyMatch(table: Table, primaryKeys: Column[]): string {
    return primaryKeys.map((column) => aliasMatch(column, quote(table.name), "data")).join(" and ");
}

/** The JS expression naming the row a patch addresses, for the message of a rejected patch. */
function keyExpression(primaryKeys: Column[]): string {
    return primaryKeys.map((column) => readExpression(column)).join(' + "/" + ');
}

/** The columns a patch writes: every column but the key, which addresses a row, and the database-owned ones. */
function patchColumns(table: Table): Column[] {
    return table.columns.filter((column) => !column.primaryKey && column.updatable !== false);
}

/**
 * The optimistic-lock column, which a write claims instead of assigning. It is always patchable, since
 * `isUpdatable` accepts a `@version` field whatever else it carries, so a patch finds it here too.
 * See docs/versioning.md.
 */
function versionColumn(table: Table): Column | undefined {
    return table.columns.find((column) => column.version);
}

/** The insert a create runs, planned from the table alone: the statement's fragments and the arrays it binds. */
export function createStatement(table: Table): ChunkStatement {
    // A create writes the insertable fields, the same set `<entity>InsertSchema` accepts.
    const insertColumns = table.columns.filter((column) => column.insertable !== false);
    // A defaulted column may be absent from a row, so it binds a flag and falls back to its default.
    const arrays = insertColumns.flatMap((column) => columnArrays(column, column.default !== undefined));
    const selectItems = insertColumns.map((column) => {
        const value = `${VALUES_ALIAS}.${quote(column.name)}`;
        return column.default === undefined ? value : suppliedValue(column, column.default);
    });
    const insertColumnNames = insertColumns.map((column) => quote(column.name)).join(", ");
    const primaryKeys = table.columns.filter((column) => column.primaryKey);
    return {
        fragments: [
            `insert into ${quote(table.name)} (${insertColumnNames}) select `,
            ...selectItems.map((item, index) => `${item}${index === selectItems.length - 1 ? " " : ", "}`),
            ...unnestFragments(arrays),
            // The assigned keys come back, so a create reports the rows it wrote and a short count stays detectable.
            `returning ${primaryKeys.map((column) => `${quote(table.name)}.${quote(column.name)}`).join(", ")}`,
        ],
        arrays,
    };
}

/** Render `create<Entity>`: a chunk of rows per insert, returning the keys it wrote in the order it carried them. */
export function generateCreate(table: Table): string {
    const entity = table.interfaceName;
    const statement = createStatement(table);
    const { arrays } = statement;
    const primaryKeys = table.columns.filter((column) => column.primaryKey);
    const lines = modulePrologue(
        [`${entity}Insert`, `${entity}PrimaryKey`],
        'import { MAX_STATEMENT_PARAMETERS, resultRows, type SqlExecutor } from "../sql-executor.ts";',
    );

    lines.push("/** The key a written row was given, as the insert returned it. */");
    lines.push(keyReader(entity, primaryKeys));
    lines.push("");
    lines.push("/** The parameters one row costs: one per bound array, so a chunk stays inside the limit. */");
    lines.push(`const PARAMETERS_PER_ROW = ${arrays.length};`);
    lines.push("");
    lines.push("/** The rows one insert carries, so its parameters stay inside MAX_STATEMENT_PARAMETERS. */");
    lines.push("const ROWS_PER_STATEMENT = Math.floor(MAX_STATEMENT_PARAMETERS / PARAMETERS_PER_ROW);");
    lines.push("");
    lines.push(
        `export async function create${entity}(db: SqlExecutor, rows: ${entity}Insert[]): Promise<${entity}PrimaryKey[]> {`,
    );
    lines.push("    if (rows.length === 0) {");
    lines.push("        return [];");
    lines.push("    }");
    lines.push(`    const keys: ${entity}PrimaryKey[] = [];`);
    lines.push("    const write = async (tx: SqlExecutor): Promise<void> => {");
    lines.push("        for (let start = 0; start < rows.length; start += ROWS_PER_STATEMENT) {");
    lines.push("            const chunk = rows.slice(start, start + ROWS_PER_STATEMENT);");
    lines.push(...bindArrays(arrays));
    lines.push(...chunkQuery(statement));
    // An insert writes every row it carries, so a short count is lost data rather than a caller's mistake. See docs/repositories.md.
    lines.push("            const written = resultRows(result);");
    lines.push("            if (written.length !== chunk.length) {");
    lines.push(
        `                throw new Error('the insert wrote ' + written.length + ' of the ' + chunk.length + ' ${table.name} rows this create supplied');`,
    );
    lines.push("            }");
    lines.push("            keys.push(...written.map(keyOf));");
    lines.push("        }");
    lines.push("    };");
    // One statement is atomic on its own; only a call that spills past the limit opens a boundary.
    lines.push("    if (rows.length <= ROWS_PER_STATEMENT) {");
    lines.push("        await write(db);");
    lines.push("        return keys;");
    lines.push("    }");
    lines.push("    await db.transaction(write);");
    lines.push("    return keys;");
    lines.push("}");

    return lines.join("\n") + "\n";
}

/** The patch an update runs, planned from the table alone: the statement's fragments and the arrays it binds. */
export function updateStatement(table: Table): ChunkStatement {
    const primaryKeys = table.columns.filter((column) => column.primaryKey);
    const patchable = patchColumns(table);
    // The version is the optimistic-lock precondition, not an assignment; the trigger increments it.
    const version = versionColumn(table);
    const setColumns = patchable.filter((column): column is SuppliedColumn => column.supplied !== undefined);
    const arrays = [
        ...primaryKeys.flatMap((column) => columnArrays(column, false)),
        ...(version === undefined ? [] : columnArrays(version, false)),
        ...setColumns.flatMap((column) => columnArrays(column, true)),
    ];
    const assignments =
        setColumns.length === 0
            ? [identityAssignment(primaryKeys[0] as Column, TARGET_ALIAS)]
            : setColumns.map(keptAssignment);
    // A patch addresses the row at the version the caller holds, so a stale one matches no row. See docs/versioning.md.
    const match = [
        ...primaryKeys.map((column) => aliasMatch(column, TARGET_ALIAS, VALUES_ALIAS)),
        ...(version === undefined ? [] : [aliasMatch(version, TARGET_ALIAS, VALUES_ALIAS)]),
    ].join(" and ");
    return {
        fragments: [
            `update ${quote(table.name)} as ${TARGET_ALIAS} set `,
            ...assignments.map((entry, index) => `${entry}${index === assignments.length - 1 ? " " : ", "}`),
            ...unnestFragments(arrays),
            `where ${match} `,
            // The statement returns the rows it wrote, so a chunk that wrote fewer names the rows it left out.
            `returning ${primaryKeys.map((column) => `${TARGET_ALIAS}.${quote(column.name)}`).join(", ")}`,
        ],
        arrays,
    };
}

/** Render `update<Entity>`: a chunk of rows per statement, writing the columns a patch may supply. See docs/repositories.md. */
export function generateUpdate(table: Table): string {
    const entity = table.interfaceName;
    const statement = updateStatement(table);
    const { arrays } = statement;
    const primaryKeys = table.columns.filter((column) => column.primaryKey);
    const version = versionColumn(table);
    const rejection =
        version === undefined
            ? `'no row of ${table.name} matches this patch: '`
            : `'no row of ${table.name} is at the version this patch supplied for '`;
    const lines = modulePrologue(
        `${entity}Patch`,
        'import { MAX_STATEMENT_PARAMETERS, resultRows, type SqlExecutor } from "../sql-executor.ts";',
    );

    lines.push("/** The key a patch addresses, as the statement returns it, so a rejected chunk names its rows. */");
    lines.push(`const keyOf = (row: ${entity}Patch): string => String(${keyExpression(primaryKeys)});`);
    lines.push("");
    lines.push("/** The parameters one row costs: one per bound array, so a chunk stays inside the limit. */");
    lines.push(`const PARAMETERS_PER_ROW = ${arrays.length};`);
    lines.push("");
    lines.push("/** The rows one statement carries, so its parameters stay inside MAX_STATEMENT_PARAMETERS. */");
    lines.push("const ROWS_PER_STATEMENT = Math.floor(MAX_STATEMENT_PARAMETERS / PARAMETERS_PER_ROW);");
    lines.push("");
    lines.push(`export async function update${entity}(db: SqlExecutor, rows: ${entity}Patch[]): Promise<void> {`);
    lines.push("    if (rows.length === 0) {");
    lines.push("        return;");
    lines.push("    }");
    lines.push("    const write = async (tx: SqlExecutor): Promise<void> => {");
    lines.push("        for (let start = 0; start < rows.length; start += ROWS_PER_STATEMENT) {");
    lines.push("            const chunk = rows.slice(start, start + ROWS_PER_STATEMENT);");
    lines.push(...bindArrays(arrays));
    lines.push(...chunkQuery(statement));
    lines.push(`            const written = new Set(resultRows(result).map((row) => ${returnedKeyExpression(primaryKeys)}));`);
    // A patch that wrote fewer rows than the chunk carried is a rejected call. See docs/versioning.md.
    lines.push("            if (written.size !== chunk.length) {");
    lines.push("                const missed = chunk.filter((row) => !written.has(keyOf(row)));");
    // A chunk naming one key twice writes fewer rows than it carries, and has no single row to blame.
    lines.push("                const named = missed.length > 0 ? missed : chunk;");
    lines.push(
        `                throw Object.assign(new Error(${rejection} + named.map(keyOf).join(", ")), { code: "40001" });`,
    );
    lines.push("            }");
    lines.push("        }");
    lines.push("    };");
    // One row is one atomic statement; a longer call rejects after its chunk has written, so it opens a boundary.
    lines.push("    if (rows.length === 1) {");
    lines.push("        await write(db);");
    lines.push("        return;");
    lines.push("    }");
    lines.push("    await db.transaction(write);");
    lines.push("}");

    return lines.join("\n") + "\n";
}

/** The insert and replacement an upsert runs, planned from the table alone: the fragments and the arrays it binds. */
export function upsertStatement(table: Table): ChunkStatement {
    const primaryKeys = table.columns.filter((column) => column.primaryKey);
    // An upsert writes the fields a create writes, plus the version an existing row is claimed at.
    // The conflict path cannot see the values alias, so `excluded` carries every column it stores.
    const insertColumns = table.columns.filter((column) => column.insertable !== false);
    // An identity key is the database's on a create, but an upsert names it: the key is what the conflict matches.
    const identityKeys = table.columns.filter((column) => column.identity);
    const version = versionColumn(table);
    const writeColumns = [...insertColumns, ...identityKeys, ...(version === undefined ? [] : [version])];
    // A defaulted column may be absent from a row, so it binds a flag and falls back to its default.
    // The identity key and the version are always claimed, so they carry no flag.
    const arrays = [
        ...insertColumns.flatMap((column) => columnArrays(column, column.default !== undefined)),
        ...identityKeys.flatMap((column) => columnArrays(column, false)),
        ...(version === undefined ? [] : columnArrays(version, false)),
    ];
    const selectItems = [
        ...insertColumns.map((column) => {
            const value = `${VALUES_ALIAS}.${quote(column.name)}`;
            return column.default === undefined ? value : suppliedValue(column, column.default);
        }),
        ...identityKeys.map((column) => `${VALUES_ALIAS}.${quote(column.name)}`),
        ...(version === undefined ? [] : [`${VALUES_ALIAS}.${quote(version.name)}`]),
    ];
    // The key is what the conflict matches on; the version is compared, never assigned, because the
    // trigger owns the increment and rejects a statement that names the column. See docs/versioning.md.
    // A keyless or versionless write has nothing to compare, so the target stays unnamed and `stored`
    // is the table itself.
    const stored = version === undefined ? quote(table.name) : TARGET_ALIAS;
    const target = version === undefined ? quote(table.name) : `${quote(table.name)} as ${TARGET_ALIAS}`;
    const assigned = writeColumns
        .filter((column) => !column.primaryKey && !column.version)
        .map((column) => `${quote(column.name)} = excluded.${quote(column.name)}`);
    const assignments = assigned.length === 0 ? [identityAssignment(primaryKeys[0] as Column, stored)] : assigned;
    return {
        fragments: [
            `insert into ${target} (${writeColumns.map((column) => quote(column.name)).join(", ")}) select `,
            ...selectItems.map((item, index) => `${item}${index === selectItems.length - 1 ? " " : ", "}`),
            ...unnestFragments(arrays),
            `on conflict (${primaryKeys.map((column) => quote(column.name)).join(", ")}) do update set `,
            ...assignments.map((entry, index) => `${entry}${index === assignments.length - 1 ? " " : ", "}`),
            // A row at another version is left alone, so the statement writes fewer rows than it carried.
            ...(version === undefined ? [] : [`where ${aliasMatch(version, stored, "excluded")} `]),
            // The written keys come back, so the call reports what it wrote and a chunk that skipped a row names it.
            `returning ${primaryKeys.map((column) => `${stored}.${quote(column.name)}`).join(", ")}`,
        ],
        arrays,
    };
}

/**
 * Render `upsert<Entity>`: a chunk of rows per statement, each inserted, or replacing the row at the
 * version it claims. See docs/repositories.md and docs/versioning.md.
 */
export function generateUpsert(table: Table): string {
    const entity = table.interfaceName;
    const statement = upsertStatement(table);
    const { arrays } = statement;
    const primaryKeys = table.columns.filter((column) => column.primaryKey);
    const version = versionColumn(table);
    const lines = modulePrologue(
        [`${entity}Upsert`, `${entity}PrimaryKey`],
        'import { MAX_STATEMENT_PARAMETERS, resultRows, type SqlExecutor } from "../sql-executor.ts";',
    );

    lines.push("/** The key a written row carries, as the upsert returned it. */");
    lines.push(keyReader(entity, primaryKeys));
    lines.push("");
    if (version !== undefined) {
        lines.push("/** The key a claimed row carries, as the caller names it, so a stale claim names its rows. */");
        lines.push(`const keyName = (row: ${entity}Upsert): string => String(${keyExpression(primaryKeys)});`);
        lines.push("");
    }
    lines.push("/** The parameters one row costs: one per bound array, so a chunk stays inside the limit. */");
    lines.push(`const PARAMETERS_PER_ROW = ${arrays.length};`);
    lines.push("");
    lines.push("/** The rows one statement carries, so its parameters stay inside MAX_STATEMENT_PARAMETERS. */");
    lines.push("const ROWS_PER_STATEMENT = Math.floor(MAX_STATEMENT_PARAMETERS / PARAMETERS_PER_ROW);");
    lines.push("");
    lines.push(
        `export async function upsert${entity}(db: SqlExecutor, rows: ${entity}Upsert[]): Promise<${entity}PrimaryKey[]> {`,
    );
    lines.push("    if (rows.length === 0) {");
    lines.push("        return [];");
    lines.push("    }");
    lines.push(`    const keys: ${entity}PrimaryKey[] = [];`);
    lines.push("    const write = async (tx: SqlExecutor): Promise<void> => {");
    lines.push("        for (let start = 0; start < rows.length; start += ROWS_PER_STATEMENT) {");
    lines.push("            const chunk = rows.slice(start, start + ROWS_PER_STATEMENT);");
    lines.push(...bindArrays(arrays));
    lines.push(...chunkQuery(statement));
    lines.push("            const written = resultRows(result);");
    if (version === undefined) {
        // Every conflicting row is replaced, so a short count is lost data rather than a stale claim.
        lines.push("            if (written.length !== chunk.length) {");
        lines.push(
            `                throw new Error('the upsert wrote ' + written.length + ' of the ' + chunk.length + ' ${table.name} rows this upsert supplied');`,
        );
        lines.push("            }");
    } else {
        // The statement leaves a row the version predicate did not match, so a short write is a stale claim.
        lines.push(`            const writtenKeys = new Set(written.map((row) => ${returnedKeyExpression(primaryKeys)}));`);
        lines.push("            if (writtenKeys.size !== chunk.length) {");
        lines.push("                const missed = chunk.filter((row) => !writtenKeys.has(keyName(row)));");
        lines.push("                const named = missed.length > 0 ? missed : chunk;");
        lines.push(
            `                throw Object.assign(new Error('no row of ${table.name} is at the version this upsert claims for ' + named.map(keyName).join(", ")), { code: "40001" });`,
        );
        lines.push("            }");
    }
    lines.push("            keys.push(...written.map(keyOf));");
    lines.push("        }");
    lines.push("    };");
    if (version === undefined) {
        // One statement is atomic on its own; only a call that spills past the limit opens a boundary.
        lines.push("    if (rows.length <= ROWS_PER_STATEMENT) {");
    } else {
        // A chunk that skipped a row has written the rest before it rejects, so a longer call opens a boundary.
        lines.push("    if (rows.length === 1) {");
    }
    lines.push("        await write(db);");
    lines.push("        return keys;");
    lines.push("    }");
    lines.push("    await db.transaction(write);");
    lines.push("    return keys;");
    lines.push("}");

    return lines.join("\n") + "\n";
}

/** The delete's SQL around the `(values …)` tuple list, which the runtime builds one tuple per row. */
export interface DeleteStatement {
    /** The SQL before the tuple list. */
    before: string;
    /** The SQL after it, naming the key columns the tuples are read as and matching each to its row. */
    after: string;
}

/** The delete an entity runs, planned from the table alone: its SQL around the tuple list. */
export function deleteStatement(table: Table): DeleteStatement {
    const primaryKeys = table.columns.filter((column) => column.primaryKey);
    const primaryKeyColumns = primaryKeys.map((column) => quote(column.name)).join(", ");
    return {
        before: `delete from ${quote(table.name)} using (values `,
        after: `) as data(${primaryKeyColumns}) where ${keyMatch(table, primaryKeys)}`,
    };
}

/** Render `delete<Entity>`: one multi-row delete matching on the primary key alone. */
export function generateDelete(table: Table): string {
    const entity = table.interfaceName;
    const primaryKeys = table.columns.filter((column) => column.primaryKey);
    const { before, after } = deleteStatement(table);
    const lines = modulePrologue(`${entity}PrimaryKey`);

    lines.push(`export async function delete${entity}(db: SqlExecutor, rows: ${entity}PrimaryKey[]): Promise<void> {`);
    lines.push("    if (rows.length === 0) {");
    lines.push("        return;");
    lines.push("    }");
    lines.push(...collectValues(primaryKeys.map(readEntry), { indent: "    ", source: "rows" }));
    lines.push(`    await db.query('${before}' + tuples.join(", ") + '${after}', parameters);`);
    lines.push("}");

    return lines.join("\n") + "\n";
}

/** The generator for each operation, so the barrel and the file set come from one list. */
const OPERATION_GENERATORS: Record<WriteOperation, (table: Table) => string> = {
    create: generateCreate,
    upsert: generateUpsert,
    update: generateUpdate,
    delete: generateDelete,
};

/** Render the barrel that re-exports every operation module, grouped by entity. */
export function generateIndex(tables: Table[]): string {
    const lines = [HEADER];
    for (const table of [...tables].sort((a, b) => a.interfaceName.localeCompare(b.interfaceName))) {
        for (const operation of table.repositoryOperations) {
            lines.push(`export * from "./${operationFileName(operation, table.interfaceName)}";`);
        }
    }
    return lines.join("\n") + "\n";
}

/** Render every generated file, keyed by file name (including the barrel). */
export function generateRepositories(tables: Map<string, Table>): Map<string, string> {
    const files = new Map<string, string>();
    for (const table of tables.values()) {
        for (const operation of table.repositoryOperations) {
            files.set(
                operationFileName(operation, table.interfaceName),
                OPERATION_GENERATORS[operation](table),
            );
        }
    }
    files.set(INDEX_FILE, generateIndex([...tables.values()]));
    return files;
}

/** Remove the generated modules the spec no longer declares, so a narrowed operation set leaves no file. */
function pruneStale(outDir: string, keep: Set<string>): void {
    for (const entry of readdirSync(outDir, { withFileTypes: true })) {
        if (!entry.isFile() || !entry.name.endsWith(".ts") || keep.has(entry.name)) {
            continue;
        }
        const file = join(outDir, entry.name);
        if (readFileSync(file, "utf8").split("\n", 1)[0] === HEADER) {
            rmSync(file);
        }
    }
}

function main(): void {
    const { tables, diagnostics } = buildSpecTables(loadSpec());

    for (const diagnostic of diagnostics) {
        console.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }

    if (diagnostics.length > 0) {
        process.exitCode = 1;
        return;
    }

    const outIndex = process.argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : process.argv[outIndex + 1];
    if (!outDir) {
        console.error("--out needs a directory");
        process.exitCode = 1;
        return;
    }

    const files = generateRepositories(tables);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    pruneStale(outDir, new Set(files.keys()));
    console.log(`wrote ${files.size} files to ${outDir}`);
}

if (import.meta.main) {
    main();
}
