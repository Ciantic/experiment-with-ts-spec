/** Generate CRUD repositories from `spec/domain`. See docs/repositories.md. */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Project } from "ts-morph";
import { lowerFirst } from "spec/scripts/spec-model.ts";
import {
    BACKEND_PACKAGE_ROOT,
    DEFAULT_SPEC_GLOB,
    SPEC_GLOB,
    buildSpecTables,
    quote,
    type Column,
    type Table,
} from "./postgres-model.ts";

/** Where the repository files are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(BACKEND_PACKAGE_ROOT, "src/db/repositories");

const HEADER = "// Generated by scripts/generate-repositories.ts. Do not edit.";

/** The barrel re-exporting every operation module. */
const INDEX_FILE = "index.ts";

/** InvoiceInsert -> repositories/invoiceInsertSchema.ts: the module holding one write type. */
export function validationFileName(writeType: string): string {
    const kind = writeType.endsWith("PrimaryKey")
        ? "PrimaryKey"
        : writeType.endsWith("Insert")
          ? "Insert"
          : "Patch";
    return `repositories/${lowerFirst(writeType.slice(0, -kind.length))}${kind}Schema.ts`;
}

/** The module for one operation, named after the function it exports: ("create", "Invoice") -> createInvoice.ts. */
function operationFileName(operation: Operation, entity: string): string {
    return `${operation}${entity}.ts`;
}

/** The operations every entity gets, in the order the barrel lists them. */
const OPERATIONS = ["create", "update", "delete"] as const;

type Operation = (typeof OPERATIONS)[number];

/** A column's value expression and the type its placeholder is cast to. */
interface ValueEntry {
    expression: string;
    sqlType: string;
    /** True for a defaulted column: an absent value emits the `default` keyword. */
    optional?: boolean;
}

/** The accessor that reads a column from a row, e.g. `customer?.id` for an inlined optional field. */
function readExpression(column: Column): string {
    return `row.${column.read ?? column.name}`;
}

/** The value entry for a plain write, where every column of the row is present. */
function readEntry(column: Column): ValueEntry {
    return { expression: readExpression(column), sqlType: column.sqlType };
}

/** The value entry for a create: a defaulted column may be absent, so the database fills it. */
function insertEntry(column: Column): ValueEntry {
    const entry = readEntry(column);
    return column.default === undefined ? entry : { ...entry, optional: true };
}

/** The `set` entry that assigns a column from the row's own tuple, e.g. `"name" = data."name"`. */
function assignment(column: Column): string {
    return JSON.stringify(`${quote(column.name)} = data.${quote(column.name)}`);
}

/** The lines that gather the given values into `parameters` and `tuples`, one tuple per row. */
function collectValues(entries: ValueEntry[]): string[] {
    if (entries.some((entry) => entry.optional)) {
        return collectValuesWithDefaults(entries);
    }
    const values = entries.map((entry) => entry.expression).join(", ");
    // The `values` alias is otherwise untyped text; casting each placeholder keeps keys and
    // assignments matching the column type (a bare text value would not compare to a uuid key).
    const tuple = entries
        .map((entry, index) => `"$" + (offset + ${index + 1}) + "::${entry.sqlType}"`)
        .join(' + ", " + ');
    return [
        "    if (rows.length === 0) {",
        "        return;",
        "    }",
        "    const parameters: unknown[] = [];",
        "    const tuples: string[] = [];",
        "    for (const row of rows) {",
        `        const values = [${values}];`,
        "        parameters.push(...values);",
        "        const offset = parameters.length - values.length;",
        `        tuples.push("(" + ${tuple} + ")");`,
        "    }",
    ];
}

/** The tuple builder for a create that falls back to the `default` keyword for an absent defaulted column. */
function collectValuesWithDefaults(entries: ValueEntry[]): string[] {
    const lines = [
        "    if (rows.length === 0) {",
        "        return;",
        "    }",
        "    const parameters: unknown[] = [];",
        "    const tuples: string[] = [];",
        "    for (const row of rows) {",
        "        const values: string[] = [];",
    ];
    for (const entry of entries) {
        if (!entry.optional) {
            lines.push(`        parameters.push(${entry.expression});`);
            lines.push(`        values.push("$" + parameters.length + "::${entry.sqlType}");`);
            continue;
        }
        lines.push(`        if (${entry.expression} === undefined) {`);
        lines.push('            values.push("default");');
        lines.push("        } else {");
        lines.push(`            parameters.push(${entry.expression});`);
        lines.push(`            values.push("$" + parameters.length + "::${entry.sqlType}");`);
        lines.push("        }");
    }
    lines.push('        tuples.push("(" + values.join(", ") + ")");');
    lines.push("    }");
    return lines;
}

/** The header and type imports every operation module carries, naming the one write type it uses. */
function modulePrologue(writeType: string, executorImport?: string): string[] {
    return [
        HEADER,
        // The repository, the wire schema, and the client all name the one type validation declares.
        `import type { ${writeType} } from "validation/${validationFileName(writeType)}";`,
        executorImport ?? 'import type { SqlExecutor } from "../sql-executor.ts";',
        "",
    ];
}

/** The `where` that matches each row of the `data` alias to the row it addresses. */
function keyMatch(table: Table, primaryKeys: Column[]): string {
    return primaryKeys
        .map((column) => `${quote(table.name)}.${quote(column.name)} = data.${quote(column.name)}`)
        .join(" and ");
}

/** The JS expression naming the row a patch addresses, for the message of a rejected patch. */
function keyExpression(primaryKeys: Column[]): string {
    return primaryKeys.map((column) => readExpression(column)).join(' + "/" + ');
}

/** Render `create<Entity>`: one multi-row insert over the insertable columns. */
export function generateCreate(table: Table): string {
    const entity = table.interfaceName;
    // A create writes the insertable fields, the same set `<entity>InsertSchema` accepts.
    const insertColumns = table.columns.filter((column) => column.insertable !== false);
    const insertColumnNames = insertColumns.map((column) => quote(column.name)).join(", ");
    const lines = modulePrologue(`${entity}Insert`);

    lines.push(`export async function create${entity}(db: SqlExecutor, rows: ${entity}Insert[]): Promise<void> {`);
    lines.push(...collectValues(insertColumns.map(insertEntry)));
    lines.push(
        `    await db.query('insert into ${quote(table.name)} (${insertColumnNames}) values ' + tuples.join(", "), parameters);`,
    );
    lines.push("}");

    return lines.join("\n") + "\n";
}

/** Render `update<Entity>`: a patch runner call over the columns a row may supply. See docs/repositories.md. */
export function generateUpdate(table: Table): string {
    const entity = table.interfaceName;
    const primaryKeys = table.columns.filter((column) => column.primaryKey);
    // A patch writes the patchable fields; a database-owned column keeps its stored value. See docs/repositories.md.
    const patchColumns = table.columns.filter((column) => !column.primaryKey && column.updatable !== false);
    // The version is the optimistic-lock precondition, not an assignment; the trigger increments it.
    const version = patchColumns.find((column) => column.version);
    const supplied = patchColumns.filter((column) => column.supplied !== undefined);
    const lines = modulePrologue(
        `${entity}Patch`,
        'import { affectedRows, type SqlExecutor } from "../sql-executor.ts";',
    );
    // A patch addresses the row at the version the caller holds, so a stale one matches no row. See docs/versioning.md.
    const match = version
        ? `${keyMatch(table, primaryKeys)} and ${quote(table.name)}.${quote(version.name)} = data.${quote(version.name)}`
        : keyMatch(table, primaryKeys);
    const rejection = version
        ? `'no row of ${table.name} is at the version this patch supplied for ' + ${keyExpression(primaryKeys)}`
        : `'no row of ${table.name} matches this patch: ' + ${keyExpression(primaryKeys)}`;

    // One statement per row: an omitted field is left out of the `set` clause, so it keeps its stored
    // value while a field the caller sets to `null` writes a null. More than one row is more than one
    // statement, so the call opens a boundary to stay all-or-nothing. See docs/repositories.md.
    lines.push(`export async function update${entity}(db: SqlExecutor, rows: ${entity}Patch[]): Promise<void> {`);
    lines.push("    if (rows.length === 0) {");
    lines.push("        return;");
    lines.push("    }");
    lines.push("    const write = async (tx: SqlExecutor): Promise<void> => {");
    lines.push("        for (const row of rows) {");
    lines.push("            const assignments: string[] = [];");
    lines.push("            const names: string[] = [];");
    lines.push("            const values: string[] = [];");
    lines.push("            const parameters: unknown[] = [];");
    lines.push("            const add = (column: string, cast: string, value: unknown): void => {");
    lines.push('                names.push("\\"" + column + "\\"");');
    lines.push('                values.push("$" + (parameters.length + 1) + "::" + cast);');
    lines.push("                parameters.push(value ?? null);");
    lines.push("            };");
    for (const column of primaryKeys) {
        lines.push(
            `            add(${JSON.stringify(column.name)}, ${JSON.stringify(column.sqlType)}, ${readExpression(column)});`,
        );
    }
    for (const column of supplied) {
        lines.push(`            if (${column.supplied}) {`);
        lines.push(
            `                add(${JSON.stringify(column.name)}, ${JSON.stringify(column.sqlType)}, ${readExpression(column)});`,
        );
        lines.push(`                assignments.push(${assignment(column)});`);
        lines.push("            }");
    }
    if (version) {
        // The version travels as a parameter for the `where`, never as an assignment. See docs/versioning.md.
        lines.push(
            `            add(${JSON.stringify(version.name)}, ${JSON.stringify(version.sqlType)}, ${readExpression(version)});`,
        );
    }
    // An update must set something; a row that supplies no field sets its key to the key it already holds.
    lines.push("            if (assignments.length === 0) {");
    lines.push(`                assignments.push(${assignment(primaryKeys[0] as Column)});`);
    lines.push("            }");
    lines.push(
        `            const result = await tx.query('update ${quote(table.name)} set ' + assignments.join(", ") + ' from (values (' + values.join(", ") + ')) as data(' + names.join(", ") + ') where ${match}', parameters);`,
    );
    // A patch that matched no row changed nothing, so the whole call is rejected. See docs/versioning.md.
    lines.push("            if (affectedRows(result) === 0) {");
    lines.push(`                throw Object.assign(new Error(${rejection}), { code: "40001" });`);
    lines.push("            }");
    lines.push("        }");
    lines.push("    };");
    // One row is one statement, so it needs no boundary; more than one would otherwise apply one row at a time.
    lines.push("    if (rows.length === 1) {");
    lines.push("        await write(db);");
    lines.push("        return;");
    lines.push("    }");
    lines.push("    await db.transaction(write);");
    lines.push("}");

    return lines.join("\n") + "\n";
}

/** Render `delete<Entity>`: one multi-row delete matching on the primary key alone. */
export function generateDelete(table: Table): string {
    const entity = table.interfaceName;
    const primaryKeys = table.columns.filter((column) => column.primaryKey);
    const primaryKeyColumns = primaryKeys.map((column) => quote(column.name)).join(", ");
    const lines = modulePrologue(`${entity}PrimaryKey`);

    lines.push(`export async function delete${entity}(db: SqlExecutor, rows: ${entity}PrimaryKey[]): Promise<void> {`);
    lines.push(...collectValues(primaryKeys.map(readEntry)));
    lines.push(
        `    await db.query('delete from ${quote(table.name)} using (values ' + tuples.join(", ") + ') as data(${primaryKeyColumns}) where ${keyMatch(table, primaryKeys)}', parameters);`,
    );
    lines.push("}");

    return lines.join("\n") + "\n";
}

/** The generator for each operation, so the barrel and the file set come from one list. */
const OPERATION_GENERATORS: Record<Operation, (table: Table) => string> = {
    create: generateCreate,
    update: generateUpdate,
    delete: generateDelete,
};

/** Render the barrel that re-exports every operation module, grouped by entity. */
export function generateIndex(tables: Table[]): string {
    const lines = [HEADER];
    for (const table of [...tables].sort((a, b) => a.interfaceName.localeCompare(b.interfaceName))) {
        for (const operation of OPERATIONS) {
            lines.push(`export * from "./${operationFileName(operation, table.interfaceName)}";`);
        }
    }
    return lines.join("\n") + "\n";
}

/** Render every generated file, keyed by file name (including the barrel). */
export function generateRepositories(tables: Map<string, Table>): Map<string, string> {
    const files = new Map<string, string>();
    for (const table of tables.values()) {
        for (const operation of OPERATIONS) {
            files.set(
                operationFileName(operation, table.interfaceName),
                OPERATION_GENERATORS[operation](table),
            );
        }
    }
    files.set(INDEX_FILE, generateIndex([...tables.values()]));
    return files;
}

function main(): void {
    const project = new Project({ tsConfigFilePath: "tsconfig.json" });
    project.addSourceFilesAtPaths(SPEC_GLOB);
    const { tables, diagnostics } = buildSpecTables(project, {
        specGlob: DEFAULT_SPEC_GLOB,
        aliasGlob: SPEC_GLOB,
    });

    for (const diagnostic of diagnostics) {
        console.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }

    if (diagnostics.length > 0) {
        process.exitCode = 1;
        return;
    }

    const outIndex = process.argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : process.argv[outIndex + 1];
    if (!outDir) {
        console.error("--out needs a directory");
        process.exitCode = 1;
        return;
    }

    const files = generateRepositories(tables);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    console.log(`wrote ${files.size} files to ${outDir}`);
}

if (import.meta.main) {
    main();
}
