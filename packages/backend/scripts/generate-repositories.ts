/** Generate CRUD repositories from `spec/domain`. See docs/repositories.md. */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Project } from "ts-morph";
import {
    BACKEND_PACKAGE_ROOT,
    DEFAULT_FORMULAS_FILE,
    DEFAULT_SPEC_GLOB,
    buildSpecTables,
    quote,
    type Column,
    type Table,
} from "./spec-model.ts";

/** Where the repository files are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(BACKEND_PACKAGE_ROOT, "src/postgres/db/repositories");

const HEADER = "// Generated by scripts/generate-repositories.ts. Do not edit.";

/** The barrel re-exporting every repository, alongside the per-entity files. */
const INDEX_FILE = "index.ts";

/** InvoiceRow -> invoiceRow.ts. */
function fileName(interfaceName: string): string {
    return interfaceName.charAt(0).toLowerCase() + interfaceName.slice(1) + ".ts";
}

/** The accessor that reads a column from a row, e.g. `customer?.id` for an inlined optional field. */
function readExpression(column: Column): string {
    return `row.${column.read ?? column.name}`;
}

/** The lines that gather the given columns into `parameters` and `tuples`, one tuple per row. */
function collectValues(columns: Column[]): string[] {
    const values = columns.map(readExpression).join(", ");
    // The `values` alias is otherwise untyped text; casting each placeholder keeps keys and
    // assignments matching the column type (a bare text value would not compare to a uuid key).
    const tuple = columns
        .map((column, index) => `"$" + (offset + ${index + 1}) + "::${column.sqlType}"`)
        .join(' + ", " + ');
    return [
        "    if (rows.length === 0) {",
        "        return;",
        "    }",
        "    const parameters: unknown[] = [];",
        "    const tuples: string[] = [];",
        "    for (const row of rows) {",
        `        const values = [${values}];`,
        "        parameters.push(...values);",
        "        const offset = parameters.length - values.length;",
        `        tuples.push("(" + ${tuple} + ")");`,
        "    }",
    ];
}

/** Render one repository module: create, update, and delete over `rows` of `table`. */
export function generateRepository(table: Table): string {
    const entity = table.interfaceName;
    const columns = table.columns;
    const primaryKeys = columns.filter((column) => column.primaryKey);
    // A column with a database default is left to the database; the repository never writes it.
    const written = columns.filter((column) => column.default === undefined);
    const otherColumns = written.filter((column) => !column.primaryKey);
    // An update must set something; a table whose only written column is the key sets it to itself.
    const setColumns = otherColumns.length > 0 ? otherColumns : primaryKeys;
    const writtenColumns = written.map((column) => quote(column.name)).join(", ");
    const primaryKeyColumns = primaryKeys.map((column) => quote(column.name)).join(", ");
    const setClause = setColumns.map((column) => `${quote(column.name)} = data.${quote(column.name)}`).join(", ");
    const match = primaryKeys
        .map((column) => `${quote(table.name)}.${quote(column.name)} = data.${quote(column.name)}`)
        .join(" and ");

    const lines: string[] = [];
    lines.push(HEADER);
    lines.push(`import type { ${entity} } from "${table.importSpecifier}";`);
    lines.push('import type { SqlExecutor } from "../sql-executor.js";');
    lines.push("");

    lines.push(`export async function create${entity}(db: SqlExecutor, rows: ${entity}[]): Promise<void> {`);
    lines.push(...collectValues(written));
    lines.push(
        `    await db.query('insert into ${quote(table.name)} (${writtenColumns}) values ' + tuples.join(", "), parameters);`,
    );
    lines.push("}");
    lines.push("");

    lines.push(`export async function update${entity}(db: SqlExecutor, rows: ${entity}[]): Promise<void> {`);
    lines.push(...collectValues(written));
    lines.push(
        `    await db.query('update ${quote(table.name)} set ${setClause} from (values ' + tuples.join(", ") + ') as data(${writtenColumns}) where ${match}', parameters);`,
    );
    lines.push("}");
    lines.push("");

    lines.push(`export async function delete${entity}(db: SqlExecutor, rows: ${entity}[]): Promise<void> {`);
    lines.push(...collectValues(primaryKeys));
    lines.push(
        `    await db.query('delete from ${quote(table.name)} using (values ' + tuples.join(", ") + ') as data(${primaryKeyColumns}) where ${match}', parameters);`,
    );
    lines.push("}");

    return lines.join("\n") + "\n";
}

/** Render the barrel that re-exports every repository module. */
export function generateIndex(tables: Table[]): string {
    const lines = [HEADER];
    for (const table of [...tables].sort((a, b) => a.interfaceName.localeCompare(b.interfaceName))) {
        lines.push(`export * from "./${fileName(table.interfaceName).replace(/\.ts$/, ".js")}";`);
    }
    return lines.join("\n") + "\n";
}

/** Render every generated file, keyed by file name (including the barrel). */
export function generateRepositories(tables: Map<string, Table>): Map<string, string> {
    const files = new Map<string, string>();
    for (const table of tables.values()) {
        files.set(fileName(table.interfaceName), generateRepository(table));
    }
    files.set(INDEX_FILE, generateIndex([...tables.values()]));
    return files;
}

function main(): void {
    const project = new Project({ tsConfigFilePath: "tsconfig.json" });
    project.addSourceFilesAtPaths(DEFAULT_SPEC_GLOB);
    const { tables, diagnostics } = buildSpecTables(project, {
        specGlob: DEFAULT_SPEC_GLOB,
        formulasFile: DEFAULT_FORMULAS_FILE,
    });

    for (const diagnostic of diagnostics) {
        console.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }

    if (diagnostics.length > 0) {
        process.exitCode = 1;
        return;
    }

    const outIndex = process.argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : process.argv[outIndex + 1];
    if (!outDir) {
        console.error("--out needs a directory");
        process.exitCode = 1;
        return;
    }

    const files = generateRepositories(tables);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    console.log(`wrote ${files.size} files to ${outDir}`);
}

if (import.meta.main) {
    main();
}
