/** Generate CRUD repositories from `spec/domain`. See docs/repositories.md. */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Project } from "ts-morph";
import { lowerFirst } from "spec/scripts/spec-model.ts";
import {
    BACKEND_PACKAGE_ROOT,
    DEFAULT_SPEC_GLOB,
    SPEC_GLOB,
    buildSpecTables,
    quote,
    type Column,
    type Table,
} from "./postgres-model.ts";

/** Where the repository files are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(BACKEND_PACKAGE_ROOT, "src/db/repositories");

const HEADER = "// Generated by scripts/generate-repositories.ts. Do not edit.";

/** The barrel re-exporting every operation module. */
const INDEX_FILE = "index.ts";

/** InvoiceRow -> invoiceRow.ts, matching the validation module's file name. */
function validationFileName(interfaceName: string): string {
    return `${lowerFirst(interfaceName)}.ts`;
}

/** The module for one operation, named after the function it exports: ("create", "Invoice") -> createInvoice.ts. */
function operationFileName(operation: Operation, entity: string): string {
    return `${operation}${entity}.ts`;
}

/** The operations every entity gets, in the order the barrel lists them. */
const OPERATIONS = ["create", "update", "delete"] as const;

type Operation = (typeof OPERATIONS)[number];

/** A column's value expression and the type its placeholder is cast to. */
interface ValueEntry {
    expression: string;
    sqlType: string;
}

/** The accessor that reads a column from a row, e.g. `customer?.id` for an inlined optional field. */
function readExpression(column: Column): string {
    return `row.${column.read ?? column.name}`;
}

/** The value entry for a plain write, where every column of the row is present. */
function readEntry(column: Column): ValueEntry {
    return { expression: readExpression(column), sqlType: column.sqlType };
}

/** The value entry for a patch: a version is required, every other column is null when the caller omits it. */
function patchEntry(column: Column): ValueEntry {
    const read = readExpression(column);
    return { expression: column.version ? read : `${read} ?? null`, sqlType: column.sqlType };
}

/** The lines that gather the given values into `parameters` and `tuples`, one tuple per row. */
function collectValues(entries: ValueEntry[]): string[] {
    const values = entries.map((entry) => entry.expression).join(", ");
    // The `values` alias is otherwise untyped text; casting each placeholder keeps keys and
    // assignments matching the column type (a bare text value would not compare to a uuid key).
    const tuple = entries
        .map((entry, index) => `"$" + (offset + ${index + 1}) + "::${entry.sqlType}"`)
        .join(' + ", " + ');
    return [
        "    if (rows.length === 0) {",
        "        return;",
        "    }",
        "    const parameters: unknown[] = [];",
        "    const tuples: string[] = [];",
        "    for (const row of rows) {",
        `        const values = [${values}];`,
        "        parameters.push(...values);",
        "        const offset = parameters.length - values.length;",
        `        tuples.push("(" + ${tuple} + ")");`,
        "    }",
    ];
}

/** The header and type imports every operation module carries, naming the one write type it uses. */
function modulePrologue(entity: string, writeType: string): string[] {
    return [
        HEADER,
        // The repository, the wire schema, and the client all name the one type validation declares.
        `import type { ${writeType} } from "validation/${validationFileName(entity)}";`,
        'import type { SqlExecutor } from "../sql-executor.ts";',
        "",
    ];
}

/** The `where` that matches each row of the `data` alias to the row it addresses. */
function keyMatch(table: Table, primaryKeys: Column[]): string {
    return primaryKeys
        .map((column) => `${quote(table.name)}.${quote(column.name)} = data.${quote(column.name)}`)
        .join(" and ");
}

/** Render `create<Entity>`: one multi-row insert over the insertable columns. */
export function generateCreate(table: Table): string {
    const entity = table.interfaceName;
    // A create writes the insertable fields, the same set `<entity>InsertSchema` accepts.
    const insertColumns = table.columns.filter((column) => column.insertable !== false);
    const insertColumnNames = insertColumns.map((column) => quote(column.name)).join(", ");
    const lines = modulePrologue(entity, `${entity}Insert`);

    lines.push(`export async function create${entity}(db: SqlExecutor, rows: ${entity}Insert[]): Promise<void> {`);
    lines.push(...collectValues(insertColumns.map(readEntry)));
    lines.push(
        `    await db.query('insert into ${quote(table.name)} (${insertColumnNames}) values ' + tuples.join(", "), parameters);`,
    );
    lines.push("}");

    return lines.join("\n") + "\n";
}

/** Render `update<Entity>`: one multi-row patch over the patchable columns, keeping omitted values. */
export function generateUpdate(table: Table): string {
    const entity = table.interfaceName;
    const primaryKeys = table.columns.filter((column) => column.primaryKey);
    // A patch writes the patchable fields; a database-owned column keeps its stored value. See docs/repositories.md.
    const patchColumns = table.columns.filter((column) => !column.primaryKey && column.updatable !== false);
    // The tuple carries the keys first, then the patchable columns.
    const dataEntries = [...primaryKeys.map(readEntry), ...patchColumns.map(patchEntry)];
    const dataColumnNames = [...primaryKeys, ...patchColumns].map((column) => quote(column.name)).join(", ");
    const keyAssignment = (column: Column) => `${quote(column.name)} = data.${quote(column.name)}`;
    // An omitted column keeps its stored value, so a patch cannot set one to null; the version is required.
    const patchAssignment = (column: Column) =>
        column.version
            ? keyAssignment(column)
            : `${quote(column.name)} = coalesce(data.${quote(column.name)}, ${quote(table.name)}.${quote(column.name)})`;
    // An update must set something; a table with nothing to patch sets its key to the key it already holds.
    const setClause =
        patchColumns.length > 0
            ? patchColumns.map(patchAssignment).join(", ")
            : primaryKeys.map(keyAssignment).join(", ");
    const lines = modulePrologue(entity, `${entity}Patch`);

    lines.push(`export async function update${entity}(db: SqlExecutor, rows: ${entity}Patch[]): Promise<void> {`);
    lines.push(...collectValues(dataEntries));
    lines.push(
        `    await db.query('update ${quote(table.name)} set ${setClause} from (values ' + tuples.join(", ") + ') as data(${dataColumnNames}) where ${keyMatch(table, primaryKeys)}', parameters);`,
    );
    lines.push("}");

    return lines.join("\n") + "\n";
}

/** Render `delete<Entity>`: one multi-row delete matching on the primary key alone. */
export function generateDelete(table: Table): string {
    const entity = table.interfaceName;
    const primaryKeys = table.columns.filter((column) => column.primaryKey);
    const primaryKeyColumns = primaryKeys.map((column) => quote(column.name)).join(", ");
    const lines = modulePrologue(entity, `${entity}PrimaryKey`);

    lines.push(`export async function delete${entity}(db: SqlExecutor, rows: ${entity}PrimaryKey[]): Promise<void> {`);
    lines.push(...collectValues(primaryKeys.map(readEntry)));
    lines.push(
        `    await db.query('delete from ${quote(table.name)} using (values ' + tuples.join(", ") + ') as data(${primaryKeyColumns}) where ${keyMatch(table, primaryKeys)}', parameters);`,
    );
    lines.push("}");

    return lines.join("\n") + "\n";
}

/** The generator for each operation, so the barrel and the file set come from one list. */
const OPERATION_GENERATORS: Record<Operation, (table: Table) => string> = {
    create: generateCreate,
    update: generateUpdate,
    delete: generateDelete,
};

/** Render the barrel that re-exports every operation module, grouped by entity. */
export function generateIndex(tables: Table[]): string {
    const lines = [HEADER];
    for (const table of [...tables].sort((a, b) => a.interfaceName.localeCompare(b.interfaceName))) {
        for (const operation of OPERATIONS) {
            lines.push(`export * from "./${operationFileName(operation, table.interfaceName)}";`);
        }
    }
    return lines.join("\n") + "\n";
}

/** Render every generated file, keyed by file name (including the barrel). */
export function generateRepositories(tables: Map<string, Table>): Map<string, string> {
    const files = new Map<string, string>();
    for (const table of tables.values()) {
        for (const operation of OPERATIONS) {
            files.set(
                operationFileName(operation, table.interfaceName),
                OPERATION_GENERATORS[operation](table),
            );
        }
    }
    files.set(INDEX_FILE, generateIndex([...tables.values()]));
    return files;
}

function main(): void {
    const project = new Project({ tsConfigFilePath: "tsconfig.json" });
    project.addSourceFilesAtPaths(SPEC_GLOB);
    const { tables, diagnostics } = buildSpecTables(project, {
        specGlob: DEFAULT_SPEC_GLOB,
        aliasGlob: SPEC_GLOB,
    });

    for (const diagnostic of diagnostics) {
        console.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }

    if (diagnostics.length > 0) {
        process.exitCode = 1;
        return;
    }

    const outIndex = process.argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : process.argv[outIndex + 1];
    if (!outDir) {
        console.error("--out needs a directory");
        process.exitCode = 1;
        return;
    }

    const files = generateRepositories(tables);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    console.log(`wrote ${files.size} files to ${outDir}`);
}

if (import.meta.main) {
    main();
}
