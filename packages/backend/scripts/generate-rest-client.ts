/**
 * Generate the type-safe client from the REST model. See docs/rest-api.md.
 *
 * Writes `packages/sdk/src`: one module per entity plus a barrel. The output may
 * import `spec`, the type-only write types `validation` shares, and its own
 * `./http.ts` — no backend module, no `zod`. A test asserts that invariant.
 *
 * The call signatures are the generated reads with `db` replaced by `http`, so
 * the client narrows exactly as the server does and needs no encoding logic of
 * its own: `http.request` owns the codec.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { Project } from "ts-morph";
import { DEFAULT_SPEC_GLOB, SPEC_GLOB, buildSpecTables } from "./postgres-model.ts";
import { BACKEND_PACKAGE_ROOT } from "./postgres-model.ts";
import { buildRestModel, type RestEntity, type RestKind, type RestModel } from "./rest-model.ts";

export type { Diagnostic } from "./postgres-model.ts";

/** Where the client is written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(BACKEND_PACKAGE_ROOT, "..", "sdk", "src");

const HEADER = "// Generated by scripts/generate-rest-client.ts. Do not edit.";

/** The hand-written transport, the only module of the generated client that is not generated. */
const HTTP_MODULE = "http.ts";

/** The barrel re-exporting the transport and every entity module. */
const INDEX_FILE = "index.ts";

/** The package specifier the read types are imported from. */
const SELECTION_IMPORT = "spec/selection.ts";

/** The package the shared write types (`<Entity>Patch`, `<Entity>Insert`) are imported from. */
const VALIDATION_PACKAGE = "validation";

/** `"id" | "customerId"`. */
function filterKeys(filters: string[]): string {
    return filters.map((name) => JSON.stringify(name)).join(" | ");
}

/** `Where<Widget, { size: "gt" | "gte" }>`. */
function whereType(name: string, fields: { name: string; operators: string[] }[]): string {
    const entries = fields.map((field) => `${field.name}: ${filterKeys(field.operators)}`);
    return `Where<${name}, { ${entries.join("; ")} }>`;
}

/** The `query` options: an optional filter, ordering, comparisons, and paging, plus the selection. */
function queryOptsType(
    name: string,
    filters: string[],
    order: string[],
    where: { name: string; operators: string[] }[],
): string {
    const parts: string[] = [];
    if (filters.length > 0) {
        parts.push(`filter?: Filters<${name}, ${filterKeys(filters)}>`);
    }
    if (order.length > 0) {
        parts.push(`order?: Order<${filterKeys(order)}>[]`);
    }
    if (where.length > 0) {
        parts.push(`where?: ${whereType(name, where)}`);
    }
    parts.push("limit?: number", "offset?: number", "select: S");
    return `{ ${parts.join("; ")} }`;
}

/** The operation of the given kind, or undefined when the entity does not expose it. */
function operation(entity: RestEntity, kind: RestKind) {
    return entity.operations.find((candidate) => candidate.kind === kind);
}

/** The `HttpClient` method a call goes through, chosen by where the model puts the argument. */
function transport(op: { source: "query" | "body" }): "query" | "send" {
    return op.source === "query" ? "query" : "send";
}

/** The doc comment above a generated function, mirroring the generated reads. */
function comment(entity: RestEntity, kind: RestKind): string {
    const name = entity.entity;
    switch (kind) {
        case "query":
            return `/** Query \`${name}\` rows, filtered by the \`@queryfilter\` fields, combined with and. */`;
        case "create":
            return `/** Create \`${name}\` rows. */`;
        case "update":
            return `/** Patch \`${name}\` rows; a stale version raises. See docs/versioning.md. */`;
        case "delete":
            return `/** Delete \`${name}\` rows, keyed on \`${entity.key}\`. */`;
    }
}

/** Render one entity's client module. */
export function renderClientModule(entity: RestEntity): string {
    const name = entity.entity;
    const query = operation(entity, "query");
    const create = operation(entity, "create");
    const update = operation(entity, "update");
    const remove = operation(entity, "delete");

    const selectionTypes = ["Selection", "Selected"];
    if (entity.filters.length > 0) {
        selectionTypes.push("Filters");
    }
    if (entity.orderFields.length > 0) {
        selectionTypes.push("Order");
    }
    if (entity.whereFields.length > 0) {
        selectionTypes.push("Where");
    }
    selectionTypes.sort((a, b) => a.localeCompare(b));

    const lines: string[] = [HEADER];
    lines.push(`import type { ${name} } from "${entity.importSpecifier}";`);
    lines.push(`import type { ${selectionTypes.join(", ")} } from "${SELECTION_IMPORT}";`);
    // The write types live in the validation package, so the client, the wire schema, and the server
    // all name one definition. A type-only import keeps `zod` out of the client's runtime. See docs/validation.md.
    const writeTypes: string[] = [];
    if (create) {
        writeTypes.push(`${name}Insert`);
    }
    if (update) {
        writeTypes.push(`${name}Patch`);
    }
    writeTypes.sort((a, b) => a.localeCompare(b));
    if (writeTypes.length > 0) {
        lines.push(`import type { ${writeTypes.join(", ")} } from "${VALIDATION_PACKAGE}/${entity.module}.ts";`);
    }
    lines.push(`import type { HttpClient } from "./${HTTP_MODULE}";`);
    if (writeTypes.length > 0) {
        lines.push("");
        lines.push(`export type { ${writeTypes.join(", ")} };`);
    }

    if (query) {
        lines.push("");
        lines.push(comment(entity, "query"));
        lines.push(`export function query${name}<S extends Selection<${name}>>(`);
        lines.push("    http: HttpClient,");
        lines.push(`    opts: ${queryOptsType(name, entity.filters, entity.orderFields, entity.whereFields)},`);
        lines.push(`): Promise<Selected<${name}, S>[]> {`);
        lines.push(
            `    return http.${transport(query)}<Selected<${name}, S>[]>("${query.method}", "${query.path}", opts);`,
        );
        lines.push("}");
    }

    if (create) {
        lines.push("");
        lines.push(comment(entity, "create"));
        lines.push(`export function create${name}(http: HttpClient, rows: ${name}Insert[]): Promise<void> {`);
        lines.push(`    return http.${transport(create)}<void>("${create.method}", "${create.path}", rows);`);
        lines.push("}");
    }

    if (update) {
        lines.push("");
        lines.push(comment(entity, "update"));
        lines.push(`export function update${name}(http: HttpClient, rows: ${name}Patch[]): Promise<void> {`);
        lines.push(`    return http.${transport(update)}<void>("${update.method}", "${update.path}", rows);`);
        lines.push("}");
    }

    if (remove) {
        lines.push("");
        lines.push(comment(entity, "delete"));
        lines.push(
            `export function delete${name}(http: HttpClient, rows: Pick<${name}, "${entity.key}">[]): Promise<void> {`,
        );
        lines.push(`    return http.${transport(remove)}<void>("${remove.method}", "${remove.path}", rows);`);
        lines.push("}");
    }

    return lines.join("\n") + "\n";
}

/** Render the barrel re-exporting the transport and every entity module. */
export function renderClientIndex(model: RestModel): string {
    const lines: string[] = [HEADER];
    lines.push(`export * from "./${HTTP_MODULE}";`);
    for (const entity of model.entities) {
        lines.push(`export * from "./${entity.module}.ts";`);
    }
    return lines.join("\n") + "\n";
}

/** Render every generated client file, keyed by file name. */
export function generateRestClient(model: RestModel): Map<string, string> {
    const files = new Map<string, string>();
    for (const entity of model.entities) {
        files.set(`${entity.module}.ts`, renderClientModule(entity));
    }
    files.set(INDEX_FILE, renderClientIndex(model));
    return files;
}

function main(): void {
    const project = new Project({ tsConfigFilePath: "tsconfig.json" });
    project.addSourceFilesAtPaths(SPEC_GLOB);
    const { tables, diagnostics } = buildSpecTables(project, {
        specGlob: DEFAULT_SPEC_GLOB,
        aliasGlob: SPEC_GLOB,
    });

    for (const diagnostic of diagnostics) {
        console.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }
    if (diagnostics.length > 0) {
        process.exitCode = 1;
        return;
    }

    const outIndex = process.argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : process.argv[outIndex + 1];
    if (!outDir) {
        console.error("--out needs a directory");
        process.exitCode = 1;
        return;
    }

    const files = generateRestClient(buildRestModel(tables));
    for (const [name, content] of files) {
        const target = join(outDir, name);
        mkdirSync(dirname(target), { recursive: true });
        writeFileSync(target, content);
    }
    console.log(`wrote ${files.size} files to ${outDir}`);
}

if (import.meta.main) {
    main();
}
