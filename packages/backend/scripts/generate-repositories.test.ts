/** Unit tests for the repository generator, driven by self-contained table fixtures. */
import { describe, expect, it } from "vitest";
import { generateIndex, generateRepositories, generateRepository } from "./generate-repositories.js";
import type { Column, Table } from "./spec-model.js";

function column(name: string, extras: Partial<Column> = {}): Column {
    return { name, sqlType: "text", notNull: true, primaryKey: false, unique: false, ...extras };
}

/** A table fixture; defaults keep each test focused on the part it exercises. */
function table(name: string, interfaceName: string, columns: Column[]): Table {
    return {
        name,
        interfaceName,
        importSpecifier: `spec/domain/${interfaceName}.js`,
        columns,
        sameRowAssignments: [],
        rollups: new Map(),
    };
}

const customer = table("customer", "Customer", [
    column("id", { sqlType: "uuid", primaryKey: true }),
    column("name"),
    column("email"),
]);

describe("generateRepository", () => {
    it("starts with the do-not-edit header", () => {
        const code = generateRepository(customer);

        expect(code.startsWith("// Generated by scripts/generate-repositories.ts. Do not edit.\n")).toBe(true);
    });

    it("imports the entity type and the executor interface", () => {
        const code = generateRepository(customer);

        expect(code).toContain('import type { Customer } from "spec/domain/Customer.js";');
        expect(code).toContain('import type { SqlExecutor } from "../sql-executor.js";');
    });

    it("exports create, update, and delete taking rows and returning nothing", () => {
        const code = generateRepository(customer);

        expect(code).toContain("export async function createCustomer(db: SqlExecutor, rows: Customer[]): Promise<void> {");
        expect(code).toContain("export async function updateCustomer(db: SqlExecutor, rows: CustomerPatch[]): Promise<void> {");
        expect(code).toContain("export async function deleteCustomer(db: SqlExecutor, rows: Customer[]): Promise<void> {");
    });

    it("returns early for an empty array", () => {
        const code = generateRepository(customer);

        expect(code.match(/if \(rows\.length === 0\) \{/g)).toHaveLength(3);
    });

    it("inserts every column with one placeholder per value", () => {
        const code = generateRepository(customer);

        expect(code).toContain('insert into "customer" ("id", "name", "email") values ');
        expect(code).toContain("const values = [row.id, row.name, row.email];");
    });

    it("casts each placeholder to its column type, so keys compare against the right type", () => {
        const code = generateRepository(customer);

        expect(code).toContain(
            '        tuples.push("(" + "$" + (offset + 1) + "::uuid" + ", " + "$" + (offset + 2) + "::text" + ", " + "$" + (offset + 3) + "::text" + ")");',
        );
    });

    it("exports a patch type requiring only the key and the version", () => {
        const code = generateRepository(
            table("customer", "Customer", [
                column("id", { sqlType: "uuid", primaryKey: true }),
                column("name"),
                column("version", { sqlType: "int8", default: "0", version: true }),
            ]),
        );

        expect(code).toContain(
            'export type CustomerPatch = Partial<Customer> & Required<Pick<Customer, "id" | "version">>;',
        );
    });

    it("requires only the key in the patch type when there is no version column", () => {
        const code = generateRepository(customer);

        expect(code).toContain('export type CustomerPatch = Partial<Customer> & Required<Pick<Customer, "id">>;');
    });

    it("updates only the columns a patch supplies, keeping the stored value for the rest", () => {
        const code = generateRepository(customer);

        expect(code).toContain("export async function updateCustomer(db: SqlExecutor, rows: CustomerPatch[])");
        expect(code).toContain("const values = [row.id, row.name ?? null, row.email ?? null];");
        expect(code).toContain(
            'update "customer" set "name" = coalesce(data."name", "customer"."name"), "email" = coalesce(data."email", "customer"."email") from (values ',
        );
        expect(code).toContain(') as data("id", "name", "email") where "customer"."id" = data."id"');
    });

    it("assigns the version directly rather than coalescing it", () => {
        const code = generateRepository(
            table("customer", "Customer", [
                column("id", { sqlType: "uuid", primaryKey: true }),
                column("name"),
                column("version", { sqlType: "int8", default: "0", version: true }),
            ]),
        );

        expect(code).toContain('"name" = coalesce(data."name", "customer"."name")');
        expect(code).toContain('"version" = data."version"');
        expect(code).not.toContain('coalesce(data."version"');
    });

    it("deletes by the primary key columns only", () => {
        const code = generateRepository(customer);

        expect(code).toContain('delete from "customer" using (values ');
        expect(code).toContain(') as data("id") where "customer"."id" = data."id"');
        expect(code).toContain("const values = [row.id];");
    });

    it("reads an inlined optional field through optional chaining", () => {
        const code = generateRepository(
            table("invoice_sent", "InvoiceSent", [
                column("id", { sqlType: "uuid", primaryKey: true }),
                column("customerName", { read: "customer?.name", notNull: false }),
            ]),
        );

        expect(code).toContain("const values = [row.id, row.customer?.name];");
    });

    it("reads a relation field through its id for an insert, and coalesces it for a patch", () => {
        const code = generateRepository(
            table("invoice", "Invoice", [
                column("id", { sqlType: "uuid", primaryKey: true }),
                column("customerId", { sqlType: "uuid", read: "customer?.id", notNull: false }),
            ]),
        );

        expect(code).toContain("const values = [row.id, row.customer?.id];");
        expect(code).toContain("const values = [row.id, row.customer?.id ?? null];");
    });

    it("sets the key to itself when a table has nothing to patch", () => {
        const code = generateRepository(
            table("tag", "Tag", [column("id", { sqlType: "uuid", primaryKey: true })]),
        );

        expect(code).toContain('update "tag" set "id" = data."id" from (values ');
    });

    it("does not write a column that has a database default", () => {
        const code = generateRepository(
            table("customer", "Customer", [
                column("id", { sqlType: "uuid", primaryKey: true }),
                column("name"),
                column("createdAt", { sqlType: "timestamptz", default: "now()" }),
            ]),
        );

        expect(code).not.toContain("row.createdAt");
        expect(code).toContain('insert into "customer" ("id", "name") values ');
        expect(code).toContain(') as data("id", "name") where "customer"."id" = data."id"');
        expect(code).not.toContain('"createdAt" = coalesce(data."createdAt"');
    });

    it("omits a @version column from insert but writes it on update", () => {
        const code = generateRepository(
            table("customer", "Customer", [
                column("id", { sqlType: "uuid", primaryKey: true }),
                column("name"),
                column("version", { sqlType: "int8", default: "0", version: true }),
            ]),
        );

        expect(code).toContain("const values = [row.id, row.name];");
        expect(code).toContain('insert into "customer" ("id", "name") values ');
        expect(code).toContain("const values = [row.id, row.name ?? null, row.version];");
        expect(code).toContain('as data("id", "name", "version") where "customer"."id" = data."id"');
    });
});

describe("generateIndex", () => {
    it("re-exports every repository module sorted by interface name", () => {
        const code = generateIndex([
            table("invoice_row", "InvoiceRow", []),
            table("customer", "Customer", []),
        ]);

        expect(code).toBe(
            [
                "// Generated by scripts/generate-repositories.ts. Do not edit.",
                'export * from "./customer.js";',
                'export * from "./invoiceRow.js";',
                "",
            ].join("\n"),
        );
    });
});

describe("generateRepositories", () => {
    it("emits one file per entity plus a barrel", () => {
        const tables = new Map<string, Table>([
            ["Customer", customer],
            ["Invoice", table("invoice", "Invoice", [column("id", { primaryKey: true })])],
        ]);

        const files = generateRepositories(tables);

        expect([...files.keys()].sort()).toEqual(["customer.ts", "index.ts", "invoice.ts"]);
    });
});
