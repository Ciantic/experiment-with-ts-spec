/** Unit tests for the repository generator, driven by self-contained table fixtures. */
import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";
import { ts } from "ts-morph";
import { createPglite } from "../src/postgres/pglite-setup.ts";
import type { SqlExecutor } from "../src/db/sql-executor.ts";
import { createTransactionalDb } from "../src/db/sql-executor.ts";
import { generateIndex, generateRepositories, generateRepository } from "./generate-repositories.ts";
import type { Column, Table } from "./postgres-model.ts";

function column(name: string, extras: Partial<Column> = {}): Column {
    // A defaulted column is neither insertable nor patchable, except the version; a fixture that says
    // otherwise passes the flag itself.
    const insertable = extras.insertable ?? extras.default === undefined;
    return { name, sqlType: "text", notNull: true, primaryKey: false, unique: false, insertable, updatable: extras.version === true || insertable, ...extras };
}

/** A table fixture; defaults keep each test focused on the part it exercises. */
function table(name: string, interfaceName: string, columns: Column[]): Table {
    return {
        name,
        interfaceName,
        importSpecifier: `spec/domain/${interfaceName}.ts`,
        columns,
        relations: new Map(),
        sameRowAssignments: [],
        rollups: new Map(),
    };
}

const customer = table("customer", "Customer", [
    column("id", { sqlType: "uuid", primaryKey: true }),
    column("name"),
    column("email"),
]);

const translation = table("translation", "Translation", [
    column("languageCode", { primaryKey: true }),
    column("key", { primaryKey: true }),
    column("value", { notNull: false }),
]);

/** A `create table` for a fixture, derived from its column metadata so this stays domain-free. */
function createTableSql(table: Table): string {
    const definitions = table.columns.map((column) => {
        const parts = [`"${column.name}" ${column.sqlType}`];
        if (column.notNull) {
            parts.push("not null");
        }
        if (column.default !== undefined) {
            parts.push(`default ${column.default}`);
        }
        return `    ${parts.join(" ")}`;
    });
    const keys = table.columns.filter((column) => column.primaryKey).map((column) => `"${column.name}"`);
    if (keys.length > 0) {
        definitions.push(`    primary key (${keys.join(", ")})`);
    }
    return `create table "${table.name}" (\n${definitions.join(",\n")}\n);`;
}

/** The three generated CRUD functions, resolved from an evaluated module. */
interface GeneratedRepository {
    create: (db: SqlExecutor, rows: unknown[]) => Promise<void>;
    update: (db: SqlExecutor, rows: unknown[]) => Promise<void>;
    delete: (db: SqlExecutor, rows: unknown[]) => Promise<void>;
}

/** Strips the generated module's type-only imports and evaluates the rest in memory. */
function loadRepository(table: Table): GeneratedRepository {
    const code = ts.transpileModule(generateRepository(table), {
        compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
    }).outputText;
    const exports: Record<string, unknown> = {};
    // The module imports only types, so this require is never reached at runtime.
    new Function("exports", "require", code)(exports, () => {
        throw new Error("the generated repository must not import a runtime dependency");
    });
    const pick = (prefix: string) => {
        const fn = exports[`${prefix}${table.interfaceName}`];
        if (typeof fn !== "function") {
            throw new Error(`the generated module does not export ${prefix}${table.interfaceName}`);
        }
        return fn as (db: SqlExecutor, rows: unknown[]) => Promise<void>;
    };
    return { create: pick("create"), update: pick("update"), delete: pick("delete") };
}

describe("generateRepository", () => {
    it("starts with the do-not-edit header", () => {
        const code = generateRepository(customer);

        expect(code.startsWith("// Generated by scripts/generate-repositories.ts. Do not edit.\n")).toBe(true);
    });

    it("imports the shared write types and the executor interface", () => {
        const code = generateRepository(customer);

        expect(code).toContain(
            'import type { CustomerInsert, CustomerPatch, CustomerPrimaryKey } from "validation/customer.ts";',
        );
        expect(code).toContain('import type { SqlExecutor } from "../sql-executor.ts";');
        expect(code).not.toContain("spec/domain");
    });

    it("exports create, update, and delete taking rows and returning nothing", () => {
        const code = generateRepository(customer);

        expect(code).toContain("export async function createCustomer(db: SqlExecutor, rows: CustomerInsert[]): Promise<void> {");
        expect(code).toContain("export async function updateCustomer(db: SqlExecutor, rows: CustomerPatch[]): Promise<void> {");
        expect(code).toContain("export async function deleteCustomer(db: SqlExecutor, rows: CustomerPrimaryKey[]): Promise<void> {");
    });

    it("imports the write types from the validation package rather than declaring them", () => {
        const limited = table("limited", "Limited", [
            column("id", { sqlType: "uuid", primaryKey: true }),
            column("label"),
        ]);
        const code = generateRepository(limited);

        expect(code).toContain(
            'import type { LimitedInsert, LimitedPatch, LimitedPrimaryKey } from "validation/limited.ts";',
        );
        expect(code).toContain("export async function createLimited(db: SqlExecutor, rows: LimitedInsert[])");
        expect(code).not.toContain("export type LimitedInsert");
        expect(code).not.toContain("export type LimitedPatch");
    });

    it("declares no write type locally, so the schema and the type cannot drift", () => {
        const code = generateRepository(customer);

        expect(code).not.toContain("export type CustomerInsert");
        expect(code).not.toContain("export type CustomerPatch");
        expect(code).not.toContain("export type CustomerPrimaryKey");
    });

    it("leaves a defaulted or derived column out of the patch statement", () => {
        const limited = table("limited", "Limited", [
            column("id", { sqlType: "uuid", primaryKey: true }),
            column("label"),
            column("createdAt", { sqlType: "timestamptz", default: "now()" }),
            column("derived", { notNull: false, updatable: false }),
            column("version", { sqlType: "int8", default: "0", version: true }),
        ]);
        const code = generateRepository(limited);
        const setClause = code.match(/set (.*?) from \(values /)?.[1] ?? "";
        const assigned = new Set([...setClause.matchAll(/"(\w+)" = /g)].map((match) => match[1]));

        // The statement sets the patchable column and the version; the key identifies the row in the where
        // clause, and the defaulted and derived columns are skipped altogether.
        expect(assigned).toEqual(new Set(["label", "version"]));
        expect(code).toContain('where "limited"."id" = data."id"');
    });

    it("leaves a non-updatable column out of the patch statement", () => {
        const limited = table("limited", "Limited", [
            column("id", { sqlType: "uuid", primaryKey: true }),
            column("label"),
            column("derived", { notNull: false, updatable: false }),
        ]);
        const setClause = generateRepository(limited).match(/set (.*?) from \(values /)?.[1] ?? "";

        expect(setClause).toContain('"label" = ');
        expect(setClause).not.toContain('"derived"');
    });

    it("leaves a non-insertable column out of the insert statement", () => {
        const limited = table("limited", "Limited", [
            column("id", { sqlType: "uuid", primaryKey: true }),
            column("label"),
            column("derived", { insertable: false }),
        ]);
        const insert = generateRepository(limited).match(/insert into "limited" \(([^)]*)\)/)?.[1] ?? "";

        expect(insert).toContain('"label"');
        expect(insert).not.toContain('"derived"');
    });

    it("returns early for an empty array", () => {
        const code = generateRepository(customer);

        expect(code.match(/if \(rows\.length === 0\) \{/g)).toHaveLength(3);
    });

    it("inserts every column with one placeholder per value", () => {
        const code = generateRepository(customer);

        expect(code).toContain('insert into "customer" ("id", "name", "email") values ');
        expect(code).toContain("const values = [row.id, row.name, row.email];");
    });

    it("casts each placeholder to its column type, so keys compare against the right type", () => {
        const code = generateRepository(customer);

        expect(code).toContain(
            '        tuples.push("(" + "$" + (offset + 1) + "::uuid" + ", " + "$" + (offset + 2) + "::text" + ", " + "$" + (offset + 3) + "::text" + ")");',
        );
    });

    it("uses the validation patch type whether or not the table has a version", () => {
        const versioned = generateRepository(
            table("customer", "Customer", [
                column("id", { sqlType: "uuid", primaryKey: true }),
                column("name"),
                column("version", { sqlType: "int8", default: "0", version: true }),
            ]),
        );

        expect(versioned).toContain(
            'import type { CustomerInsert, CustomerPatch, CustomerPrimaryKey } from "validation/customer.ts";',
        );
        expect(generateRepository(customer)).toContain(
            'import type { CustomerInsert, CustomerPatch, CustomerPrimaryKey } from "validation/customer.ts";',
        );
    });

    it("updates only the columns a patch supplies, keeping the stored value for the rest", () => {
        const code = generateRepository(customer);

        expect(code).toContain("export async function updateCustomer(db: SqlExecutor, rows: CustomerPatch[])");
        expect(code).toContain("const values = [row.id, row.name ?? null, row.email ?? null];");
        expect(code).toContain(
            'update "customer" set "name" = coalesce(data."name", "customer"."name"), "email" = coalesce(data."email", "customer"."email") from (values ',
        );
        expect(code).toContain(') as data("id", "name", "email") where "customer"."id" = data."id"');
    });

    it("assigns the version directly rather than coalescing it", () => {
        const code = generateRepository(
            table("customer", "Customer", [
                column("id", { sqlType: "uuid", primaryKey: true }),
                column("name"),
                column("version", { sqlType: "int8", default: "0", version: true }),
            ]),
        );

        expect(code).toContain('"name" = coalesce(data."name", "customer"."name")');
        expect(code).toContain('"version" = data."version"');
        expect(code).not.toContain('coalesce(data."version"');
    });

    it("deletes by the primary key columns only", () => {
        const code = generateRepository(customer);

        expect(code).toContain('delete from "customer" using (values ');
        expect(code).toContain(') as data("id") where "customer"."id" = data."id"');
        expect(code).toContain("const values = [row.id];");
    });

    it("matches every column of a composite key on delete", () => {
        const code = generateRepository(translation);

        expect(code).toContain(') as data("languageCode", "key")');
        expect(code).toContain('where "translation"."languageCode" = data."languageCode" and "translation"."key" = data."key"');
        expect(code).toContain("const values = [row.languageCode, row.key];");
    });

    it("patches a composite-key row by every key column", () => {
        const code = generateRepository(translation);

        expect(code).toContain(') as data("languageCode", "key", "value")');
        expect(code).toContain('set "value" = coalesce(data."value", "translation"."value")');
    });

    it("reads an inlined optional field through optional chaining", () => {
        const code = generateRepository(
            table("invoice_sent", "InvoiceSent", [
                column("id", { sqlType: "uuid", primaryKey: true }),
                column("customerName", { read: "customer?.name", notNull: false }),
            ]),
        );

        expect(code).toContain("const values = [row.id, row.customer?.name];");
    });

    it("reads each column through its recorded accessor, and coalesces it for a patch", () => {
        const code = generateRepository(
            table("invoice", "Invoice", [
                column("id", { sqlType: "uuid", primaryKey: true }),
                column("customerId", { sqlType: "uuid", read: "customer?.id", notNull: false }),
            ]),
        );

        expect(code).toContain("const values = [row.id, row.customer?.id];");
        expect(code).toContain("const values = [row.id, row.customer?.id ?? null];");
    });

    it("sets the key to itself when a table has nothing to patch", () => {
        const code = generateRepository(
            table("tag", "Tag", [column("id", { sqlType: "uuid", primaryKey: true })]),
        );

        expect(code).toContain('update "tag" set "id" = data."id" from (values ');
    });

    it("does not write a column that has a database default", () => {
        const code = generateRepository(
            table("customer", "Customer", [
                column("id", { sqlType: "uuid", primaryKey: true }),
                column("name"),
                column("createdAt", { sqlType: "timestamptz", default: "now()" }),
            ]),
        );

        expect(code).not.toContain("row.createdAt");
        expect(code).toContain('insert into "customer" ("id", "name") values ');
        expect(code).toContain(') as data("id", "name") where "customer"."id" = data."id"');
        expect(code).not.toContain('"createdAt" = coalesce(data."createdAt"');
    });

    it("omits a @version column from insert but writes it on update", () => {
        const code = generateRepository(
            table("customer", "Customer", [
                column("id", { sqlType: "uuid", primaryKey: true }),
                column("name"),
                column("version", { sqlType: "int8", default: "0", version: true }),
            ]),
        );

        expect(code).toContain("const values = [row.id, row.name];");
        expect(code).toContain('insert into "customer" ("id", "name") values ');
        expect(code).toContain("const values = [row.id, row.name ?? null, row.version];");
        expect(code).toContain('as data("id", "name", "version") where "customer"."id" = data."id"');
    });
});

