/** Generate a code-first GraphQL layer from `spec/domain`. See docs/graphql.md. */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Project } from "ts-morph";
import {
    BACKEND_PACKAGE_ROOT,
    DEFAULT_ANNOTATION_GLOB,
    DEFAULT_FORMULAS_FILE,
    DEFAULT_SPEC_GLOB,
    buildSpecTables,
    quote,
    readGraphScalars,
    type GraphField,
    type Table,
} from "./spec-model.ts";

export type { Diagnostic } from "./spec-model.ts";

/** Where the GraphQL files are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(BACKEND_PACKAGE_ROOT, "src/graphql");

const HEADER = "// Generated by scripts/generate-graphql.ts. Do not edit.";

const SCALARS_FILE = "scalars.ts";
const LOADERS_FILE = "loaders.ts";
const SCHEMA_FILE = "schema.ts";
const INDEX_FILE = "index.ts";

/** GraphQL built-in scalar names, mapped to the symbol imported from `graphql`. */
const GRAPHQL_BUILTINS: Record<string, string> = {
    String: "GraphQLString",
    ID: "GraphQLID",
    Int: "GraphQLInt",
    Float: "GraphQLFloat",
    Boolean: "GraphQLBoolean",
};

/** TypeScript built-in types mapped to a GraphQL scalar. These are language types, not spec types. */
const TYPESCRIPT_SCALARS: Record<string, string> = {
    string: "String",
    number: "Float",
    boolean: "Boolean",
    bigint: "String",
    Date: "DateTime",
};

/** Custom scalars serialized as ISO strings; every other custom scalar is serialized as text. */
const DATE_SCALARS = new Set(["DateTime"]);

/** Invoice -> invoice, InvoiceSentRow -> invoiceSentRow. */
function lowerFirst(name: string): string {
    return name.charAt(0).toLowerCase() + name.slice(1);
}

/** rows -> Rows. */
function upperFirst(name: string): string {
    return name.charAt(0).toUpperCase() + name.slice(1);
}

/** The module specifier for a sibling generated file. */
function specifier(fileName: string): string {
    return `./${fileName.replace(/\.ts$/, ".js")}`;
}

/** The generated DataLoader name for a `@children` field, e.g. `invoiceRows`. */
function childrenLoaderName(table: Table, field: GraphField): string {
    return `${lowerFirst(table.interfaceName)}${upperFirst(field.name)}`;
}

/** The primary key column of a table, for loaders and list ordering. */
function primaryKey(table: Table): string {
    return table.columns.find((column) => column.primaryKey)?.name ?? "id";
}

/** The GraphQL scalar name a scalar/computed field is exposed as, from its annotation or its TypeScript type. */
function graphQLScalarName(field: GraphField, scalars: Map<string, string>): string {
    const leaf = field.scalarName ?? field.typeName;
    return scalars.get(leaf) ?? TYPESCRIPT_SCALARS[leaf] ?? "String";
}

/** The expression that names a scalar in generated code: a builtin symbol, or the custom scalar itself. */
function scalarExpression(field: GraphField, scalars: Map<string, string>): string {
    const name = graphQLScalarName(field, scalars);
    return GRAPHQL_BUILTINS[name] ?? name;
}

/** The custom scalars the schema needs, in a stable order. */
function customScalarNames(tables: Table[], scalars: Map<string, string>): string[] {
    const names = new Set<string>();
    for (const table of tables) {
        for (const field of table.graphFields) {
            if (field.kind !== "scalar" && field.kind !== "computed") {
                continue;
            }
            const name = graphQLScalarName(field, scalars);
            if (!GRAPHQL_BUILTINS[name]) {
                names.add(name);
            }
        }
    }
    return [...names].sort();
}

function nonNull(inner: string): string {
    return `new GraphQLNonNull(${inner})`;
}

function listOf(inner: string): string {
    return `new GraphQLList(${inner})`;
}

/** The GraphQL output type expression for a field. */
function outputExpression(field: GraphField, scalars: Map<string, string>): string {
    if (field.kind === "children") {
        const list = listOf(nonNull(`${field.target}Type`));
        return field.notNull ? nonNull(list) : list;
    }
    if (field.kind === "relation" || field.kind === "inlined") {
        return field.notNull ? nonNull(`${field.target}Type`) : `${field.target}Type`;
    }
    const base = scalarExpression(field, scalars);
    return field.notNull ? nonNull(base) : base;
}

/** One field entry in a generated `GraphQLObjectType`, including its resolver when it is not a plain column. */
function fieldEntry(table: Table, field: GraphField, scalars: Map<string, string>): string {
    const type = outputExpression(field, scalars);
    if (field.kind === "relation") {
        const column = field.column ?? `${field.name}Id`;
        const loader = `${lowerFirst(field.target ?? "")}ById`;
        return [
            `        ${field.name}: {`,
            `            type: ${type},`,
            "            resolve: (parent, _args, context: GraphQLContext) =>",
            `                parent.${column} == null ? null : context.loaders.${loader}.load(String(parent.${column})),`,
            "        },",
        ].join("\n");
    }
    if (field.kind === "children") {
        const loader = childrenLoaderName(table, field);
        const key = primaryKey(table);
        return [
            `        ${field.name}: {`,
            `            type: ${type},`,
            "            resolve: (parent, _args, context: GraphQLContext) =>",
            `                context.loaders.${loader}.load(String(parent.${key})),`,
            "        },",
        ].join("\n");
    }
    if (field.kind === "inlined") {
        const key = field.inlinedIdColumn ?? field.inlinedColumns[0]?.column ?? "id";
        const shape = field.inlinedColumns
            .map((entry) => `${entry.field}: parent["${entry.column}"]`)
            .join(", ");
        const build = `{ ${shape} }`;
        const resolve = field.notNull
            ? `(parent) => ${build}`
            : `(parent) => (parent["${key}"] == null ? null : ${build})`;
        return [
            `        ${field.name}: {`,
            `            type: ${type},`,
            `            resolve: ${resolve},`,
            "        },",
        ].join("\n");
    }
    return `        ${field.name}: { type: ${type} },`;
}

function objectType(table: Table, scalars: Map<string, string>): string[] {
    const lines = [
        `const ${table.interfaceName}Type = new GraphQLObjectType({`,
        `    name: "${table.interfaceName}",`,
        "    fields: () => ({",
    ];
    for (const field of table.graphFields) {
        lines.push(fieldEntry(table, field, scalars));
    }
    lines.push("    }),", "});");
    return lines;
}

function queryType(tables: Table[]): string[] {
    const lines = ['const Query = new GraphQLObjectType({', '    name: "Query",', "    fields: () => ({"]; 
    for (const table of tables) {
        const entity = table.interfaceName;
        const singular = lowerFirst(entity);
        const byId = `${singular}ById`;
        const list = `list${entity}`;
        lines.push(`        ${singular}: {`);
        lines.push(`            type: ${entity}Type,`);
        lines.push("            args: { id: { type: new GraphQLNonNull(GraphQLID) } },");
        lines.push(`            resolve: (_root, args, context: GraphQLContext) => context.loaders.${byId}.load(String(args.id)),`);
        lines.push("        },");
        lines.push(`        ${singular}s: {`);
        lines.push(`            type: new GraphQLNonNull(new GraphQLList(new GraphQLNonNull(${entity}Type))),`);
        lines.push("            args: { limit: { type: GraphQLInt }, offset: { type: GraphQLInt } },");
        lines.push(`            resolve: (_root, args, context: GraphQLContext) => context.loaders.${list}(args),`);
        lines.push("        },");
    }
    lines.push("    }),", "});");
    return lines;
}

/** Render the custom scalars named by the spec's `@graphql` annotations. */
export function generateScalars(customNames: string[]): string {
    if (customNames.length === 0) {
        return [HEADER, "", "/** No custom scalars are referenced by the spec. */", ""].join("\n");
    }
    const lines: string[] = [
        HEADER,
        'import { GraphQLScalarType, Kind, type ValueNode } from "graphql";',
        "",
        "/** Read a string or numeric literal; a scalar annotation names a type, never a literal default. */",
        "function literalText(node: ValueNode): string {",
        "    if (node.kind === Kind.STRING || node.kind === Kind.INT || node.kind === Kind.FLOAT) {",
        "        return node.value;",
        "    }",
        '    throw new TypeError("expected a string or numeric literal");',
        "}",
        "",
    ];
    for (const name of customNames) {
        const serialize = DATE_SCALARS.has(name)
            ? "(value) => (value instanceof Date ? value.toISOString() : String(value))"
            : "(value) => String(value)";
        lines.push(`/** The ${name} scalar. */`);
        lines.push(`export const ${name} = new GraphQLScalarType({`);
        lines.push(`    name: "${name}",`);
        lines.push(`    serialize: ${serialize},`);
        lines.push("    parseValue: (value) => String(value),");
        lines.push("    parseLiteral: (node) => literalText(node),");
        lines.push("});");
        lines.push("");
    }
    return lines.join("\n");
}

/** Render the DataLoaders, list roots, and the per-request context. */
export function generateLoaders(tables: Map<string, Table>): string {
    const ordered = [...tables.values()];
    const lines: string[] = [HEADER];
    lines.push('import DataLoader from "dataloader";');
    lines.push('import type { RowExecutor } from "../postgres/db/sql-executor.js";');
    lines.push("");
    lines.push("/** A database row, keyed by column name; the GraphQL resolvers read it directly. */");
    lines.push("export type Row = Record<string, unknown>;");
    lines.push("");
    lines.push("/** Paging for a list root. */");
    lines.push("export interface ListOptions {");
    lines.push("    limit?: number;");
    lines.push("    offset?: number;");
    lines.push("}");
    lines.push("");
    for (const table of ordered) {
        const columns = table.columns.map((column) => quote(column.name)).join(", ");
        lines.push(`/** The columns selected for ${table.name}. */`);
        lines.push(`const ${lowerFirst(table.interfaceName)}Columns = '${columns}';`);
    }
    lines.push("");
    lines.push("export function createLoaders(db: RowExecutor) {");
    for (const table of ordered) {
        const entity = table.interfaceName;
        const columns = `${lowerFirst(entity)}Columns`;
        const key = primaryKey(table);
        lines.push(`    const ${lowerFirst(entity)}ById = new DataLoader<string, Row | null>(async (ids) => {`);
        lines.push(`        const { rows } = await db.query(\`select \${${columns}} from ${quote(table.name)} where ${quote(key)} = any($1::uuid[])\`, [ids]);`);
        lines.push(`        const byId = new Map(rows.map((row) => [String((row as Row)[${JSON.stringify(key)}]), row as Row]));`);
        lines.push("        return ids.map((id) => byId.get(id) ?? null);");
        lines.push("    });");
    }
    for (const table of ordered) {
        for (const field of table.graphFields) {
            if (field.kind !== "children" || !field.target || !field.foreignKeyColumn) {
                continue;
            }
            const child = tables.get(field.target);
            const columns = `${lowerFirst(field.target)}Columns`;
            const loader = childrenLoaderName(table, field);
            const foreignKey = field.foreignKeyColumn;
            lines.push(`    const ${loader} = new DataLoader<string, Row[]>(async (ids) => {`);
            lines.push(`        const { rows } = await db.query(\`select \${${columns}} from ${quote(child?.name ?? "")} where ${quote(foreignKey)} = any($1::uuid[])\`, [ids]);`);
            lines.push("        const groups = new Map<string, Row[]>();");
            lines.push("        for (const row of rows as Row[]) {");
            lines.push(`            const key = String(row[${JSON.stringify(foreignKey)}]);`);
            lines.push("            const group = groups.get(key);");
            lines.push("            if (group) {");
            lines.push("                group.push(row);");
            lines.push("            } else {");
            lines.push("                groups.set(key, [row]);");
            lines.push("            }");
            lines.push("        }");
            lines.push("        return ids.map((id) => groups.get(id) ?? []);");
            lines.push("    });");
        }
    }
    for (const table of ordered) {
        const entity = table.interfaceName;
        const columns = `${lowerFirst(entity)}Columns`;
        const key = primaryKey(table);
        lines.push(`    const list${entity} = async (options: ListOptions = {}): Promise<Row[]> => {`);
        lines.push(`        const { rows } = await db.query(\`select \${${columns}} from ${quote(table.name)} order by ${quote(key)} limit $1::int offset $2::int\`, [options.limit ?? 100, options.offset ?? 0]);`);
        lines.push("        return rows as Row[];");
        lines.push("    };");
    }
    lines.push("");
    lines.push("    return {");
    for (const table of ordered) {
        lines.push(`        ${lowerFirst(table.interfaceName)}ById,`);
    }
    for (const table of ordered) {
        for (const field of table.graphFields) {
            if (field.kind === "children" && field.foreignKeyColumn) {
                lines.push(`        ${childrenLoaderName(table, field)},`);
            }
        }
    }
    for (const table of ordered) {
        lines.push(`        list${table.interfaceName},`);
    }
    lines.push("    };");
    lines.push("}");
    lines.push("");
    lines.push("export type Loaders = ReturnType<typeof createLoaders>;");
    lines.push("");
    lines.push("/** The per-request context handed to every resolver. */");
    lines.push("export interface GraphQLContext {");
    lines.push("    db: RowExecutor;");
    lines.push("    loaders: Loaders;");
    lines.push("}");
    return lines.join("\n") + "\n";
}

/** Render the object types, the Query root, and the schema. */
export function generateSchema(tables: Map<string, Table>, scalars: Map<string, string> = new Map()): string {
    const ordered = [...tables.values()];
    const custom = customScalarNames(ordered, scalars);
    // GraphQLList/NonNull/Int/ID/ObjectType/Schema are always used; the rest only if a field needs them.
    const builtins = new Set([
        "GraphQLID",
        "GraphQLInt",
        "GraphQLList",
        "GraphQLNonNull",
        "GraphQLObjectType",
        "GraphQLSchema",
    ]);
    for (const table of ordered) {
        for (const field of table.graphFields) {
            if (field.kind !== "scalar" && field.kind !== "computed") {
                continue;
            }
            const symbol = GRAPHQL_BUILTINS[graphQLScalarName(field, scalars)];
            if (symbol) {
                builtins.add(symbol);
            }
        }
    }
    const lines: string[] = [HEADER];
    lines.push("import {");
    for (const symbol of [...builtins].sort()) {
        lines.push(`    ${symbol},`);
    }
    lines.push('} from "graphql";');
    if (custom.length > 0) {
        lines.push(`import { ${custom.join(", ")} } from "${specifier(SCALARS_FILE)}";`);
    }
    lines.push(`import type { GraphQLContext } from "${specifier(LOADERS_FILE)}";`);
    lines.push("");
    for (const table of ordered) {
        lines.push(...objectType(table, scalars));
        lines.push("");
    }
    lines.push(...queryType(ordered));
    lines.push("");
    lines.push("export const schema = new GraphQLSchema({ query: Query });");
    return lines.join("\n") + "\n";
}

/** Render the package entry point: context creation and execution. */
export function generateIndex(): string {
    return [
        HEADER,
        'import { graphql } from "graphql";',
        `import { createLoaders, type GraphQLContext } from "${specifier(LOADERS_FILE)}";`,
        `import { schema } from "${specifier(SCHEMA_FILE)}";`,
        'import type { RowExecutor } from "../postgres/db/sql-executor.js";',
        "",
        `export * from "${specifier(SCALARS_FILE)}";`,
        `export * from "${specifier(LOADERS_FILE)}";`,
        `export * from "${specifier(SCHEMA_FILE)}";`,
        "",
        "/** Build the per-request context: the database and its loaders. */",
        "export function createContext(db: RowExecutor): GraphQLContext {",
        "    return { db, loaders: createLoaders(db) };",
        "}",
        "",
        "/** Run a GraphQL operation against the generated schema. */",
        "export function execute(source: string, context: GraphQLContext, variableValues?: Record<string, unknown>) {",
        "    return graphql({ schema, source, contextValue: context, variableValues });",
        "}",
        "",
    ].join("\n");
}

/** Render every generated file, keyed by file name. `scalars` is the spec's `@graphql` map. */
export function generateGraphql(tables: Map<string, Table>, scalars: Map<string, string> = new Map()): Map<string, string> {
    const files = new Map<string, string>();
    files.set(SCALARS_FILE, generateScalars(customScalarNames([...tables.values()], scalars)));
    files.set(LOADERS_FILE, generateLoaders(tables));
    files.set(SCHEMA_FILE, generateSchema(tables, scalars));
    files.set(INDEX_FILE, generateIndex());
    return files;
}

function main(): void {
    const project = new Project({ tsConfigFilePath: "tsconfig.json" });
    project.addSourceFilesAtPaths(DEFAULT_SPEC_GLOB);
    // Primitives carry the @graphql annotations, and they live outside src/domain.
    project.addSourceFilesAtPaths(DEFAULT_ANNOTATION_GLOB);
    const scalars = readGraphScalars(project, { aliasGlob: DEFAULT_ANNOTATION_GLOB });
    const { tables, diagnostics } = buildSpecTables(project, {
        specGlob: DEFAULT_SPEC_GLOB,
        aliasGlob: DEFAULT_ANNOTATION_GLOB,
        formulasFile: DEFAULT_FORMULAS_FILE,
    });

    for (const diagnostic of diagnostics) {
        console.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }

    if (diagnostics.length > 0) {
        process.exitCode = 1;
        return;
    }

    const outIndex = process.argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : process.argv[outIndex + 1];
    if (!outDir) {
        console.error("--out needs a directory");
        process.exitCode = 1;
        return;
    }

    const files = generateGraphql(tables, scalars);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    console.log(`wrote ${files.size} files to ${outDir}`);
}

if (import.meta.main) {
    main();
}
