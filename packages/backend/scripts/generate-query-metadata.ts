/**
 * Generate the query metadata and per-entity query modules from `@query` aliases.
 * See docs/queries.md. The resolver itself is hand-written: this emits the model it
 * reads and the typed factories that call it.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Project } from "ts-morph";
import {
    DEFAULT_SPEC_GLOB,
    SPEC_GLOB,
    buildSpecTables,
    type Table,
} from "./postgres-model.ts";
import { BACKEND_PACKAGE_ROOT } from "./postgres-model.ts";
import { readQueries } from "spec/scripts/spec-model.js";

/** Where the generated modules are written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(BACKEND_PACKAGE_ROOT, "src/db/queries");

const HEADER = "// Generated by scripts/generate-query-metadata.ts. Do not edit.";

/** The model file name, next to the per-entity query modules. */
const MODEL_FILE = "model.ts";

/** The barrel re-exporting the model and every query module. */
const INDEX_FILE = "index.ts";

/** One `@query` alias, reduced to the data a renderer needs. */
export interface QuerySpec {
    /** The alias name, e.g. `ListInvoices`. */
    name: string;
    /** The entity `@query` names, e.g. `Invoice`. */
    entity: string;
    cardinality: "one" | "many";
    /** The module specifier that imports the args alias. */
    importSpecifier: string;
    /** Set-membership args, from `@in`: argument name -> the field it matches. */
    inFilters?: Record<string, string>;
}

/** QueryTable as plain data, matching the resolver's `QueryTable`. */
interface QueryTableData {
    name: string;
    key: string;
    fields: Record<string, string>;
    relations: Record<string, Record<string, unknown>>;
}

/** QueryModel as plain data, matching the resolver's `QueryModel`. */
interface QueryModelData {
    tables: Record<string, QueryTableData>;
}

/** Invoice -> invoice, ListInvoices -> listInvoices. */
function lowerFirst(name: string): string {
    return name.charAt(0).toLowerCase() + name.slice(1);
}

/** The module file for an entity, e.g. `Invoice` -> `invoiceQueries.ts`. */
function queryFileName(entity: string): string {
    return `${lowerFirst(entity)}Queries.ts`;
}

/** Map the table model to the resolver's metadata: scalar fields plus branch descriptors. */
export function buildQueryModel(tables: Map<string, Table>): QueryModelData {
    const out: Record<string, QueryTableData> = {};
    for (const table of tables.values()) {
        // Relation and inlined columns are reached through their branch, not as selectable fields.
        const branchColumns = new Set<string>();
        for (const relation of table.relations.values()) {
            if (relation.kind === "relation" && relation.column) {
                branchColumns.add(relation.column);
            }
            if (relation.kind === "inlined") {
                for (const column of Object.values(relation.columns ?? {})) {
                    branchColumns.add(column);
                }
            }
        }

        const fields: Record<string, string> = {};
        for (const column of table.columns) {
            if (!branchColumns.has(column.name)) {
                fields[column.name] = column.name;
            }
        }

        const relations: Record<string, Record<string, unknown>> = {};
        for (const [field, relation] of table.relations) {
            relations[field] =
                relation.kind === "inlined"
                    ? { kind: relation.kind, table: relation.table, columns: relation.columns }
                    : { kind: relation.kind, table: relation.table, column: relation.column };
        }

        const key = table.columns.find((column) => column.primaryKey)?.name ?? "id";
        out[table.name] = { name: table.name, key, fields, relations };
    }
    return { tables: out };
}

/** Render the metadata module the resolver is constructed with. */
export function renderQueryModelModule(model: QueryModelData): string {
    const lines: string[] = [HEADER];
    lines.push('import type { QueryModel } from "../resolvers.js";');
    lines.push("");
    lines.push(`export const queryModel: QueryModel = ${JSON.stringify(model, null, 4)};`);
    return lines.join("\n") + "\n";
}

/** The args import statement(s) for a module, grouped by module specifier. */
function renderArgsImports(methods: QuerySpec[]): string[] {
    const bySpecifier = new Map<string, string[]>();
    for (const method of methods) {
        const names = bySpecifier.get(method.importSpecifier) ?? [];
        names.push(method.name);
        bySpecifier.set(method.importSpecifier, names);
    }
    return [...bySpecifier.entries()]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([specifier, names]) => `import type { ${[...names].sort().join(", ")} } from "${specifier}";`);
}

/** Render one entity's query interface and its factory. */
export function renderQueryModule(
    entity: string,
    tableName: string,
    entityImport: string,
    methods: QuerySpec[],
): string {
    const sorted = [...methods].sort((a, b) => a.name.localeCompare(b.name));
    const factory = `${lowerFirst(entity)}Queries`;
    const lines: string[] = [HEADER];
    lines.push(`import type { ${entity} } from "${entityImport}";`);
    lines.push(...renderArgsImports(sorted));
    lines.push('import type { Selection, Selected } from "spec/queries/selection.js";');
    lines.push('import type { SqlExecutor } from "../sql-executor.js";');
    lines.push('import { createResolver } from "../resolvers.js";');
    lines.push('import { queryModel } from "./model.js";');
    lines.push("");

    lines.push(`export interface ${entity}Queries {`);
    for (const method of sorted) {
        const returns =
            method.cardinality === "one"
                ? `Promise<Selected<${entity}, S> | undefined>`
                : `Promise<Selected<${entity}, S>[]>`;
        lines.push(
            `    ${lowerFirst(method.name)}<S extends Selection<${entity}>>(opts: ${method.name} & { select: S }): ${returns};`,
        );
    }
    lines.push("}");
    lines.push("");

    lines.push("const resolver = createResolver(queryModel);");
    lines.push("");
    lines.push(`export function ${factory}(db: SqlExecutor): ${entity}Queries {`);
    lines.push("    return {");
    for (const method of sorted) {
        const call = method.cardinality === "one" ? "resolveOne" : "resolveMany";
        lines.push(
            `        ${lowerFirst(method.name)}: <S extends Selection<${entity}>>(opts: ${method.name} & { select: S }) => {`,
        );
        lines.push("            const { select, ...args } = opts;");
        const filterEntries = Object.entries(method.inFilters ?? {}).map(
            ([argument, field]) => `${JSON.stringify(argument)}: ${JSON.stringify(field)}`,
        );
        const options =
            filterEntries.length > 0
                ? `{ select, inFilters: { ${filterEntries.join(", ")} } }`
                : "{ select }";
        lines.push(
            `            return resolver.${call}<${entity}, S>(db, ${JSON.stringify(tableName)}, args, ${options});`,
        );
        lines.push("        },");
    }
    lines.push("    };");
    lines.push("}");
    return lines.join("\n") + "\n";
}

/** Render every generated file, keyed by file name (including the barrel). */
export function generateQueries(tables: Map<string, Table>, queries: QuerySpec[]): Map<string, string> {
    const byEntity = new Map<string, QuerySpec[]>();
    for (const query of queries) {
        const list = byEntity.get(query.entity) ?? [];
        list.push(query);
        byEntity.set(query.entity, list);
    }

    const files = new Map<string, string>();
    files.set(MODEL_FILE, renderQueryModelModule(buildQueryModel(tables)));
    const entries = [...byEntity.entries()].sort(([a], [b]) => a.localeCompare(b));
    for (const [entity, methods] of entries) {
        const table = [...tables.values()].find((candidate) => candidate.interfaceName === entity);
        if (!table) {
            throw new Error(`@query ${entity} has no table`);
        }
        files.set(queryFileName(entity), renderQueryModule(entity, table.name, table.importSpecifier, methods));
    }

    const lines = [HEADER, `export * from "./${MODEL_FILE.replace(/\.ts$/, ".js")}";`];
    for (const [entity] of entries) {
        lines.push(`export * from "./${queryFileName(entity).replace(/\.ts$/, ".js")}";`);
    }
    files.set(INDEX_FILE, lines.join("\n") + "\n");
    return files;
}

function main(): void {
    const project = new Project({ tsConfigFilePath: "tsconfig.json" });
    project.addSourceFilesAtPaths(SPEC_GLOB);
    const { tables, diagnostics } = buildSpecTables(project, {
        specGlob: DEFAULT_SPEC_GLOB,
        aliasGlob: SPEC_GLOB,
    });

    for (const diagnostic of diagnostics) {
        console.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }
    if (diagnostics.length > 0) {
        process.exitCode = 1;
        return;
    }

    const queries: QuerySpec[] = readQueries(project, SPEC_GLOB).map((query) => ({
        name: query.name,
        entity: query.entity,
        cardinality: query.cardinality,
        importSpecifier: query.importSpecifier,
        inFilters: Object.fromEntries(
            query.arguments
                .filter((argument) => argument.tags.in !== undefined)
                .map((argument) => [argument.name, argument.tags.in as string]),
        ),
    }));

    const outIndex = process.argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : process.argv[outIndex + 1];
    if (!outDir) {
        console.error("--out needs a directory");
        process.exitCode = 1;
        return;
    }

    const files = generateQueries(tables, queries);
    mkdirSync(outDir, { recursive: true });
    for (const [name, content] of files) {
        writeFileSync(join(outDir, name), content);
    }
    console.log(`wrote ${files.size} files to ${outDir}`);
}

if (import.meta.main) {
    main();
}
