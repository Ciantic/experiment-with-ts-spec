/** Generate the type-safe client from the REST model; a builder returns a call the caller passes to `exec`. See docs/rest-api.md. */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { loadSpec, type SpecModel } from "spec/scripts/spec-model.ts";
import { writeTypeFileName } from "./generate-zod-schemas.ts";
import {
    buildRestModel,
    type RestEntity,
    type RestKind,
    type RestModel,
    type RestOperationCall,
} from "./rest-model.ts";

export type { Diagnostic } from "./rest-model.ts";

/** This package's root, so paths do not depend on the current working directory. */
const SDK_PACKAGE_ROOT = dirname(import.meta.dirname);

/** Where the client is written when no `--out` is given. */
const DEFAULT_OUT_DIR = join(SDK_PACKAGE_ROOT, "src", "api");

const HEADER = "// Generated by scripts/generate-rest-client.ts. Do not edit.";

/** The hand-written call model the generated builders return. */
const CLIENT_MODULE = "client.ts";

/** The barrel re-exporting every entity module. */
const INDEX_FILE = "index.ts";

/** The package specifier the read types are imported from. */
const SELECTION_IMPORT = "../selection.ts";

/** The directory the shared write types (`<Entity>Patch`, `<Entity>Insert`) are imported from, relative to `api/`. */
const WRITE_TYPES_DIR = "..";

/** `"id" | "customerId"`. */
function filterKeys(filters: string[]): string {
    return filters.map((name) => JSON.stringify(name)).join(" | ");
}

/** `Where<Widget, { size: "gt" | "gte" }>`. */
function whereType(name: string, fields: { name: string; operators: string[] }[]): string {
    const entries = fields.map((field) => `${field.name}: ${filterKeys(field.operators)}`);
    return `Where<${name}, { ${entries.join("; ")} }>`;
}

/** The `query` options: a filter, ordering, comparisons, and paging, plus the selection. */
function queryOptsType(
    name: string,
    filters: string[],
    required: string[],
    order: string[],
    where: { name: string; operators: string[] }[],
): string {
    const parts: string[] = [];
    if (filters.length > 0) {
        // A required filter makes the whole object mandatory, exactly as the server's own read types do.
        const keys = required.length > 0 ? `${filterKeys(filters)}, ${filterKeys(required)}` : filterKeys(filters);
        parts.push(`${required.length > 0 ? "filter" : "filter?"}: Filters<${name}, ${keys}>`);
    }
    if (order.length > 0) {
        parts.push(`order?: Order<${filterKeys(order)}>[]`);
    }
    if (where.length > 0) {
        parts.push(`where?: ${whereType(name, where)}`);
    }
    parts.push("limit?: number", "offset?: number", "select: S");
    return `{ ${parts.join("; ")} }`;
}

/** The operation of the given kind, or undefined when the entity does not expose it. */
function operation(entity: RestEntity, kind: RestKind) {
    return entity.operations.find((candidate) => candidate.kind === kind);
}

/** The doc comment above a generated function, mirroring the generated reads. */
function comment(entity: RestEntity, kind: RestKind): string {
    const name = entity.entity;
    switch (kind) {
        case "query":
            return `/** Query \`${name}\` rows, filtered by the \`@queryFilter\` fields, combined with and. */`;
        case "create":
            return `/** Create \`${name}\` rows. */`;
        case "upsert":
            return entity.versionFields.length > 0
                ? `/** Upsert \`${name}\` rows: each row is created, or replaces the row at the version it claims. See docs/versioning.md. */`
                : `/** Upsert \`${name}\` rows: each row is created, or replaces the row it keys on. */`;
        case "update":
            return entity.versionFields.length > 0
                ? `/** Patch \`${name}\` rows; a stale version, or a row that is not there, rejects the call. See docs/versioning.md. */`
                : `/** Patch \`${name}\` rows; a row that is not there rejects the call. See docs/versioning.md. */`;
        case "delete":
            return `/** Delete \`${name}\` rows, keyed on ${entity.keys.map((key) => `\`${key}\``).join(", ")}. */`;
    }
}

/** The key projection the write schemas declare for the entity, e.g. `InvoicePrimaryKey`. */
function keyType(entity: RestEntity): string {
    return `${entity.entity}PrimaryKey`;
}

/** Render one entity's client module. */
export function renderClientModule(entity: RestEntity): string {
    const name = entity.entity;
    const query = operation(entity, "query");
    const create = operation(entity, "create");
    const upsert = operation(entity, "upsert");
    const update = operation(entity, "update");
    const remove = operation(entity, "delete");

    const selectionTypes = ["Selection", "Selected"];
    if (entity.filters.length > 0) {
        selectionTypes.push("Filters");
    }
    if (entity.orderFields.length > 0) {
        selectionTypes.push("Order");
    }
    if (entity.whereFields.length > 0) {
        selectionTypes.push("Where");
    }
    selectionTypes.sort((a, b) => a.localeCompare(b));

    const lines: string[] = [HEADER];
    // The entity type and the selection types are what the read's signature is made of, so only a read carries them. See docs/queries.md.
    if (query) {
        lines.push(`import type { ${name} } from "${entity.importSpecifier}";`);
        lines.push(`import type { ${selectionTypes.join(", ")} } from "${SELECTION_IMPORT}";`);
    }
    // The write types come from this package's schema modules; a type-only import keeps `zod` out of the runtime.
    const writeTypes: string[] = [];
    if (create) {
        writeTypes.push(`${name}Insert`);
    }
    // Create, upsert, and delete all name the key, so the type follows whichever of them exists.
    if (create || upsert || remove) {
        writeTypes.push(keyType(entity));
    }
    if (upsert) {
        writeTypes.push(`${name}Upsert`);
    }
    if (update) {
        writeTypes.push(`${name}Patch`);
    }
    writeTypes.sort((a, b) => a.localeCompare(b));
    if (writeTypes.length > 0) {
        // Each type lives in its own module, so the imports group by module rather than by entity.
        const byModule = new Map<string, string[]>();
        for (const writeType of writeTypes) {
            const module = writeTypeFileName(writeType);
            byModule.set(module, [...(byModule.get(module) ?? []), writeType]);
        }
        for (const [module, names] of [...byModule].sort(([a], [b]) => a.localeCompare(b))) {
            lines.push(`import type { ${names.join(", ")} } from "${WRITE_TYPES_DIR}/${module}";`);
        }
    }
    lines.push(`import { call, type Call } from "../${CLIENT_MODULE}";`);
    if (writeTypes.length > 0) {
        lines.push("");
        lines.push(`export type { ${writeTypes.join(", ")} };`);
    }

    if (query) {
        lines.push("");
        lines.push(comment(entity, "query"));
        lines.push(`export function ${query.id}<S extends Selection<${name}>>(`);
        lines.push(`    opts: ${queryOptsType(name, entity.filters, entity.requiredFilters, entity.orderFields, entity.whereFields)},`);
        lines.push(`): Call<Selected<${name}, S>[]> {`);
        lines.push(
            `    return call<Selected<${name}, S>[]>("${query.id}", "${query.method}", "${query.path}", opts);`,
        );
        lines.push("}");
    }

    if (create) {
        lines.push("");
        lines.push(comment(entity, "create"));
        lines.push(`export function ${create.id}(rows: ${name}Insert[]): Call<${keyType(entity)}[]> {`);
        lines.push(`    return call<${keyType(entity)}[]>("${create.id}", "${create.method}", "${create.path}", rows);`);
        lines.push("}");
    }

    if (upsert) {
        lines.push("");
        lines.push(comment(entity, "upsert"));
        lines.push(`export function ${upsert.id}(rows: ${name}Upsert[]): Call<${keyType(entity)}[]> {`);
        lines.push(`    return call<${keyType(entity)}[]>("${upsert.id}", "${upsert.method}", "${upsert.path}", rows);`);
        lines.push("}");
    }

    if (update) {
        lines.push("");
        lines.push(comment(entity, "update"));
        lines.push(`export function ${update.id}(rows: ${name}Patch[]): Call<void> {`);
        lines.push(`    return call<void>("${update.id}", "${update.method}", "${update.path}", rows);`);
        lines.push("}");
    }
    if (remove) {
        lines.push("");
        lines.push(comment(entity, "delete"));
        lines.push(`export function ${remove.id}(rows: ${keyType(entity)}[]): Call<void> {`);
        lines.push(`    return call<void>("${remove.id}", "${remove.method}", "${remove.path}", rows);`);
        lines.push("}");
    }

    return lines.join("\n") + "\n";
}

/** InvoiceOperations -> invoiceOperations.ts, the module holding that contract's operation builders. */
export function operationModuleName(contract: string): string {
    return `${contract.charAt(0).toLowerCase()}${contract.slice(1)}.ts`;
}

/** The contract as a type a client can name without choosing the context, e.g. `InvoiceOperations<unknown>`. */
function contractType(operation: RestOperationCall): string {
    return operation.contractTypeParameters === 0 ? operation.contract : `${operation.contract}<unknown>`;
}

/** Render one contract's operation builders: one function per `@restOperation`. */
export function renderOperationClientModule(contract: string, operations: RestOperationCall[]): string {
    const lines: string[] = [HEADER];
    const first = operations[0];
    if (first === undefined) {
        return lines.join("\n") + "\n";
    }
    lines.push(`import type { ${contract} } from "${first.contractImport}";`);
    lines.push(`import { call, type Call } from "../${CLIENT_MODULE}";`);

    for (const operation of operations) {
        const signature = `${contractType(operation)}["${operation.id}"]`;
        lines.push("");
        if (operation.description.length > 0) {
            lines.push("/**");
            for (const line of operation.description) {
                lines.push(` * ${line}`);
            }
            lines.push(" */");
        }
        const parameters = operation.hasInput ? `opts: Parameters<${signature}>[1]` : "";
        const result = `Awaited<ReturnType<${signature}>>`;
        lines.push(`export function ${operation.id}(${parameters}): Call<${result}> {`);
        const argument = operation.hasInput ? "opts" : "undefined";
        lines.push(`    return call<${result}>("${operation.id}", "${operation.method}", "${operation.path}", ${argument});`);
        lines.push("}");
    }
    return lines.join("\n") + "\n";
}

/** Render the barrel re-exporting every entity module. */
export function renderClientIndex(model: RestModel): string {
    const lines: string[] = [HEADER];
    for (const entity of model.entities) {
        lines.push(`export * from "./${entity.module}.ts";`);
    }
    for (const contract of contractsOf(model)) {
        lines.push(`export * from "./${operationModuleName(contract)}";`);
    }
    return lines.join("\n") + "\n";
}

/** The contracts the model's operations belong to, in name order. */
function contractsOf(model: RestModel): string[] {
    return [...new Set(model.operations.map((operation) => operation.contract))].sort((a, b) => a.localeCompare(b));
}

/** The operations of one contract, in name order. */
function operationsOf(model: RestModel, contract: string): RestOperationCall[] {
    return model.operations
        .filter((operation) => operation.contract === contract)
        .sort((a, b) => a.id.localeCompare(b.id));
}

/** Render every generated client file, keyed by file name. */
export function generateRestClient(model: RestModel): Map<string, string> {
    const files = new Map<string, string>();
    for (const entity of model.entities) {
        files.set(`${entity.module}.ts`, renderClientModule(entity));
    }
    for (const contract of contractsOf(model)) {
        files.set(operationModuleName(contract), renderOperationClientModule(contract, operationsOf(model, contract)));
    }
    files.set(INDEX_FILE, renderClientIndex(model));
    return files;
}

/** Remove the generated modules the spec no longer declares, so a dropped entity leaves no client module. */
function pruneStale(outDir: string, keep: Set<string>): void {
    for (const entry of readdirSync(outDir, { withFileTypes: true })) {
        if (!entry.isFile() || !entry.name.endsWith(".ts") || keep.has(entry.name)) {
            continue;
        }
        const file = join(outDir, entry.name);
        if (readFileSync(file, "utf8").split("\n", 1)[0] === HEADER) {
            rmSync(file);
        }
    }
}

/** Write the client modules for a parsed spec and return the exit code. */
export function run(spec: SpecModel, argv: readonly string[] = process.argv): number {
    const model = buildRestModel(spec);

    for (const diagnostic of model.diagnostics) {
        console.error(`${diagnostic.filePath}:${diagnostic.line}: ${diagnostic.message}`);
    }
    if (model.diagnostics.length > 0) {
        return 1;
    }

    const outIndex = argv.indexOf("--out");
    const outDir = outIndex === -1 ? DEFAULT_OUT_DIR : argv[outIndex + 1];
    if (!outDir) {
        console.error("--out needs a directory");
        return 1;
    }

    const files = generateRestClient(model);
    for (const [name, content] of files) {
        const target = join(outDir, name);
        mkdirSync(dirname(target), { recursive: true });
        writeFileSync(target, content);
    }
    pruneStale(outDir, new Set(files.keys()));
    console.log(`wrote ${files.size} files to ${outDir}`);
    return 0;
}

if (import.meta.main) {
    process.exitCode = run(loadSpec());
}
